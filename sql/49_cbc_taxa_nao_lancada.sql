   ser mexido (comissao ja calculada). Decisao do Alexandre (27/11): lancar a taxa como SAIDA AVULSA 710 no banco da loja, contabil, classe
   830 / CC 24 (as da 956), contraparte o fornecedor 26184 REDECARD INSTITUICAO DE PAGAMENTO S.A., dentro da conciliacao do deposito:
   entradas 706 - 977 (taxa antecipada, se houver) - 710 (taxa nao lancada) = linha do extrato. Titulo e baixa intocados.
   - Uma 710 por parcela (doc = NF; complemento com NF/parcela); cada uma ligada ao titulo em CCS_TB_GFIN_BXC_LOG_TIT (ACAOM_DESC, valor 0,
     saldo do titulo sem mudanca) -> o Desfazer padrao apaga as acoes e nao mexe no titulo. ESTORNO_X (sql/31) passou a aceitar N movimentos
     criados na mesma conciliacao.
   - Substitui CCS_P_GFIN_CBC_TX1_X / CCS_P_GFIN_CBC_TX1 do sql/48 (P_VALOR da 977 pode ser 0; P_TAXAS novo no fim).
   SO ASCII. Blocos separados por "/".
   ===================================================================================================================== */
MERGE INTO MEGA.CCS_TB_GFIN_PARAM P USING (
  SELECT 'CBC_TX0_EMI_ATE' K, 20260831 V, 'Taxa da Rede nao lancada (710): so vendas emitidas ate esta data (AAAAMMDD)' D FROM DUAL UNION ALL
  SELECT 'CBC_TAXA_AGN', 26184, 'Taxa da Rede nao lancada (710): fornecedor contraparte (REDECARD)' FROM DUAL
) X ON (P.PARAM_ST_CHAVE = X.K)
WHEN NOT MATCHED THEN INSERT (PARAM_ST_CHAVE, PARAM_RE_VALOR, PARAM_ST_DESCRICAO, PARAM_DT_ALTERACAO, PARAM_ST_USU) VALUES (X.K, X.V, X.D, SYSDATE, 'CCS 27/11/2026')
