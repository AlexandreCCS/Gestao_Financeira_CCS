         WHERE L.ORG_TAB_IN_CODIGO = C_ORG_TAB AND L.ORG_PAD_IN_CODIGO = C_ORG_PAD AND L.ORG_IN_CODIGO = P_ORG AND L.ORG_TAU_ST_CODIGO = C_ORG_TAU
           AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND L.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
