    FUNCTION FIL_DA_ORG(P_FIL NUMBER) RETURN BOOLEAN IS W NUMBER;
    BEGIN
        SELECT COUNT(*) INTO W FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.PAI_AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.PAI_AGN_IN_CODIGO = P_ORG AND A.AGN_IN_CODIGO = P_FIL;
        RETURN W > 0;
    END;
    FUNCTION RAIZ(P_FIL NUMBER) RETURN VARCHAR2 IS W VARCHAR2(40);
    BEGIN
        SELECT SUBSTR(REGEXP_REPLACE(MAX(A.AGN_ST_CGC), '[^0-9]', ''), 1, 8) INTO W FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_IN_CODIGO = P_FIL;
        RETURN W;
    END;
BEGIN
    SELECT * INTO L FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = P_LOG;
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := REGEXP_SUBSTR(P_CBAS, '[^,]+', 1, W_N); EXIT WHEN W_ITEM IS NULL;
        CBAS(W_N) := TO_NUMBER(TRIM(W_ITEM));
    END LOOP;
    IF CBAS.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Informe as linhas do extrato do deposito.'); END IF;
    FOR I IN 1 .. CBAS.COUNT LOOP
        BEGIN
            SELECT X.* INTO B FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = CBAS(I) FOR UPDATE NOWAIT;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' do extrato nao existe no Mega.');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' do extrato em uso por outro usuario no Mega.');
        END;
        IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' do extrato ja esta conciliada.'); END IF;
        IF B.ORG_IN_CODIGO <> P_ORG THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' de outra organizacao.'); END IF;
        IF B.CBA_CH_NATUREZA <> 'C' THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' nao e entrada (credito).'); END IF;
        IF NOT REGEXP_LIKE(UPPER(NVL(B.CBA_ST_HISTORICO, ' ')), '^DEP\s+DIN') THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(I) || ' nao e deposito em dinheiro (DEP DIN).'); END IF;
        IF I = 1 THEN W_CTA := B.AGN_IN_CODIGO; W_DATA := TRUNC(B.CBA_DT_DATA); W_HIST1 := B.CBA_ST_HISTORICO;
        ELSIF B.AGN_IN_CODIGO <> W_CTA OR TRUNC(B.CBA_DT_DATA) <> W_DATA THEN RAISE_APPLICATION_ERROR(-20100, 'As linhas precisam ser da mesma conta e do mesmo dia.');
        END IF;
        W_VAL := W_VAL + ROUND(NVL(B.CBA_RE_VALOR, 0), 2);
    END LOOP;
    W_VAL := ROUND(W_VAL, 2); W_QT := CBAS.COUNT;
    IF W_VAL <= 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Deposito sem valor.'); END IF;
    IF W_DATA > TRUNC(SYSDATE) OR W_DATA < TRUNC(SYSDATE) - 90 THEN RAISE_APPLICATION_ERROR(-20100, 'Data do deposito fora da janela (90 dias).'); END IF;
    BEGIN
        SELECT * INTO K FROM MEGA.CCS_TB_GFIN_BXC_CONTA WHERE AGN_IN_CODIGO = W_CTA AND CTA_CH_ATIVA = 'S';
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ' || W_CTA || ' fora do escopo do Baixar e Conciliar.');
    END;
    IF NVL(K.CTA_CH_LOJA, 'N') <> 'S' THEN RAISE_APPLICATION_ERROR(-20100, 'Deposito em dinheiro do dia so em conta de loja.'); END IF;
    IF K.CTA_IN_AGN_DINHEIRO IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ' || W_CTA || ' sem conta de dinheiro configurada (Configuracao).'); END IF;
    W_FIL := K.FIL_IN_CODIGO;
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO INTO W_CTA_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = W_CTA AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
        SELECT C.AGN_PAD_IN_CODIGO INTO W_OUT_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = K.CTA_IN_AGN_DINHEIRO AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira do banco ou do dinheiro nao encontrada.');
    END;
    /* ja lancada (pelo financeiro) e nao conciliada? entao e conciliar, nao lancar */
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_MOVIMENTO M
     WHERE M.ORG_IN_CODIGO = P_ORG AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.AGN_IN_CODIGO = W_CTA AND M.AGN_TAU_ST_CODIGO = 'N' AND M.ACAO_IN_CODIGO = 712
       AND M.MOV_CH_NATUREZA = 'D' AND ABS(M.MOV_RE_VALOR - W_VAL) < 0.005 AND TRUNC(M.MOV_DT_DATADOCTO) = W_DATA
       AND NVL(M.MOV_CH_CONCILIADO, 'N') = 'N' AND NVL(M.MOV_CH_SITUACAO, 'A') <> 'C';
    IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Ja existe transferencia de ' || TO_CHAR(W_VAL, 'FM999G999G990D00') || ' nesta conta neste dia, nao conciliada. Concilie com ela em vez de lancar outra.'); END IF;
    FOR E IN (SELECT X.SIS_DT_ENCERRAMENTO, X.FIL_IN_CODIGO FROM MEGA.GLO_ENCERRASISTEMA X
               WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
                 AND X.FIL_IN_CODIGO = W_FIL AND X.SIS_IN_CODIGO IN (11, 4) AND W_DATA <= X.SIS_DT_ENCERRAMENTO) LOOP
        RAISE_APPLICATION_ERROR(-20100, 'Periodo encerrado no Mega para a empresa ' || E.FIL_IN_CODIGO || ' ate ' || TO_CHAR(E.SIS_DT_ENCERRAMENTO, 'DD/MM/YYYY') || '.');
    END LOOP;
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
    IF W_HUS IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mov. Financeiro do Mega.'); END IF;
    SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_IN_CODIGO = W_CTA;

    FIN_PCK_MOVIMENTO.COMP_ST_NOME := 'MEGA'; FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    W_SEQ := PCK_MEGA.ACHASEQUENCIADATABELA(P_ORG, C_MOV_TAB, W_DATA);
    IF W_SEQ IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Sem sequencia de movimento para ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || '.'); END IF;
    W_ACAOM := PCK_MEGA.PROXIMASEQUENCIATAB(59);
    W_AQUI := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_LA := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_DOC := TO_CHAR(W_AQUI);   /* numerador do Gestor: o proprio lancamento no banco (so digitos) */
    W_HIST := SUBSTR(NVL(K.CTA_ST_COMPL_DINHEIRO, 'TRANSFERENCIA PARA DEPOSITO') || ' - DEP DIN ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || ' (' || CBAS.COUNT || ' deposito(s)) (GESTOR FINANCEIRO)', 1, 500);
    INSERT INTO MEGA.GLO_ACAOMOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, ACAOM_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO,
      ACAOM_ST_DOCUMENTO, ACAOM_DT_DATAEMISSAO, ACAOM_DT_DATAENTRADA, USU_IN_INCLUSAO, USU_IN_ALTERACAO, ACAOM_DT_INCLUSAO, ACAOM_DT_ALTERACAO,
      ACAOM_RE_VALORCONTABIL, ACAOM_RE_VALORCONTABILREAL, ACAOM_RE_VALORFISCAL, ACAOM_RE_VALORFISCALREAL, ACAOM_RE_VALORFINANC, ACAOM_RE_VALORFINANCREAL,
      ACAOM_RE_VALORIMOB, ACAOM_RE_VALORIMOBREAL, CONT_ORG_IN_CODIGO, FIL_IN_CODIGO, LAN_CH_TIPOCONTAB, FORM_IN_ID )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, W_ACAOM, 55, 1, W_ACAO, W_DOC, W_DATA, W_DATA, P_USU, P_USU, SYSDATE, SYSDATE,
      W_VAL, 0, 0, 0, 0, 0, 0, 0, P_ORG, W_FIL, 'S', 14001 );
    /* TRANSFD na conta do dinheiro (W_LA), TRANSFC no banco da loja (W_AQUI) */
    INS_MOV(W_LA, W_FIL, 'TRANSFD', 'C', NULL, W_OUT_PAD, K.CTA_IN_AGN_DINHEIRO, 'N', 'S');
    INS_RATEIO(W_LA, '1', 522, '1', 215, 'D');
    ATUALIZA(W_LA, W_FIL, W_OUT_PAD, K.CTA_IN_AGN_DINHEIRO, 'N', NULL, 'C');
    INS_MOV(W_AQUI, W_FIL, 'TRANSFC', 'D', 'TRANSF', W_CTA_PAD, W_CTA, 'N', 'N');
    INS_REF(W_AQUI, W_LA, W_AQUI, 'TRANSF');
    INS_REF(W_LA, W_AQUI, W_AQUI, 'TRANSFDEST');
    INS_RATEIO(W_AQUI, '1', 523, '1', 215, 'C');
    ATUALIZA(W_AQUI, W_FIL, W_CTA_PAD, W_CTA, 'N', 'TRANSF', 'D');
    CONCILIA_N(W_CTA, W_CTA_PAD, W_FIL, W_DATA, W_AQUI, W_CON);
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG
       SET CTA_AGN_IN_CODIGO = W_CTA, FIL_IN_CODIGO = W_FIL, LOG_DT_BANCO = W_DATA, LOG_RE_VALOR_BANCO = W_VAL, LOG_IN_QT_TITULOS = 0,
           ACAO_IN_CODIGO = W_ACAO, ACAOM_IN_SEQUENCIA = W_ACAOM, MOV_SEQ_IN_CODIGO = W_SEQ, LANCTO_FIN = W_AQUI, LANCTO_CONTRA = W_LA, CON_IN_SEQUENCIAL = W_CON,
           LOG_ST_MOVS = W_AQUI || ',' || W_LA, LOG_ST_DOC_FIN = W_DOC, TPD_FIN_ST_CODIGO = 'TRANSFC',
           EXT_ST_HISTORICO = SUBSTR('DEP DIN ' || TO_CHAR(W_DATA, 'DD/MM') || ': ' || W_QT || ' deposito(s) - ' || W_HIST1, 1, 120)
     WHERE LOG_IN_CODIGO = P_LOG;
END CCS_P_GFIN_BXC_DEPDIN_X;
