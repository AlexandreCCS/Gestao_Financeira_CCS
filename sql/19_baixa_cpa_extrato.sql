CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_ESTORNO_BAIXA (
    P_LOG   IN NUMBER,
    P_USU   IN NUMBER,
    P_LOGIN IN VARCHAR2
) IS
    /* [21/09/2026 - Alexandre Carvalho] O QUE A API CHAMA PARA DESFAZER UMA BAIXA DO GESTOR. RESULTADO NO PROPRIO LOG:
       STATUS VIRA 'E' SE DESFEZ; SE RECUSOU, STATUS CONTINUA 'B' E O MOTIVO FICA EM LOG_ST_MENSAGEM. */
    R MEGA.CCS_TB_GFIN_BAIXA_LOG%ROWTYPE;
    W_MSG VARCHAR2(1500);
BEGIN
    BEGIN
        SELECT * INTO R FROM MEGA.CCS_TB_GFIN_BAIXA_LOG WHERE LOG_IN_CODIGO = P_LOG AND LOG_CH_STATUS = 'B' FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN;
    END;
    SAVEPOINT SP_GFIN_ESTORNO;
    BEGIN
        MEGA.CCS_P_GFIN_ESTORNO_BAIXA_X(R.ORG_IN_CODIGO, R.MOV_SEQ_IN_CODIGO, R.MOV_IN_NUMLANCTO, R.BX_MOV_SEQ_IN_CODIGO,
            R.LANCTO_FIN, R.LANCTO_BX, R.ACAOM_IN_SEQUENCIA, R.LOG_RE_VALOR, R.LOG_RE_SALDO_ANT, R.LOG_CH_ZERADO_ANT, P_USU);
        UPDATE MEGA.CCS_TB_GFIN_BAIXA_LOG
           SET LOG_CH_STATUS = 'E', EST_USU_IN_CODIGO = P_USU, EST_USU_ST_LOGIN = SUBSTR(P_LOGIN, 1, 60), EST_DT = SYSDATE, LOG_ST_MENSAGEM = NULL
         WHERE LOG_IN_CODIGO = P_LOG;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_ESTORNO;
            UPDATE MEGA.CCS_TB_GFIN_BAIXA_LOG SET LOG_ST_MENSAGEM = SUBSTR('ESTORNO RECUSADO: ' || W_MSG, 1, 1500) WHERE LOG_IN_CODIGO = P_LOG;
    END;
    COMMIT;
END CCS_P_GFIN_ESTORNO_BAIXA;
