-- [09/09/2026 - Alexandre Carvalho] Trava de baixa retroativa (V7 vigente) - espelho do fonte vivo
-- em producao OCPDB493. V7: a janela de N dias uteis passa a ser calculada pela funcao nova
-- MEGA.CCS_F_ANTDIAUTIL_N (abaixo, criada antes da trigger), independente do NLS da sessao. A nativa
-- F_ANTDIAUTIL, em sessao portuguesa, avanca para a sexta seguinte quando o feriado cai na segunda
-- (07/09/2026) e o laco antigo ciclava entre 08 e 11/09 bloqueando toda baixa com data anterior ao dia.
-- Backup da V6 em CCS_TB_BKP_TRG_DTBAIXA_09092026. Historico: V1-V5 so em backups CTAS; V6 em 13/08/2026.

CREATE OR REPLACE FUNCTION      CCS_F_ANTDIAUTIL_N
(PDATA IN DATE, PDIAS IN NUMBER, PAGN_PAD_IN_CODIGO IN NUMBER, PAGN_IN_CODIGO IN NUMBER)
RETURN DATE IS
-- [09/09/2026 - ALEXANDRE CARVALHO] CRIADO: DEVOLVE A DATA N DIAS UTEIS ANTES DE PDATA (PDATA NAO CONTA),
-- PULANDO SABADO/DOMINGO E FERIADOS DA GLO_FERIADO (F NACIONAL; E ESTADUAL PELA UF DO AGENTE; R MUNICIPAL
-- PELA UF+MUNICIPIO DO AGENTE). SUBSTITUI O ENCADEAMENTO DE F_ANTDIAUTIL NA CCS_T_DATA_BAIXA: A NATIVA,
-- EM SESSAO COM NLS PORTUGUES, CAI NO RAMO NEXT_DAY(VDATA,'SEXTA') SEM O -4 QUANDO O FERIADO CAI NA SEGUNDA
-- (07/09/2026) E AVANCA PARA A SEXTA SEGUINTE - O LACO DA TRIGGER CICLAVA ENTRE 08 E 11/09 E BLOQUEAVA
-- TODAS AS BAIXAS. DIA DA SEMANA POR TRUNC(D,'IW') (INDEPENDE DE NLS). GUARDA DE 3000 ITERACOES.
  VDATA DATE := TRUNC(PDATA);
  VN    NUMBER := 0;
  VFER  NUMBER;
  VUF   VARCHAR2(2);
  VMUN  NUMBER;
  VDOW  NUMBER;
  VITER NUMBER := 0;
BEGIN
  IF NVL(PDIAS, 0) <= 0 THEN
    RETURN VDATA;
  END IF;
  BEGIN
    SELECT A.UF_ST_SIGLA, A.MUN_IN_CODIGO
      INTO VUF, VMUN
      FROM MEGA.GLO_AGENTES A
     WHERE A.AGN_TAB_IN_CODIGO = 53
       AND A.AGN_PAD_IN_CODIGO = PAGN_PAD_IN_CODIGO
       AND A.AGN_IN_CODIGO     = PAGN_IN_CODIGO
       AND ROWNUM = 1;
  EXCEPTION
    WHEN OTHERS THEN
      VUF := NULL; VMUN := NULL;
  END;
  WHILE VN < PDIAS LOOP
    VDATA := VDATA - 1;
    VITER := VITER + 1;
    IF VITER > 3000 THEN
      RETURN VDATA;
    END IF;
    VDOW := VDATA - TRUNC(VDATA, 'IW'); -- 0=SEGUNDA ... 5=SABADO, 6=DOMINGO
    IF VDOW NOT IN (5, 6) THEN
      SELECT COUNT(*)
        INTO VFER
        FROM MEGA.GLO_FERIADO F
       WHERE TRUNC(F.FER_DT_FERIADO) = VDATA
         AND (F.FER_CH_TIPO = 'F'
              OR (F.FER_CH_TIPO = 'E' AND F.UF_ST_SIGLA = VUF)
              OR (F.FER_CH_TIPO = 'R' AND F.UF_ST_SIGLA = VUF AND F.MUN_IN_CODIGO = VMUN));
      IF VFER = 0 THEN
        VN := VN + 1;
      END IF;
    END IF;
  END LOOP;
  RETURN VDATA;
END;
