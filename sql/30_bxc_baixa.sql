    /* RATEIO HERDADO DO TITULO (classe, centro de custo e projeto), proporcional ao valor baixado, natureza INVERTIDA. */
    PROCEDURE INS_RATEIO_COPIA(P_LANC NUMBER, T MEGA.FIN_MOVIMENTO%ROWTYPE, P_VAL NUMBER) IS
        W_FATOR NUMBER := CASE WHEN NVL(T.MOV_RE_VALOR, 0) = 0 THEN 1 ELSE P_VAL / T.MOV_RE_VALOR END;
        W_SOMA NUMBER;
    BEGIN
        INSERT INTO MEGA.FIN_LANCCLASSE
        ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO,
          CLA_TAB_IN_CODIGO, CLA_PAD_IN_CODIGO, CLA_IDE_ST_CODIGO, CLA_IN_REDUZIDO, LCL_CH_NATUREZA, LCL_RE_PERCENTUAL, LCL_RE_VALOR, LCL_RE_VALORCRE, LCL_RE_VALORDEB,
          LCL_CH_STATUSBXREF, LCL_RE_VALORMOE, LCL_RE_VALORCREMOE, LCL_RE_VALORDEBMOE )
        SELECT C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_LANC,
               L.CLA_TAB_IN_CODIGO, L.CLA_PAD_IN_CODIGO, L.CLA_IDE_ST_CODIGO, L.CLA_IN_REDUZIDO, DECODE(L.LCL_CH_NATUREZA, 'C', 'D', 'C'), L.LCL_RE_PERCENTUAL,
               ROUND(L.LCL_RE_VALOR * W_FATOR, 2), CASE WHEN L.LCL_CH_NATUREZA = 'D' THEN ROUND(L.LCL_RE_VALOR * W_FATOR, 2) ELSE 0 END, CASE WHEN L.LCL_CH_NATUREZA = 'C' THEN ROUND(L.LCL_RE_VALOR * W_FATOR, 2) ELSE 0 END,
               'N', ROUND(L.LCL_RE_VALOR * W_FATOR, 2), CASE WHEN L.LCL_CH_NATUREZA = 'D' THEN ROUND(L.LCL_RE_VALOR * W_FATOR, 2) ELSE 0 END, CASE WHEN L.LCL_CH_NATUREZA = 'C' THEN ROUND(L.LCL_RE_VALOR * W_FATOR, 2) ELSE 0 END
          FROM MEGA.FIN_LANCCLASSE L
         WHERE L.ORG_TAB_IN_CODIGO = C_ORG_TAB AND L.ORG_PAD_IN_CODIGO = C_ORG_PAD AND L.ORG_IN_CODIGO = P_ORG AND L.ORG_TAU_ST_CODIGO = C_ORG_TAU
           AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND L.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || T.MOV_ST_DOCUMENTO || ' sem rateio de classe financeira.'); END IF;
        SELECT SUM(LCL_RE_VALOR) INTO W_SOMA FROM MEGA.FIN_LANCCLASSE WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = W_SEQ AND MOV_IN_NUMLANCTO = P_LANC;
        IF ABS(W_SOMA - P_VAL) >= 0.005 THEN
