           AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND L.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
    END;
    /* CENTRO DE CUSTO DO TITULO (primeira linha) para o rateio dos encargos */
    PROCEDURE CC_TITULO(T MEGA.FIN_MOVIMENTO%ROWTYPE, O_IDE OUT VARCHAR2, O_CC OUT NUMBER) IS
    BEGIN
        SELECT MAX(L.CCF_IDE_ST_CODIGO) KEEP (DENSE_RANK FIRST ORDER BY L.LCC_IN_NUMERO), MAX(L.CCF_IN_REDUZIDO) KEEP (DENSE_RANK FIRST ORDER BY L.LCC_IN_NUMERO)
          INTO O_IDE, O_CC FROM MEGA.FIN_LANCCCUSTO L
         WHERE L.ORG_IN_CODIGO = P_ORG AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND L.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
        IF O_CC IS NULL THEN O_IDE := '9'; O_CC := 2; END IF;
    END;
BEGIN
    IF P_TIPO NOT IN ('P', 'R') THEN RAISE_APPLICATION_ERROR(-20100, 'Tipo invalido (P = pagar, R = receber).'); END IF;
    IF W_DATA IS NULL OR W_DATA > TRUNC(SYSDATE) OR W_DATA < TRUNC(SYSDATE) - 90 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Data do banco fora da janela permitida (de 90 dias atras ate hoje).');
    END IF;
    IF P_DOC_FIN IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Documento do movimento financeiro nao informado.'); END IF;
    W_DOC := SUBSTR(P_DOC_FIN, 1, 30);
    W_JANELA := PAR('BXC_JANELA_DIAS', 5);
    IF W_RECEBER THEN W_ACAO_FIN := 706; W_NAT_FIN := 'D'; W_ORIGEM := 'R'; W_TREF_BX := 'BXCRE'; W_TREF_FIN := 'BXFINCRE'; W_SIS_BX := 13;
    ELSE W_ACAO_FIN := 705; W_NAT_FIN := 'C'; W_ORIGEM := 'P'; W_TREF_BX := 'BXCPA'; W_TREF_FIN := 'BXFINCPA'; W_SIS_BX := 12; END IF;

    /* CONTA FINANCEIRA: cadastrada no Mega e no escopo do Gestor */
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO INTO W_CTA_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = P_CTA AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira ' || P_CTA || ' nao encontrada no Mega.');
    END;
    SELECT COUNT(*) INTO W_N FROM MEGA.CCS_TB_GFIN_BXC_CONTA K WHERE K.AGN_IN_CODIGO = P_CTA AND K.CTA_CH_ATIVA = 'S';
    IF W_N = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ' || P_CTA || ' fora do escopo do Baixar e Conciliar (CCS_TB_GFIN_BXC_CONTA).'); END IF;

    /* HIERARQUIAS DO USUARIO */
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS_FIN FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS_BX FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = W_SIS_BX AND H.GRU_IN_CODIGO = P_USU;
    IF W_HUS_FIN IS NULL OR W_HUS_BX IS NULL THEN
        RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mega (Mov. Financeiro e ' || CASE WHEN W_RECEBER THEN 'Contas a Receber' ELSE 'Contas a Pagar' END || ').');
    END IF;

    /* LINHAS DO EXTRATO: pendentes, da conta, natureza coerente, dentro da janela; soma = dinheiro */
    W_N := 0;
    LOOP
        W_N := W_N + 1;
        W_ITEM := REGEXP_SUBSTR(P_CBAS, '[^,]+', 1, W_N);
        EXIT WHEN W_ITEM IS NULL;
        CBAS(W_N) := TO_NUMBER(TRIM(W_ITEM));
        DECLARE B MEGA.FIN_CONCILIACAO%ROWTYPE;
        BEGIN
            SELECT X.* INTO B FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = CBAS(W_N) FOR UPDATE NOWAIT;
            IF B.AGN_IN_CODIGO <> P_CTA THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato e de outra conta (' || B.AGN_IN_CODIGO || ').'); END IF;
            IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato ja esta conciliada no Mega.'); END IF;
            IF (W_RECEBER AND B.CBA_CH_NATUREZA <> 'C') OR (NOT W_RECEBER AND B.CBA_CH_NATUREZA <> 'D') THEN
                RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato e ' || CASE WHEN B.CBA_CH_NATUREZA = 'D' THEN 'saida' ELSE 'entrada' END || ', incompativel com ' || CASE WHEN W_RECEBER THEN 'recebimento' ELSE 'pagamento' END || '.');
            END IF;
            IF ABS(TRUNC(B.CBA_DT_DATA) - W_DATA) > W_JANELA THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato (' || TO_CHAR(B.CBA_DT_DATA, 'DD/MM/YYYY') || ') longe da data da baixa.'); END IF;
            W_BANCO := W_BANCO + NVL(B.CBA_RE_VALOR, 0);
            W_MAIOR := GREATEST(NVL(W_MAIOR, TRUNC(B.CBA_DT_DATA)), TRUNC(B.CBA_DT_DATA));
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato nao existe no Mega (foi importada?).');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato em uso por outro usuario no Mega.');
        END;
    END LOOP;
    IF CBAS.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Nenhuma linha do extrato informada: a baixa nasce do extrato.'); END IF;

    /* TITULOS */
    W_N := 0;
    LOOP
        W_N := W_N + 1;
        W_ITEM := REGEXP_SUBSTR(P_TITULOS, '[^;]+', 1, W_N);
        EXIT WHEN W_ITEM IS NULL;
        IF W_N > 30 THEN RAISE_APPLICATION_ERROR(-20100, 'Mais de 30 titulos numa so baixa.'); END IF;
        DECLARE
            I PLS_INTEGER := W_N; R R_TIT; T MEGA.FIN_MOVIMENTO%ROWTYPE; W_DOCT VARCHAR2(60); W_EXISTE NUMBER;
        BEGIN
            R.SEQ := TO_NUMBER(CAMPO(W_ITEM, 1)); R.LANC := TO_NUMBER(CAMPO(W_ITEM, 2));
            R.VALOR := NUM(CAMPO(W_ITEM, 3)); R.JUROS := NUM(CAMPO(W_ITEM, 4)); R.MULTA := NUM(CAMPO(W_ITEM, 5)); R.DESCO := NUM(CAMPO(W_ITEM, 6));
            IF R.VALOR <= 0 OR R.JUROS < 0 OR R.MULTA < 0 OR R.DESCO < 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Valores invalidos no titulo ' || R.LANC || '.'); END IF;
            IF NOT W_RECEBER AND R.MULTA > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Multa em contas a pagar: lance como juros.'); END IF;
            BEGIN
                SELECT M.* INTO T FROM MEGA.FIN_MOVIMENTO M
                 WHERE M.ORG_TAB_IN_CODIGO = C_ORG_TAB AND M.ORG_PAD_IN_CODIGO = C_ORG_PAD AND M.ORG_IN_CODIGO = P_ORG AND M.ORG_TAU_ST_CODIGO = C_ORG_TAU
                   AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = R.SEQ AND M.MOV_IN_NUMLANCTO = R.LANC
                   FOR UPDATE NOWAIT;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || R.LANC || ' nao encontrado no Mega.');
                WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || R.LANC || ' em uso por outro usuario no Mega. Tente de novo em instantes.');
            END;
            W_DOCT := T.MOV_ST_DOCUMENTO || '/' || T.MOV_ST_PARCELA;
            IF T.MOV_CH_ORIGEM <> W_ORIGEM OR T.TREF_ST_CODIGO IS NOT NULL OR T.MOV_CH_NATUREZA <> W_NAT_FIN THEN
                RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || W_DOCT || ' nao e um titulo ' || CASE WHEN W_RECEBER THEN 'a receber' ELSE 'a pagar' END || '.');
            END IF;
            IF W_RECEBER THEN
                SELECT COUNT(*), MAX(NVL(C.CRE_RE_VRJUROSBAIXA, 0)) INTO W_EXISTE, R.JURBX_ANT FROM MEGA.FIN_CONTASRECEBER C
                 WHERE C.ORG_IN_CODIGO = P_ORG AND C.MOV_TAB_IN_CODIGO = C_MOV_TAB AND C.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND C.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
            ELSE
                SELECT COUNT(*), MAX(NVL(C.CPA_RE_VRJUROSBAIXA, 0)) INTO W_EXISTE, R.JURBX_ANT FROM MEGA.FIN_CONTASPAGAR C
                 WHERE C.ORG_IN_CODIGO = P_ORG AND C.MOV_TAB_IN_CODIGO = C_MOV_TAB AND C.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND C.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
            END IF;
            R.T := T;
            TITS(I) := R;
            IF W_EXISTE = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' sem registro no ' || CASE WHEN W_RECEBER THEN 'Contas a Receber' ELSE 'Contas a Pagar' END || '.'); END IF;
            IF NVL(T.MOV_BO_PREVISAO, 'N') <> 'N' THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' e de previsao.'); END IF;
            IF NVL(T.MOV_CH_STATUSMOV, 'A') <> 'A' OR NVL(T.MOV_CH_SITUACAO, 'N') = 'C' THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' cancelado ou inativo.'); END IF;
            IF NOT W_RECEBER AND NVL(T.MOV_BO_APROVADOADM, 'N') <> 'S' THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' ainda nao aprovado para pagamento.'); END IF;
            IF NOT W_RECEBER AND NVL(T.MOV_ST_HBKSTATUS, 'NO') <> 'NO' THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' esta em remessa eletronica (' || T.MOV_ST_HBKSTATUS || '): a baixa vem pelo retorno.'); END IF;
            IF NVL(T.MOV_RE_SALDOCPACRE, 0) <= 0 OR NVL(T.MOV_BO_SALDOZERADO, 'N') = 'S' THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ' ja esta baixado.'); END IF;
            IF TITS(I).VALOR + TITS(I).DESCO > NVL(T.MOV_RE_SALDOCPACRE, 0) + 0.005 THEN
                RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || W_DOCT || ': valor + desconto (' || TO_CHAR(TITS(I).VALOR + TITS(I).DESCO, 'FM999G999G990D00') || ') maior que o saldo (' || TO_CHAR(T.MOV_RE_SALDOCPACRE, 'FM999G999G990D00') || ').');
            END IF;
            FOR E IN (SELECT X.SIS_IN_CODIGO, X.SIS_DT_ENCERRAMENTO FROM MEGA.GLO_ENCERRASISTEMA X
                       WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
                         AND X.FIL_IN_CODIGO = T.FIL_IN_CODIGO AND X.SIS_IN_CODIGO IN (11, 4) AND W_DATA <= X.SIS_DT_ENCERRAMENTO) LOOP
                RAISE_APPLICATION_ERROR(-20100, 'Periodo encerrado no Mega para a empresa ' || T.FIL_IN_CODIGO || ' ate ' || TO_CHAR(E.SIS_DT_ENCERRAMENTO, 'DD/MM/YYYY') || CASE WHEN E.SIS_IN_CODIGO = 4 THEN ' (Contabilidade).' ELSE ' (Financeiro).' END);
            END LOOP;
            BEGIN
                SELECT A.ACAO_BAIXA_IN_CODIGO INTO TITS(I).ACAO_BX FROM MEGA.GLO_ACAO A
                 WHERE A.ACAO_TAB_IN_CODIGO = T.ACAO_TAB_IN_CODIGO AND A.ACAO_PAD_IN_CODIGO = T.ACAO_PAD_IN_CODIGO AND A.ACAO_IN_CODIGO = T.ACAO_IN_CODIGO;
            EXCEPTION WHEN NO_DATA_FOUND THEN TITS(I).ACAO_BX := NULL;
            END;
            IF TITS(I).ACAO_BX IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Acao do titulo ' || W_DOCT || ' (' || T.ACAO_IN_CODIGO || ') sem acao de baixa configurada no Mega.'); END IF;
            IF W_FIL IS NULL THEN W_FIL := T.FIL_IN_CODIGO; END IF;
            /* dinheiro que saiu/entrou no banco = principal + juros + multa; o desconto so reduz o titulo (titulo quita VALOR + DESCO) */
            W_TOTAL := W_TOTAL + TITS(I).VALOR + TITS(I).JUROS + TITS(I).MULTA;
            W_TOT_TIT := W_TOT_TIT + TITS(I).VALOR; W_TOT_JUR := W_TOT_JUR + TITS(I).JUROS; W_TOT_MUL := W_TOT_MUL + TITS(I).MULTA; W_TOT_DESC := W_TOT_DESC + TITS(I).DESCO;
        END;
    END LOOP;
    IF TITS.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Nenhum titulo informado.'); END IF;
    IF ABS(W_TOTAL - W_BANCO) >= 0.005 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Soma dos titulos (' || TO_CHAR(W_TOTAL, 'FM999G999G990D00') || ') diferente do valor do banco (' || TO_CHAR(W_BANCO, 'FM999G999G990D00') || ').');
    END IF;
    IF W_TOTAL <= 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Valor da baixa precisa ser maior que zero.'); END IF;

    /* NUMERACAO E CABECALHO */
    FIN_PCK_MOVIMENTO.COMP_ST_NOME := 'MEGA'; FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    W_SEQ := PCK_MEGA.ACHASEQUENCIADATABELA(P_ORG, C_MOV_TAB, W_DATA);
    IF W_SEQ IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Sem sequencia de movimento para ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || ' (periodo fechado?).'); END IF;
    W_ACAOM := PCK_MEGA.PROXIMASEQUENCIATAB(59);
    W_FIN := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_HIST := SUBSTR(NVL(P_HIST, CASE WHEN W_RECEBER THEN 'RECEBIMENTO' ELSE 'PAGAMENTO' END || ' PELO EXTRATO (GESTOR FINANCEIRO)'), 1, 500);
    SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A
     WHERE A.AGN_TAB_IN_CODIGO = TITS(1).T.AGN_TAB_IN_CODIGO AND A.AGN_PAD_IN_CODIGO = TITS(1).T.AGN_PAD_IN_CODIGO AND A.AGN_IN_CODIGO = TITS(1).T.AGN_IN_CODIGO;
    IF TITS.COUNT > 1 THEN W_NOME := SUBSTR('DIVERSOS - ' || W_NOME, 1, 100); END IF;
    INSERT INTO MEGA.GLO_ACAOMOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, ACAOM_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO,
      ACAOM_ST_DOCUMENTO, ACAOM_DT_DATAEMISSAO, ACAOM_DT_DATAENTRADA, USU_IN_INCLUSAO, USU_IN_ALTERACAO, ACAOM_DT_INCLUSAO, ACAOM_DT_ALTERACAO,
      ACAOM_RE_VALORCONTABIL, ACAOM_RE_VALORCONTABILREAL, ACAOM_RE_VALORFISCAL, ACAOM_RE_VALORFISCALREAL, ACAOM_RE_VALORFINANC, ACAOM_RE_VALORFINANCREAL,
      ACAOM_RE_VALORIMOB, ACAOM_RE_VALORIMOBREAL, CONT_ORG_IN_CODIGO, FIL_IN_CODIGO, LAN_CH_TIPOCONTAB, FORM_IN_ID )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, W_ACAOM, 55, 1, W_ACAO_FIN,
      W_DOC, W_DATA, W_DATA, P_USU, P_USU, SYSDATE, SYSDATE,
      W_TOT_TIT + W_TOT_JUR + W_TOT_MUL, 0, 0, 0, W_TOT_TIT + W_TOT_JUR + W_TOT_MUL, 0,
      0, 0, P_ORG, W_FIL, 'S', 14001 );

    /* MOV FIN (dinheiro na conta) */
    INS_MOV(W_FIN, P_TPD_FIN, W_ACAO_FIN, W_NAT_FIN, 'M', NULL, C_ORG_TAB, W_CTA_PAD, P_CTA, 'N', W_TOTAL, W_DOC, NULL, 'S', W_FIL, W_HUS_FIN, 'N', 0, 'S');
    INSERT INTO MEGA.FIN_MOVFIN ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO, TPD_ST_CODIGO, MVF_ST_NUMERODOC, MVF_ST_NOMINAL, MVF_BO_IMPRESSO )
    VALUES ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, W_FIN, P_TPD_FIN, W_DOC, W_NOME, 'N' );
    INS_RATEIO_FIXO(W_FIN, '9', 2, '9', 2, CASE WHEN W_RECEBER THEN 'C' ELSE 'D' END, W_TOTAL);
    ATUALIZA(W_SEQ, W_FIN, W_FIL, C_ORG_TAB, W_CTA_PAD, P_CTA, 'N', NULL, 'M', W_NAT_FIN, W_TOTAL);

    /* UM BLOCO POR TITULO */
    FOR I IN 1 .. TITS.COUNT LOOP
        DECLARE
            T MEGA.FIN_MOVIMENTO%ROWTYPE := TITS(I).T;
            W_BX NUMBER; W_J1 NUMBER; W_J2 NUMBER; W_M1 NUMBER; W_M2 NUMBER; W_D1 NUMBER;
            W_NAT_BX VARCHAR2(1) := CASE WHEN W_RECEBER THEN 'C' ELSE 'D' END;
            W_NAT_TI VARCHAR2(1) := CASE WHEN W_RECEBER THEN 'D' ELSE 'C' END;
            W_TPD_BX VARCHAR2(10) := CASE WHEN W_RECEBER THEN 'CREDITO' ELSE 'DEBITO' END;
            W_TPD_TI VARCHAR2(10) := CASE WHEN W_RECEBER THEN 'DEBITO' ELSE 'CREDITO' END;
            W_LNAT_T VARCHAR2(1) := CASE WHEN W_RECEBER THEN 'C' ELSE 'D' END;
            W_LNAT_B VARCHAR2(1) := CASE WHEN W_RECEBER THEN 'D' ELSE 'C' END;
            W_CCIDE VARCHAR2(3); W_CC NUMBER; W_CLA NUMBER; W_SALDO_NOVO NUMBER;
        BEGIN
            CC_TITULO(T, W_CCIDE, W_CC);
            W_BX := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
            INS_MOV(W_BX, W_TPD_BX, TITS(I).ACAO_BX, W_NAT_BX, W_ORIGEM, W_TREF_BX, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                    TITS(I).VALOR, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'N', TITS(I).VALOR, 'N');
            INS_REF(W_TREF_BX, W_SEQ, W_BX, W_SEQ, W_FIN, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
            INS_REF(W_TREF_FIN, W_SEQ, W_BX, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, W_SEQ, W_FIN);
            INS_RATEIO_COPIA(W_BX, T, TITS(I).VALOR);
            ATUALIZA(W_SEQ, W_BX, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, W_TREF_BX, W_ORIGEM, W_NAT_BX, TITS(I).VALOR);

            IF TITS(I).JUROS > 0 THEN
                W_CLA := PAR(CASE WHEN W_RECEBER THEN 'BXC_CLA_CR_JUROS' ELSE 'BXC_CLA_CP_JUROS' END, CASE WHEN W_RECEBER THEN 68 ELSE 627 END);
                W_J1 := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
                INS_MOV(W_J1, W_TPD_TI, TITS(I).ACAO_BX, W_NAT_TI, W_ORIGEM, 'JUROS', T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                        TITS(I).JUROS, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'S', 0, 'N');
                INS_REF('JUROS', W_SEQ, W_J1, W_SEQ, W_FIN, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
                INS_RATEIO_FIXO(W_J1, '1', W_CLA, W_CCIDE, W_CC, W_LNAT_T, TITS(I).JUROS);
                ATUALIZA(W_SEQ, W_J1, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, 'JUROS', W_ORIGEM, W_NAT_TI, TITS(I).JUROS);
                W_J2 := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
                INS_MOV(W_J2, W_TPD_BX, TITS(I).ACAO_BX, W_NAT_BX, W_ORIGEM, 'BXJUROS', T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                        TITS(I).JUROS, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'N', TITS(I).JUROS, 'N');
                INS_REF(W_TREF_BX, W_SEQ, W_J2, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, W_SEQ, W_J1);
                INS_REF(W_TREF_FIN, W_SEQ, W_J2, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, W_SEQ, W_FIN);
                INS_REF('BXJUROS', W_SEQ, W_J2, W_SEQ, W_J1, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
                INS_RATEIO_FIXO(W_J2, '1', W_CLA, W_CCIDE, W_CC, W_LNAT_B, TITS(I).JUROS);
                ATUALIZA(W_SEQ, W_J2, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, 'BXJUROS', W_ORIGEM, W_NAT_BX, TITS(I).JUROS);
                IF W_RECEBER THEN
                    UPDATE MEGA.FIN_CONTASRECEBER SET CRE_RE_VRJUROSBAIXA = NVL(CRE_RE_VRJUROSBAIXA, 0) + TITS(I).JUROS
                     WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
                ELSE
                    UPDATE MEGA.FIN_CONTASPAGAR SET CPA_RE_VRJUROSBAIXA = NVL(CPA_RE_VRJUROSBAIXA, 0) + TITS(I).JUROS
                     WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
                END IF;
            END IF;

            IF TITS(I).MULTA > 0 THEN
                W_CLA := PAR('BXC_CLA_CR_MULTA', 68);
                W_M1 := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
                INS_MOV(W_M1, W_TPD_TI, TITS(I).ACAO_BX, W_NAT_TI, W_ORIGEM, 'MULTA', T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                        TITS(I).MULTA, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'S', 0, 'N');
                INS_REF('MULTA', W_SEQ, W_M1, W_SEQ, W_FIN, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
                INS_RATEIO_FIXO(W_M1, '1', W_CLA, W_CCIDE, W_CC, W_LNAT_T, TITS(I).MULTA);
                ATUALIZA(W_SEQ, W_M1, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, 'MULTA', W_ORIGEM, W_NAT_TI, TITS(I).MULTA);
                W_M2 := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
                INS_MOV(W_M2, W_TPD_BX, TITS(I).ACAO_BX, W_NAT_BX, W_ORIGEM, 'BXMULTA', T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                        TITS(I).MULTA, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'N', TITS(I).MULTA, 'N');
                INS_REF(W_TREF_BX, W_SEQ, W_M2, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, W_SEQ, W_M1);
                INS_REF(W_TREF_FIN, W_SEQ, W_M2, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, W_SEQ, W_FIN);
                INS_REF('BXMULTA', W_SEQ, W_M2, W_SEQ, W_M1, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
                INS_RATEIO_FIXO(W_M2, '1', W_CLA, W_CCIDE, W_CC, W_LNAT_B, TITS(I).MULTA);
                ATUALIZA(W_SEQ, W_M2, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, 'BXMULTA', W_ORIGEM, W_NAT_BX, TITS(I).MULTA);
            END IF;

            IF TITS(I).DESCO > 0 THEN
                W_CLA := PAR(CASE WHEN W_RECEBER THEN 'BXC_CLA_CR_DESC' ELSE 'BXC_CLA_CP_DESC' END, CASE WHEN W_RECEBER THEN 468 ELSE 566 END);
                W_D1 := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
                INS_MOV(W_D1, W_TPD_BX, TITS(I).ACAO_BX, W_NAT_BX, W_ORIGEM, 'DESC', T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO,
                        TITS(I).DESCO, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, NVL(T.MOV_CH_SONUMEROS, 'S'), T.FIL_IN_CODIGO, W_HUS_BX, 'N', TITS(I).DESCO, 'N');
                INS_REF('DESC', W_SEQ, W_D1, W_SEQ, W_FIN, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO);
                INS_RATEIO_FIXO(W_D1, '1', W_CLA, W_CCIDE, W_CC, W_LNAT_B, TITS(I).DESCO);
                ATUALIZA(W_SEQ, W_D1, T.FIL_IN_CODIGO, T.AGN_TAB_IN_CODIGO, T.AGN_PAD_IN_CODIGO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, 'DESC', W_ORIGEM, W_NAT_BX, TITS(I).DESCO);
            END IF;

            /* SALDO DO TITULO */
            W_SALDO_NOVO := ROUND(NVL(T.MOV_RE_SALDOCPACRE, 0) - TITS(I).VALOR - TITS(I).DESCO, 2);
            IF ABS(W_SALDO_NOVO) < 0.005 THEN W_SALDO_NOVO := 0; END IF;
            UPDATE MEGA.FIN_MOVIMENTO SET MOV_RE_SALDOCPACRE = W_SALDO_NOVO, MOV_BO_SALDOZERADO = CASE WHEN W_SALDO_NOVO = 0 THEN 'S' ELSE 'N' END
             WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
               AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
            IF SQL%ROWCOUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20100, 'Falha ao atualizar o saldo do titulo ' || T.MOV_ST_DOCUMENTO || '.'); END IF;

            INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG_TIT
            ( LGT_IN_CODIGO, LOG_IN_CODIGO, ORG_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO, MOV_ST_DOCUMENTO, MOV_ST_PARCELA, FIL_IN_CODIGO,
              LGT_RE_SALDO_ANT, LGT_CH_ZERADO_ANT, LGT_RE_JURBX_ANT, LGT_RE_VALOR, LGT_RE_JUROS, LGT_RE_MULTA, LGT_RE_DESCONTO, ACAO_BX_IN_CODIGO,
              LANCTO_BX, LANCTO_JUR_TIT, LANCTO_JUR_BX, LANCTO_MUL_TIT, LANCTO_MUL_BX, LANCTO_DESC )
            VALUES
            ( MEGA.CCS_SEQ_GFIN_BXC_LOG_TIT.NEXTVAL, P_LOG, P_ORG, T.MOV_SEQ_IN_CODIGO, T.MOV_IN_NUMLANCTO, T.AGN_IN_CODIGO, T.AGN_TAU_ST_CODIGO, T.MOV_ST_DOCUMENTO, T.MOV_ST_PARCELA, T.FIL_IN_CODIGO,
              NVL(T.MOV_RE_SALDOCPACRE, 0), NVL(T.MOV_BO_SALDOZERADO, 'N'), TITS(I).JURBX_ANT, TITS(I).VALOR, TITS(I).JUROS, TITS(I).MULTA, TITS(I).DESCO, TITS(I).ACAO_BX,
              W_BX, W_J1, W_J2, W_M1, W_M2, W_D1 );
        END;
    END LOOP;

    /* CONCILIACAO: o mov FIN nasce conciliado com as linhas do extrato (mesmo teste de periodo da tela do Mega) */
    BEGIN
        MEGA.FIN_PCK_CONCILIACAOBANC.P_VALIDACONCILIACAO(P_ORG, W_FIL, LEAST(W_MAIOR, W_DATA));
    EXCEPTION WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20100, 'Periodo de conciliacao encerrado no Mega para a empresa ' || W_FIL || '.');
    END;
    SELECT MEGA.FIN_SEQ_CONCILIACAO.NEXTVAL INTO W_CON FROM DUAL;
    INSERT INTO MEGA.FIN_CONCILIAMOVIMENTO
    ( CON_IN_SEQUENCIAL, ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO,
      CON_CH_TIPO, CON_DT_CONCILIACAO, CON_DT_MAIORDATA, USU_IN_CODIGO, CON_RE_VALOR )
    VALUES
    ( W_CON, C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_ORG_TAB, W_CTA_PAD, P_CTA, 'N', 'A', SYSDATE, GREATEST(W_MAIOR, W_DATA), P_USU, W_TOTAL );
    UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'S', CON_IN_SEQUENCIAL = W_CON
     WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = W_SEQ AND MOV_IN_NUMLANCTO = W_FIN;
    FOR I IN 1 .. CBAS.COUNT LOOP
        UPDATE MEGA.FIN_CONCILIACAO SET CBA_CH_STATUS = 'S', CON_IN_SEQUENCIAL = W_CON WHERE CBA_IN_SEQUENCIA = CBAS(I);
        IF SQL%ROWCOUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20100, 'Falha ao conciliar a linha ' || CBAS(I) || ' do extrato.'); END IF;
    END LOOP;

    W_N := TITS.COUNT;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG
       SET FIL_IN_CODIGO = W_FIL, LOG_RE_VALOR_BANCO = W_BANCO, LOG_RE_VALOR_TITULOS = W_TOT_TIT, LOG_RE_JUROS = W_TOT_JUR, LOG_RE_MULTA = W_TOT_MUL, LOG_RE_DESCONTO = W_TOT_DESC,
           LOG_IN_QT_TITULOS = W_N, ACAO_IN_CODIGO = W_ACAO_FIN, ACAOM_IN_SEQUENCIA = W_ACAOM, MOV_SEQ_IN_CODIGO = W_SEQ, LANCTO_FIN = W_FIN, CON_IN_SEQUENCIAL = W_CON,
           LOG_ST_MOVS = SUBSTR(W_MOVS, 1, 2000), LOG_ST_DOC_FIN = W_DOC, TPD_FIN_ST_CODIGO = P_TPD_FIN
     WHERE LOG_IN_CODIGO = P_LOG;
END CCS_P_GFIN_BXC_X;
