-- [13/08/2026 - ALEXANDRE CARVALHO] MEMORIA DE TRANSACAO DA LIBERACAO DE EXC/ALT
CREATE OR REPLACE PACKAGE MEGA.CCS_PKG_LIBERA_EXC_ALT AS
  -- [13/08/2026 - ALEXANDRE CARVALHO] MEMORIA DE TRANSACAO DA LIBERACAO DE EXC/ALT:
  -- UMA LIBERACAO VALE PARA A OPERACAO (TRANSACAO) INTEIRA SOBRE O TITULO, NAO POR
  -- VINCULO BXCRE. BAIXA COM JUROS/DESCONTO GERA 2+ VINCULOS DO MESMO TITULO E A
  -- TRIGGER CCS_T_LIBERA_EXC_ALT_REF DISPARA UMA VEZ POR VINCULO - SEM ESTA MEMORIA
  -- O SEGUNDO DISPARO NAO ACHAVA LIBERACAO ATIVA E O ESTORNO ERA IMPOSSIVEL (CASO
  -- DEPR 19566090 / TITULO 16701-003 AGN 25051 FIL 700 EM 13/08/2026).
  -- O MAPA E LIMPO QUANDO A TRANSACAO MUDA (DBMS_TRANSACTION.LOCAL_TRANSACTION_ID),
  -- ENTAO ROLLBACK INVALIDA O CONSUMO REGISTRADO (COERENTE: O UPDATE A->E TAMBEM VOLTA).
  FUNCTION F_LIB_DA_TRANSACAO(pFIL NUMBER, pAGN NUMBER, pDOC VARCHAR2, pPARC VARCHAR2) RETURN NUMBER;
  PROCEDURE P_REGISTRA_CONSUMO(pFIL NUMBER, pAGN NUMBER, pDOC VARCHAR2, pPARC VARCHAR2, pLIB NUMBER);
END CCS_PKG_LIBERA_EXC_ALT;
/

CREATE OR REPLACE PACKAGE BODY MEGA.CCS_PKG_LIBERA_EXC_ALT AS
  -- [13/08/2026 - ALEXANDRE CARVALHO] ESTADO DE SESSAO: MAPA TITULO->LIB CONSUMIDA +
  -- ID DA TRANSACAO DONA DO MAPA. TRANSACAO NOVA (OU POS COMMIT/ROLLBACK) ZERA O MAPA.
  TYPE T_MAP IS TABLE OF NUMBER INDEX BY VARCHAR2(120);
  vMAP T_MAP;
  vTXN VARCHAR2(100) := '#NENHUMA#';

  FUNCTION F_CHAVE(pFIL NUMBER, pAGN NUMBER, pDOC VARCHAR2, pPARC VARCHAR2) RETURN VARCHAR2 IS
  BEGIN
    RETURN TO_CHAR(pFIL) || '|' || TO_CHAR(pAGN) || '|' || pDOC || '|' || NVL(pPARC, '~');
  END F_CHAVE;

  PROCEDURE P_SINCRONIZA_TXN IS
    vATUAL VARCHAR2(100);
  BEGIN
    vATUAL := NVL(DBMS_TRANSACTION.LOCAL_TRANSACTION_ID, '#NULA#');
    IF vATUAL <> vTXN THEN
      vMAP.DELETE;
      vTXN := vATUAL;
    END IF;
  END P_SINCRONIZA_TXN;

  FUNCTION F_LIB_DA_TRANSACAO(pFIL NUMBER, pAGN NUMBER, pDOC VARCHAR2, pPARC VARCHAR2) RETURN NUMBER IS
    vK VARCHAR2(120);
  BEGIN
    P_SINCRONIZA_TXN;
    vK := F_CHAVE(pFIL, pAGN, pDOC, pPARC);
    IF vMAP.EXISTS(vK) THEN
      RETURN vMAP(vK);
    END IF;
    RETURN NULL;
  END F_LIB_DA_TRANSACAO;

  PROCEDURE P_REGISTRA_CONSUMO(pFIL NUMBER, pAGN NUMBER, pDOC VARCHAR2, pPARC VARCHAR2, pLIB NUMBER) IS
  BEGIN
    P_SINCRONIZA_TXN;
    vMAP(F_CHAVE(pFIL, pAGN, pDOC, pPARC)) := pLIB;
  END P_REGISTRA_CONSUMO;
END CCS_PKG_LIBERA_EXC_ALT;
