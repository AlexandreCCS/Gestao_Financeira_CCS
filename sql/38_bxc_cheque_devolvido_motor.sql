CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_CHDEV (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_CBA     IN NUMBER,
    P_CUS     IN NUMBER,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_ORIGEM  IN VARCHAR2 DEFAULT 'T',
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [03/11/2026 - Alexandre Carvalho] O QUE A API CHAMA PARA "TRATAR DEVOLUCAO". 971 (REAL_X com o de-para CHRD, classe/CC dos parametros)
       + parte do cheque (CHDEV_X) numa transacao. Log tipo 'A' (o Desfazer padrao desfaz a 971 e o status do cheque). B / S / X no log. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500); W_DEP NUMBER; W_CLA NUMBER; W_CC NUMBER; W_ACAO NUMBER; W_HIST VARCHAR2(500); W_N NUMBER;
BEGIN
    IF NVL(P_ORIGEM, 'T') NOT IN ('T', 'R') THEN RAISE_APPLICATION_ERROR(-20100, 'Origem invalida.'); END IF;
    SELECT MAX(DEP_IN_CODIGO) INTO W_DEP FROM MEGA.CCS_TB_GFIN_BXC_DEPARA WHERE TPD_ST_CODIGO = 'CHRD' AND ACAO_IN_CODIGO = 971;
    SELECT MAX(DECODE(PARAM_ST_CHAVE, 'BXC_CHD_CLASSE', PARAM_RE_VALOR)), MAX(DECODE(PARAM_ST_CHAVE, 'BXC_CHD_CCUSTO', PARAM_RE_VALOR)), MAX(DECODE(PARAM_ST_CHAVE, 'BXC_CHD_ACAO', PARAM_RE_VALOR))
      INTO W_CLA, W_CC, W_ACAO FROM MEGA.CCS_TB_GFIN_PARAM WHERE PARAM_ST_CHAVE IN ('BXC_CHD_CLASSE', 'BXC_CHD_CCUSTO', 'BXC_CHD_ACAO');
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, LOG_ST_CBAS, DEP_IN_CODIGO, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO )
    VALUES ( W_LOG, P_TOKEN, 'A', 'X', NVL(P_ORIGEM, 'T'), P_ORG, TO_CHAR(P_CBA), W_DEP, P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE );
    SAVEPOINT SP_GFIN_BXC_CHDEV;
    BEGIN
        IF W_DEP IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'De-para CHRD/971 nao encontrado (sql/38).'); END IF;
        IF NVL(W_ACAO, 971) <> 971 THEN RAISE_APPLICATION_ERROR(-20100, 'BXC_CHD_ACAO precisa ser 971 (a unica acao de devolucao com pegada mapeada).'); END IF;
        IF NVL(W_CLA, 0) <= 0 OR NVL(W_CC, 0) <= 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Informe a classe e o centro de custo do cheque devolvido em Baixar e conciliar > Configurar.'); END IF;
        /* o de-para segue os parametros da secao Cheque recebido devolvido */
        UPDATE MEGA.CCS_TB_GFIN_BXC_DEPARA SET CLA_IDE_ST_CODIGO = '1', CLA_IN_REDUZIDO = W_CLA, CCF_IDE_ST_CODIGO = '1', CCF_IN_REDUZIDO = W_CC, DEP_CH_ATIVO = 'S'
         WHERE DEP_IN_CODIGO = W_DEP AND (NVL(CLA_IN_REDUZIDO, -1) <> W_CLA OR NVL(CCF_IN_REDUZIDO, -1) <> W_CC OR DEP_CH_ATIVO <> 'S');
        SELECT 'CHEQUE DEVOLVIDO ' || NVL(REGEXP_SUBSTR(B.CBA_ST_HISTORICO, '[0-9]{3} [0-9]+ [0-9]+$'), B.CBA_ST_HISTORICO) || ' - '
               || (SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 60) FROM MEGA.CUS_FIN_CHEQUESCRE C, MEGA.GLO_AGENTES A WHERE C.CUS_IN_SEQUENCIA = P_CUS AND A.AGN_TAB_IN_CODIGO = 53 AND A.AGN_IN_CODIGO = C.AGN_IN_CODIGO)
               || ' (GESTOR FINANCEIRO)'
          INTO W_HIST FROM MEGA.FIN_CONCILIACAO B WHERE B.CBA_IN_SEQUENCIA = P_CBA;
        MEGA.CCS_P_GFIN_BXC_REAL_X(W_LOG, P_ORG, P_CBA, W_DEP, P_USU, W_HIST);
        MEGA.CCS_P_GFIN_BXC_CHDEV_X(W_LOG, P_CBA, P_CUS, P_USU);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            SELECT NVL(LOG_ST_MENSAGEM, 'Simulacao sem erro') || '. Nada foi gravado.' INTO W_MSG FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = W_LOG;
            ROLLBACK TO SP_GFIN_BXC_CHDEV; W_ST := 'S';
        ELSE
            SELECT LOG_ST_MENSAGEM INTO W_MSG FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = W_LOG;
            W_ST := 'B';
        END IF;
    EXCEPTION
        WHEN OTHERS THEN W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500); ROLLBACK TO SP_GFIN_BXC_CHDEV; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_BXC_CHDEV;
