CREATE OR REPLACE TRIGGER MEGA.CCS_T_LIBERA_EXC_ALT_REF
  BEFORE DELETE ON MEGA.FIN_REFERENCIAFIN
  FOR EACH ROW
  WHEN (OLD.REF_ST_TIPO = 'BXCRE')
DECLARE
  -- [23/07/2026 - ALEXANDRE CARVALHO] GATE DO ESTORNO DE BAIXA DE CREDITO (EXC/ALT).
  -- APAGAR O VINCULO BXCRE E O PRIMEIRO PASSO OBRIGATORIO DO ESTORNO (FKS IMPEDEM
  -- APAGAR O MOVIMENTO ANTES). RESOLVE O TITULO (REF_MOV_*), APLICA OS SKIPS
  -- (VAREJO/PDV/SEM USUARIO) E CONSOME A LIBERACAO DE USO UNICO (A->E) REGISTRANDO
  -- EXECUCAO 'D' COM O LANCAMENTO DA BAIXA (MOV_*). SEM LIBERACAO -> ORA-20001.
  -- [13/08/2026 - ALEXANDRE CARVALHO] V6: A LIBERACAO VALE PARA A OPERACAO INTEIRA,
  -- NAO POR VINCULO. BAIXA COM JUROS/DESCONTO GERA 2+ VINCULOS BXCRE DO MESMO TITULO
  -- (CASO DEPR 19566090: CREDITO 1338,04 DO NFCR + CREDITO 0,11 DO DEBITO DE JUROS,
  -- AMBOS 16701-003 AGN 25051) E A V4 EXIGIA UMA LIBERACAO POR VINCULO - IMPOSSIVEL,
  -- A TELA SO PERMITE UMA ATIVA POR TITULO. AGORA O 1o VINCULO CONSOME A LIBERACAO E
  -- REGISTRA NA MEMORIA DE TRANSACAO (CCS_PKG_LIBERA_EXC_ALT); OS DEMAIS VINCULOS DO
  -- MESMO TITULO NA MESMA TRANSACAO PASSAM GRAVANDO EXECUCAO NA MESMA LIB.
  wUSUARIO NUMBER;
  vLIB     NUMBER;
  vFIL     NUMBER;
  vAGN     NUMBER;
  vDOC     MEGA.FIN_MOVIMENTO.MOV_ST_DOCUMENTO%TYPE;
  vPARC    MEGA.FIN_MOVIMENTO.MOV_ST_PARCELA%TYPE;
  vTPD     MEGA.FIN_MOVIMENTO.TPD_ST_CODIGO%TYPE;
  vVALOR   NUMBER;
BEGIN
  wUSUARIO := TO_NUMBER(MEGA.GLO_PCK_CONTEXTO.F_GETVARIAVEL('vUSU_IN_CODIGO'));
  IF wUSUARIO IS NULL OR wUSUARIO = 0 THEN RETURN; END IF;

  BEGIN
    SELECT M.FIL_IN_CODIGO, M.AGN_IN_CODIGO, M.MOV_ST_DOCUMENTO, M.MOV_ST_PARCELA, M.TPD_ST_CODIGO
      INTO vFIL, vAGN, vDOC, vPARC, vTPD
      FROM MEGA.FIN_MOVIMENTO M
     WHERE M.MOV_TAB_IN_CODIGO = :OLD.REF_MOV_TAB_IN_CODIGO
       AND M.MOV_SEQ_IN_CODIGO = :OLD.REF_MOV_SEQ_IN_CODIGO
       AND M.MOV_IN_NUMLANCTO  = :OLD.REF_MOV_IN_NUMLANCTO;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN RETURN;
  END;
  IF vFIL IN (401,402,403,404,501,502,503,504) THEN RETURN; END IF;
  IF vTPD = 'PDV' THEN RETURN; END IF;

  BEGIN
    SELECT M.MOV_RE_VALOR INTO vVALOR
      FROM MEGA.FIN_MOVIMENTO M
     WHERE M.MOV_TAB_IN_CODIGO = :OLD.MOV_TAB_IN_CODIGO
       AND M.MOV_SEQ_IN_CODIGO = :OLD.MOV_SEQ_IN_CODIGO
       AND M.MOV_IN_NUMLANCTO  = :OLD.MOV_IN_NUMLANCTO;
  EXCEPTION
    WHEN NO_DATA_FOUND THEN vVALOR := NULL;
  END;

  -- [13/08/2026 - ALEXANDRE CARVALHO] V6: TITULO JA AUTORIZADO NESTA TRANSACAO?
  vLIB := MEGA.CCS_PKG_LIBERA_EXC_ALT.F_LIB_DA_TRANSACAO(vFIL, vAGN, vDOC, vPARC);
  IF vLIB IS NOT NULL THEN
    INSERT INTO MEGA.CCS_TB_LIBERA_EXC_ALT_EXEC
      (LIBE_IN_CODIGO, LIB_IN_CODIGO, LIBE_CH_OPERACAO, MOV_TAB_IN_CODIGO,
       MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO, LIBE_IN_USU_EXECUTOU, LIBE_DT_EXECUCAO, LIBE_RE_VALOR)
    VALUES
      (MEGA.CCS_SEQ_LIBERA_EXALT_EXEC.NEXTVAL, vLIB, 'D',
       :OLD.MOV_TAB_IN_CODIGO, :OLD.MOV_SEQ_IN_CODIGO, :OLD.MOV_IN_NUMLANCTO,
       wUSUARIO, SYSDATE, vVALOR);
    RETURN;
  END IF;

  UPDATE MEGA.CCS_TB_LIBERA_EXC_ALT L
     SET L.LIB_CH_STATUS = 'E'
   WHERE L.LIB_IN_CODIGO = (SELECT MIN(X.LIB_IN_CODIGO)
                              FROM MEGA.CCS_TB_LIBERA_EXC_ALT X
                             WHERE X.AGN_IN_CODIGO    = vAGN
                               AND X.LIB_ST_DOCUMENTO = vDOC
                               AND X.FIL_IN_CODIGO    = vFIL
                               AND (X.LIB_ST_PARCELA IS NULL OR X.LIB_ST_PARCELA = vPARC)
                               AND X.LIB_CH_STATUS    = 'A')
     AND L.LIB_CH_STATUS = 'A'
  RETURNING L.LIB_IN_CODIGO INTO vLIB;

  IF SQL%ROWCOUNT = 1 THEN
    INSERT INTO MEGA.CCS_TB_LIBERA_EXC_ALT_EXEC
      (LIBE_IN_CODIGO, LIB_IN_CODIGO, LIBE_CH_OPERACAO, MOV_TAB_IN_CODIGO,
       MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO, LIBE_IN_USU_EXECUTOU, LIBE_DT_EXECUCAO, LIBE_RE_VALOR)
    VALUES
      (MEGA.CCS_SEQ_LIBERA_EXALT_EXEC.NEXTVAL, vLIB, 'D',
       :OLD.MOV_TAB_IN_CODIGO, :OLD.MOV_SEQ_IN_CODIGO, :OLD.MOV_IN_NUMLANCTO,
       wUSUARIO, SYSDATE, vVALOR);
    MEGA.CCS_PKG_LIBERA_EXC_ALT.P_REGISTRA_CONSUMO(vFIL, vAGN, vDOC, vPARC, vLIB);
  ELSE
    RAISE_APPLICATION_ERROR(-20001, 'USUARIO ('|| wUSUARIO ||') NAO POSSUI AUTORIZACAO PARA EXCLUIR/ESTORNAR BAIXA DE TITULO! A LIBERACAO E DE USO UNICO - SOLICITE UMA NOVA NA TELA LIBERACAO DE EXC/ALT DO GESTOR FINANCEIRO.');
  END IF;
END;
