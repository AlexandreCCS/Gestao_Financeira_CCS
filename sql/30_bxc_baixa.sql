CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC (
    P_TOKEN    IN VARCHAR2,
    P_TIPO     IN VARCHAR2,
    P_ORG      IN NUMBER,
    P_CTA      IN NUMBER,
    P_DATA     IN DATE,
    P_TPD_FIN  IN VARCHAR2,
    P_DOC_FIN  IN VARCHAR2,
    P_HIST     IN VARCHAR2,
    P_USU      IN NUMBER,
    P_LOGIN    IN VARCHAR2,
    P_TITULOS  IN VARCHAR2,
    P_CBAS     IN VARCHAR2,
    P_ORIGEM   IN VARCHAR2 DEFAULT 'T',
    P_ARQ      IN VARCHAR2 DEFAULT NULL,
    P_COMP     IN NUMBER DEFAULT NULL,
    P_SIMULAR  IN VARCHAR2 DEFAULT 'N'
) IS
    /* [25/10/2026 - Alexandre Carvalho] O QUE A API CHAMA. Cria a linha de log, roda o nucleo num SAVEPOINT e registra o resultado:
       B = baixado e conciliado | S = simulado (nada gravado) | X = recusado. Nunca propaga erro de regra. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    IF P_TIPO NOT IN ('P', 'R') THEN RAISE_APPLICATION_ERROR(-20100, 'Tipo invalido (P = pagar, R = receber).'); END IF;
    IF NVL(P_ORIGEM, 'T') NOT IN ('T', 'R') THEN RAISE_APPLICATION_ERROR(-20100, 'Origem invalida (T = tela, R = robo).'); END IF;
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG
    ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, CTA_AGN_IN_CODIGO, LOG_DT_BANCO, LOG_ST_CBAS, TPD_FIN_ST_CODIGO, LOG_ST_DOC_FIN,
      COMP_IN_CODIGO, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO, EXT_ST_HISTORICO, EXT_ST_ARQUIVO )
    VALUES
    ( W_LOG, P_TOKEN, P_TIPO, 'X', NVL(P_ORIGEM, 'T'), P_ORG, P_CTA, TRUNC(P_DATA), SUBSTR(P_CBAS, 1, 2000), P_TPD_FIN, SUBSTR(P_DOC_FIN, 1, 30),
      P_COMP, P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE, SUBSTR(P_HIST, 1, 120), SUBSTR(P_ARQ, 1, 120) );
    SAVEPOINT SP_GFIN_BXC;
    BEGIN
        MEGA.CCS_P_GFIN_BXC_X(W_LOG, P_TIPO, P_ORG, P_CTA, P_DATA, P_TPD_FIN, P_DOC_FIN, P_HIST, P_USU, P_TITULOS, P_CBAS);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            SELECT 'Simulacao sem erro: ' || LOG_IN_QT_TITULOS || ' titulo(s), R$ ' || TO_CHAR(LOG_RE_VALOR_BANCO, 'FM999G999G990D00') || ' do banco. Nada foi gravado.' INTO W_MSG
              FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = W_LOG;
            ROLLBACK TO SP_GFIN_BXC;
            W_ST := 'S';
        ELSE
            W_ST := 'B'; W_MSG := NULL;
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_BXC;
            W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_BXC;
