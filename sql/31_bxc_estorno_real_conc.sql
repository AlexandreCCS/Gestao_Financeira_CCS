    END;
    BEGIN
        SELECT * INTO D FROM MEGA.CCS_TB_GFIN_BXC_DEPARA WHERE DEP_IN_CODIGO = P_DEP AND DEP_CH_ATIVO = 'S';
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'De-para ' || P_DEP || ' nao encontrado ou inativo.');
    END;
    IF D.DEP_CH_NATUREZA <> B.CBA_CH_NATUREZA THEN RAISE_APPLICATION_ERROR(-20100, 'De-para e linha do extrato com naturezas diferentes.'); END IF;
    IF D.TPD_ST_CODIGO <> B.TPD_ST_CODIGO THEN RAISE_APPLICATION_ERROR(-20100, 'De-para (' || D.TPD_ST_CODIGO || ') nao vale para a linha (' || B.TPD_ST_CODIGO || ').'); END IF;
