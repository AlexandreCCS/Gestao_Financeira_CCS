CREATE OR REPLACE TRIGGER MEGA.CCS_T_LIBERA_FORMA_REC
  BEFORE UPDATE OF HCOB_IN_SEQUENCIA ON MEGA.FIN_CONTASRECEBER
  FOR EACH ROW
  WHEN (NVL(OLD.HCOB_IN_SEQUENCIA, -1) <> NVL(NEW.HCOB_IN_SEQUENCIA, -1))
DECLARE
  -- [09/10/2026 - ALEXANDRE CARVALHO] TROCA DA FORMA DE RECEBIMENTO DO TITULO EXIGE LIBERACAO NO GESTOR FINANCEIRO (VER CABECALHO DO SQL 24)
  vUsu NUMBER; vFil NUMBER; vAgn NUMBER; vDoc VARCHAR2(20); vParc VARCHAR2(6); vTpd VARCHAR2(10);
  vTipoPara VARCHAR2(10); vTipoDe VARCHAR2(10); vLib NUMBER; vTipo CHAR(1); vProg VARCHAR2(200); vUnit VARCHAR2(200); vAuto BOOLEAN := FALSE;
BEGIN
  BEGIN
    vUsu := TO_NUMBER(MEGA.GLO_PCK_CONTEXTO.F_GETVARIAVEL('vUSU_IN_CODIGO'));
  EXCEPTION WHEN OTHERS THEN vUsu := NULL; END;
  -- quem chamou (pilha): unidade CCS_* / T_CCS_* = rotina automatica da casa
  BEGIN
    FOR i IN 2 .. UTL_CALL_STACK.DYNAMIC_DEPTH LOOP
      vUnit := UTL_CALL_STACK.CONCATENATE_SUBPROGRAM(UTL_CALL_STACK.SUBPROGRAM(i));
      IF vProg IS NULL AND vUnit IS NOT NULL AND vUnit NOT LIKE '%anonymous%' THEN vProg := SUBSTR(vUnit, 1, 200); END IF;
      IF (UPPER(vUnit) LIKE 'CCS\_%' ESCAPE '\' OR UPPER(vUnit) LIKE 'T\_CCS\_%' ESCAPE '\') THEN vAuto := TRUE; vProg := SUBSTR(vUnit, 1, 200); EXIT; END IF;
    END LOOP;
  EXCEPTION WHEN OTHERS THEN NULL; END;
  IF NVL(vUsu, 0) = 0 THEN vAuto := TRUE; END IF;

  BEGIN
    SELECT M.FIL_IN_CODIGO, M.AGN_IN_CODIGO, M.MOV_ST_DOCUMENTO, M.MOV_ST_PARCELA, M.TPD_ST_CODIGO
      INTO vFil, vAgn, vDoc, vParc, vTpd
      FROM MEGA.FIN_MOVIMENTO M
     WHERE M.ORG_TAB_IN_CODIGO = :NEW.ORG_TAB_IN_CODIGO AND M.ORG_PAD_IN_CODIGO = :NEW.ORG_PAD_IN_CODIGO
       AND M.ORG_IN_CODIGO = :NEW.ORG_IN_CODIGO AND M.ORG_TAU_ST_CODIGO = :NEW.ORG_TAU_ST_CODIGO
       AND M.MOV_TAB_IN_CODIGO = :NEW.MOV_TAB_IN_CODIGO AND M.MOV_SEQ_IN_CODIGO = :NEW.MOV_SEQ_IN_CODIGO
       AND M.MOV_IN_NUMLANCTO = :NEW.MOV_IN_NUMLANCTO;
  EXCEPTION WHEN OTHERS THEN NULL; END;

  IF :NEW.HCOB_IN_SEQUENCIA IS NOT NULL THEN
    BEGIN
      SELECT TCOB_ST_CODIGO INTO vTipoPara FROM MEGA.FIN_HBKCOBRANCA WHERE HCOB_IN_SEQUENCIA = :NEW.HCOB_IN_SEQUENCIA;
    EXCEPTION WHEN OTHERS THEN vTipoPara := NULL; END;
  END IF;

  IF :OLD.HCOB_IN_SEQUENCIA IS NOT NULL THEN
    BEGIN
      SELECT TCOB_ST_CODIGO INTO vTipoDe FROM MEGA.FIN_HBKCOBRANCA WHERE HCOB_IN_SEQUENCIA = :OLD.HCOB_IN_SEQUENCIA;
    EXCEPTION WHEN OTHERS THEN vTipoDe := NULL; END;
  END IF;

  IF vAuto THEN
    vTipo := 'A';
  ELSIF vTipoPara = 'SIMP' OR vTipoDe = 'SIMP' THEN
    -- [09/10/2026 V2 - ALEXANDRE CARVALHO] BOLETO E SO DO BANCO DO DIA: NAO ENTRA NESTA TRAVA (PEDIDO DO ALEXANDRE)
    vTipo := 'D';
  ELSIF :OLD.HCOB_IN_SEQUENCIA IS NULL THEN
    vTipo := 'S';
  END IF;

  IF vTipo IS NULL THEN
    UPDATE MEGA.CCS_TB_LIBERA_FORMA_REC L
       SET L.LIB_CH_STATUS = 'E', L.LIB_IN_USU_EXECUTOU = vUsu, L.LIB_DT_EXECUCAO = SYSDATE
     WHERE L.ORG_IN_CODIGO = :NEW.ORG_IN_CODIGO AND L.MOV_IN_NUMLANCTO = :NEW.MOV_IN_NUMLANCTO
       AND L.LIB_CH_STATUS = 'A' AND NVL(L.HCOB_IN_PARA, -1) = NVL(:NEW.HCOB_IN_SEQUENCIA, -1)
       AND ROWNUM = 1
    RETURNING L.LIB_IN_CODIGO INTO vLib;
    IF SQL%ROWCOUNT = 0 THEN
      MEGA.CCS_P_LOG_FORMA_REC_AUT('X', :NEW.ORG_IN_CODIGO, :NEW.MOV_IN_NUMLANCTO, vFil, vAgn, vDoc, vParc, vTpd,
                                   :OLD.HCOB_IN_SEQUENCIA, :NEW.HCOB_IN_SEQUENCIA, vUsu, vProg);
      RAISE_APPLICATION_ERROR(-20003, 'A TROCA DA FORMA DE RECEBIMENTO DO TITULO ' || vDoc || '/' || vParc || ' (DE '
        || NVL(TO_CHAR(:OLD.HCOB_IN_SEQUENCIA), 'SEM FORMA') || ' PARA ' || NVL(TO_CHAR(:NEW.HCOB_IN_SEQUENCIA), 'SEM FORMA')
        || ') PRECISA DE LIBERACAO NO GESTOR FINANCEIRO (LIBERACAO > FORMA DE RECEBIMENTO).');
    END IF;
    vTipo := 'L';
  END IF;

  INSERT INTO MEGA.CCS_TB_LOG_FORMA_REC (LOG_IN_CODIGO, LOG_DT, LOG_CH_TIPO, ORG_IN_CODIGO, MOV_IN_NUMLANCTO, FIL_IN_CODIGO, AGN_IN_CODIGO,
    LOG_ST_DOCUMENTO, LOG_ST_PARCELA, TPD_ST_CODIGO, HCOB_IN_DE, HCOB_IN_PARA, LIB_IN_CODIGO, USU_IN_CODIGO, LOG_ST_MODULO, LOG_ST_PROGRAMA)
  VALUES (MEGA.CCS_SEQ_LOG_FORMA_REC.NEXTVAL, SYSDATE, vTipo, :NEW.ORG_IN_CODIGO, :NEW.MOV_IN_NUMLANCTO, vFil, vAgn, vDoc, vParc, vTpd,
    :OLD.HCOB_IN_SEQUENCIA, :NEW.HCOB_IN_SEQUENCIA, vLib, vUsu, SUBSTR(SYS_CONTEXT('USERENV','MODULE'), 1, 100), vProg);
END CCS_T_LIBERA_FORMA_REC;
