   [21/09/2026 - Alexandre Carvalho] GESTOR FINANCEIRO - BAIXA AUTOMATICA DE CONTAS A PAGAR A PARTIR DO EXTRATO DO BANCO
   Tela: Baixas/Conciliacao > Extrato do banco x Mega > botao "Baixar no Mega".

   ESPELHA A BAIXA MANUAL DO MEGA (dissecada em 21/09/2026 - titulo Metrica 575/001, e medida em 4.900 baixas de 45 dias):
     GLO_ACAOMOVIMENTO  1 linha, acao 705, FORM_IN_ID 14001, VALORCONTABIL = VALORFINANC = valor.
                        VALORCONTABILREAL = 0  -> "PENDENTE DE CONTABILIZAR". No Mega REAL = CONTABIL significa "ja tem
                        lancamento contabil" (8.331 de 8.331 casos) e REAL = 0 significa "pendente" (2.762 de 2.762).
                        A baixa gravada por fora NAO gera CON_LANCAMENTO (quem gera e a tela do Mega), entao a marca
                        honesta e a de pendente - a rotina de contabilizacao do Mega enxerga e contabiliza.
     MOV FIN (banco)    acao 705, CONT MVFIN/2, agente = conta (TAU 'N'), TPD PGTOM, natureza C, origem 'M',
                        documento = numero do proprio lancamento (unico - nao colide com o numerador por conta do Mega),
                        FIN_MOVFIN com o nominal, classe/ccusto/projeto 9/2 natureza D.
     MOV BX (fornecedor) acao = GLO_ACAO.ACAO_BAIXA_IN_CODIGO da acao do TITULO (510 -> MVCPA/1 | 530 -> MVCPA/14),
                        TPD DEBITO, natureza D, TREF BXCPA, origem 'P', SALDOZERADO 'N', SALDOCPACRE = valor,
                        classe/ccusto/projeto HERDADOS DO TITULO com natureza C.
     FIN_REFERENCIAFIN  BXCPA    centro = BX, ORI = mov FIN, REF = titulo
                        BXFINCPA centro = BX, ORI = titulo,  REF = mov FIN     (no CPA a ordem e o INVERSO do CRE)
     TITULO             MOV_RE_SALDOCPACRE = 0, MOV_BO_SALDOZERADO = 'S'.

   SO BAIXA O CASO SEGURO (o resto a tela ALERTA e o usuario baixa no Mega):
     titulo a pagar aprovado, fora de remessa bancaria (HBK 'NO'), sem rateio (1 classe / 1 ccusto / ate 1 projeto),
     VALOR DO BANCO = SALDO EM ABERTO (baixa integral, sem juros/desconto), data do banco entre hoje-60 e hoje e FORA de
     periodo encerrado (GLO_ENCERRASISTEMA, sistemas 11 Financeiro e 4 Contabilidade, da empresa do titulo),
     usuario com hierarquia no Contas a Pagar (SIS 12) e no Mov. Financeiro (SIS 14).

   OBJETOS:  CCS_TB_GFIN_BAIXA_LOG / CCS_SEQ_GFIN_BAIXA_LOG     trilha + base do estorno
             CCS_P_GFIN_BAIXA_CPA_X      nucleo (NAO comita, NAO loga, propaga erro) - usado tambem no ensaio com ROLLBACK
             CCS_P_GFIN_BAIXA_CPA        o que a API chama: savepoint + nucleo + log + commit | P_SIMULAR='S' desfaz tudo
             CCS_P_GFIN_ESTORNO_BAIXA_X  nucleo do estorno     |  CCS_P_GFIN_ESTORNO_BAIXA  o que a API chama
   SEM ACENTO E SEM COMENTARIO DE LINHA: o fonte sobe pelo gateway SOAP.
   ROLLBACK: DROP PROCEDURE das 4 + DROP TABLE/SEQUENCE (so depois de conferir que nao ha LOG_CH_STATUS = 'B').
   ===================================================================================================================== */
