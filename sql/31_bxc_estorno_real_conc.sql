           ACAO_IN_CODIGO = D.ACAO_IN_CODIGO, ACAOM_IN_SEQUENCIA = W_ACAOM, MOV_SEQ_IN_CODIGO = W_SEQ, LANCTO_FIN = W_FIN, LANCTO_CONTRA = W_CT, CON_IN_SEQUENCIAL = W_CON,
           LOG_ST_MOVS = W_FIN || ',' || W_CT, LOG_ST_DOC_FIN = W_DOC, TPD_FIN_ST_CODIGO = W_TPD_FIN, DEP_IN_CODIGO = P_DEP, EXT_ST_HISTORICO = SUBSTR(B.CBA_ST_HISTORICO, 1, 120)
