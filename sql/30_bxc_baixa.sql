    FUNCTION NUM(P_S VARCHAR2) RETURN NUMBER IS
    BEGIN
        IF P_S IS NULL OR TRIM(P_S) = '' THEN RETURN 0; END IF;
        RETURN ROUND(TO_NUMBER(REPLACE(TRIM(P_S), ',', '.'), 'FM99999999999990.9999', 'NLS_NUMERIC_CHARACTERS=''.,'''), 2);
    END;
