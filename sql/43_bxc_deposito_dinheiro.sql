CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_DEPDIN (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_CBAS    IN VARCHAR2,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_ORIGEM  IN VARCHAR2 DEFAULT 'T',
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [23/11/2026 - Alexandre Carvalho] O QUE A API CHAMA. Log tipo A com status B/S/X; P_SIMULAR = 'S' desfaz tudo. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, LOG_ST_CBAS, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO )
    VALUES ( W_LOG, P_TOKEN, 'A', 'X', NVL(P_ORIGEM, 'T'), P_ORG, SUBSTR(P_CBAS, 1, 2000), P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE );
    SAVEPOINT SP_GFIN_BXC_DEPDIN;
    BEGIN
        MEGA.CCS_P_GFIN_BXC_DEPDIN_X(W_LOG, P_ORG, P_CBAS, P_USU);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN ROLLBACK TO SP_GFIN_BXC_DEPDIN; W_ST := 'S'; W_MSG := 'Simulacao sem erro. Nada foi gravado.';
        ELSE W_ST := 'B'; W_MSG := NULL; END IF;
    EXCEPTION
        WHEN OTHERS THEN W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500); ROLLBACK TO SP_GFIN_BXC_DEPDIN; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_BXC_DEPDIN;
