CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_REAL (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_CBA     IN NUMBER,
    P_DEP     IN NUMBER,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_HIST    IN VARCHAR2 DEFAULT NULL,
    P_ORIGEM  IN VARCHAR2 DEFAULT 'T',
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [25/10/2026 - Alexandre Carvalho] O QUE A API CHAMA PARA "LANCAR NO MEGA". Modo do de-para: 'T' = titulo ao banco + baixa + conciliacao
       (CCS_P_GFIN_BXC_TITBX_X); 'A' = avulso 710/711 + contraparte (CCS_P_GFIN_BXC_REAL_X). B / S / X no log. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500); W_MODO CHAR(1);
BEGIN
    IF NVL(P_ORIGEM, 'T') NOT IN ('T', 'R') THEN RAISE_APPLICATION_ERROR(-20100, 'Origem invalida.'); END IF;
    SELECT MAX(DEP_CH_MODO) INTO W_MODO FROM MEGA.CCS_TB_GFIN_BXC_DEPARA WHERE DEP_IN_CODIGO = P_DEP;
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, LOG_ST_CBAS, DEP_IN_CODIGO, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO )
    VALUES ( W_LOG, P_TOKEN, 'A', 'X', NVL(P_ORIGEM, 'T'), P_ORG, TO_CHAR(P_CBA), P_DEP, P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE );
    SAVEPOINT SP_GFIN_BXC_REAL;
    BEGIN
        IF W_MODO = 'T' THEN MEGA.CCS_P_GFIN_BXC_TITBX_X(W_LOG, P_ORG, P_CBA, P_DEP, P_USU, P_HIST);
        ELSE MEGA.CCS_P_GFIN_BXC_REAL_X(W_LOG, P_ORG, P_CBA, P_DEP, P_USU, P_HIST); END IF;
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            SELECT NVL(LOG_ST_MENSAGEM, 'Simulacao sem erro') || '. Nada foi gravado.' INTO W_MSG FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = W_LOG;
            ROLLBACK TO SP_GFIN_BXC_REAL; W_ST := 'S';
        ELSE
            SELECT LOG_ST_MENSAGEM INTO W_MSG FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = W_LOG;
            W_ST := 'B';
        END IF;
    EXCEPTION
        WHEN OTHERS THEN W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500); ROLLBACK TO SP_GFIN_BXC_REAL; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_BXC_REAL;
