   [28/10/2026 - Alexandre Carvalho] GESTOR FINANCEIRO - BAIXAR E CONCILIAR (QUALITY): LANCAMENTO PELO EXTRATO DE
   ADIANTAMENTO DE CLIENTE (704), ADIANTAMENTO A FORNECEDOR (702) E TRANSFERENCIA ENTRE CONTAS (712), JA CONCILIADO.
   Pegada copiada da tela do Mega (mm44c_78/80, iguais nas orgs 10/20/30):
     704: ADCLI na conta (nat D, rateio 9/2 C) + CREDITO no cliente (tau C, TREF ADIANT, nat C, classe 505 / CC 196) + ref ADIANT
     702: ADIFOR na conta (nat C, rateio 9/2 D) + DEBITO no fornecedor (tau F, TREF ADIANT, nat D, classe 500 / CC 232) + ref ADIANT
     712: TRANSFD na origem (nat C, classe 522 D) + TRANSFC no destino (TREF TRANSF, nat D, classe 523 C), CC 215 + refs TRANSF/TRANSFDEST
   Transferencia: concilia a linha da tela e, se informada, a linha da outra conta (log companheiro tipo C; o estorno desfaz os dois).
   Complementa sql/31 (molde CCS_P_GFIN_BXC_REAL_X). SO ASCII. Blocos separados por "/".
   ===================================================================================================================== */
MERGE INTO MEGA.CCS_TB_GFIN_BXC_CONT C USING (
  SELECT 704 ACAO, '-' TREF, 'MVFIN' TAC, 3 SEQ, 'adiantamento de cliente: mov da conta (ADCLI) [28/10/2026]' OBS FROM DUAL UNION ALL
  SELECT 704, 'ADIANT', 'MVFIN', 4, 'adiantamento de cliente: CREDITO no cliente [28/10/2026]' FROM DUAL UNION ALL
  SELECT 702, '-', 'MVFIN', 5, 'adiantamento a fornecedor: mov da conta (ADIFOR) [28/10/2026]' FROM DUAL UNION ALL
  SELECT 702, 'ADIANT', 'MVFIN', 6, 'adiantamento a fornecedor: DEBITO no fornecedor [28/10/2026]' FROM DUAL UNION ALL
  SELECT 712, '-', 'MVFIN', 11, 'transferencia: TRANSFD na conta de origem [28/10/2026]' FROM DUAL UNION ALL
  SELECT 712, 'TRANSF', 'MVFIN', 12, 'transferencia: TRANSFC na conta de destino [28/10/2026]' FROM DUAL
) X ON (C.ACAO_IN_CODIGO = X.ACAO AND C.TREF_ST_CODIGO = X.TREF)
WHEN NOT MATCHED THEN INSERT (ACAO_IN_CODIGO, TREF_ST_CODIGO, CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA, CONT_ST_OBS) VALUES (X.ACAO, X.TREF, X.TAC, X.SEQ, X.OBS)
/
