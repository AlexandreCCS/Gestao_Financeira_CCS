  -- [09/10/2026 - ALEXANDRE CARVALHO] % JUROS / % MULTA DO TITULO A RECEBER (ABONO = ZERAR). SO REGISTRA.
  FUNCTION N(P NUMBER) RETURN VARCHAR2 IS BEGIN RETURN TO_CHAR(P, 'FM9999990.0000', 'NLS_NUMERIC_CHARACTERS=,.'); END;
  PROCEDURE L(P_CAMPO VARCHAR2, P_DE NUMBER, P_PARA NUMBER) IS
  BEGIN
    MEGA.CCS_P_GFIN_ALTTIT_LOG('FIN_CONTASRECEBER', 'U', P_CAMPO, N(P_DE), N(P_PARA),
      :NEW.ORG_TAB_IN_CODIGO, :NEW.ORG_PAD_IN_CODIGO, :NEW.ORG_IN_CODIGO, :NEW.ORG_TAU_ST_CODIGO,
      :NEW.MOV_TAB_IN_CODIGO, :NEW.MOV_SEQ_IN_CODIGO, :NEW.MOV_IN_NUMLANCTO, NULL, NULL, NULL, NULL, 'R', NULL);
  END;
