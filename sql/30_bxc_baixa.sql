             WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = W_SEQ AND MOV_IN_NUMLANCTO = P_LANC AND ROWNUM = 1;
