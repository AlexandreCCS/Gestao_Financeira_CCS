CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_DESCONCILIA_X (
    P_ORG    IN NUMBER,
    P_SEQ    IN NUMBER,
    P_LANCTO IN NUMBER,
    P_CBA    IN NUMBER,
    P_CON    IN NUMBER
) IS
    /* [21/09/2026 - Alexandre Carvalho] DESFAZ UMA CONCILIACAO 1 x 1 FEITA PELO GESTOR, SE AINDA ESTIVER INTACTA. NAO COMITA. */
    W_NM NUMBER; W_NB NUMBER; W_OK NUMBER;
BEGIN
    SELECT COUNT(*) INTO W_NM FROM MEGA.FIN_MOVIMENTO   X WHERE X.CON_IN_SEQUENCIAL = P_CON;
    SELECT COUNT(*) INTO W_NB FROM MEGA.FIN_CONCILIACAO X WHERE X.CON_IN_SEQUENCIAL = P_CON;
    IF W_NM <> 1 OR W_NB <> 1 THEN
        RAISE_APPLICATION_ERROR(-20100, 'A conciliacao foi alterada no Mega (' || W_NM || ' lancamento(s), ' || W_NB || ' linha(s) do banco). Desfaca pelo Mega.');
    END IF;
    SELECT COUNT(*) INTO W_OK FROM MEGA.FIN_CONCILIAMOVIMENTO C WHERE C.CON_IN_SEQUENCIAL = P_CON AND C.CON_CH_TIPO = 'A' AND C.ORG_IN_CODIGO = P_ORG;
    IF W_OK <> 1 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Conciliacao nao encontrada no Mega (ja desfeita por la?).');
    END IF;
    UPDATE MEGA.FIN_MOVIMENTO
       SET MOV_CH_CONCILIADO = 'N',
           CON_IN_SEQUENCIAL = NULL
     WHERE ORG_TAB_IN_CODIGO = 53 AND ORG_PAD_IN_CODIGO = 1 AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = 'G'
       AND MOV_TAB_IN_CODIGO = 352 AND MOV_SEQ_IN_CODIGO = P_SEQ AND MOV_IN_NUMLANCTO = P_LANCTO AND CON_IN_SEQUENCIAL = P_CON;
    IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20100, 'O lancamento desta conciliacao nao e mais o mesmo. Desfaca pelo Mega.');
    END IF;
    UPDATE MEGA.FIN_CONCILIACAO
       SET CBA_CH_STATUS     = 'N',
           CON_IN_SEQUENCIAL = NULL
     WHERE CBA_IN_SEQUENCIA = P_CBA AND CON_IN_SEQUENCIAL = P_CON;
    IF SQL%ROWCOUNT <> 1 THEN
        RAISE_APPLICATION_ERROR(-20100, 'A linha do extrato desta conciliacao nao e mais a mesma. Desfaca pelo Mega.');
    END IF;
    DELETE FROM MEGA.FIN_CONCILIAMOVIMENTO WHERE CON_IN_SEQUENCIAL = P_CON;
END CCS_P_GFIN_DESCONCILIA_X;
