CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_LANC (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_CBA     IN NUMBER,
    P_TIPO    IN VARCHAR2,
    P_AGN     IN NUMBER,
    P_CBA2    IN NUMBER,
    P_CLA     IN NUMBER,
    P_CC      IN NUMBER,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_HIST    IN VARCHAR2 DEFAULT NULL,
    P_ORIGEM  IN VARCHAR2 DEFAULT 'T',
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [28/10/2026 - Alexandre Carvalho] O QUE A API CHAMA. Log tipo A (lancamento) com status B/S/X; P_SIMULAR = 'S' desfaz tudo. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, LOG_ST_CBAS, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO )
    VALUES ( W_LOG, P_TOKEN, 'A', 'X', NVL(P_ORIGEM, 'T'), P_ORG, TO_CHAR(P_CBA), P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE );
    SAVEPOINT SP_GFIN_BXC_LANC;
    BEGIN
        MEGA.CCS_P_GFIN_BXC_LANC_X(W_LOG, P_ORG, P_CBA, P_TIPO, P_AGN, P_CBA2, P_CLA, P_CC, P_USU, P_HIST);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN ROLLBACK TO SP_GFIN_BXC_LANC; W_ST := 'S'; W_MSG := 'Simulacao sem erro. Nada foi gravado.';
        ELSE W_ST := 'B'; W_MSG := NULL; END IF;
    EXCEPTION
        WHEN OTHERS THEN W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500); ROLLBACK TO SP_GFIN_BXC_LANC; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_BXC_LANC;
