CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_CONCILIA (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_SEQ     IN NUMBER,
    P_LANCTO  IN NUMBER,
    P_CBA     IN NUMBER,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_HIST    IN VARCHAR2 DEFAULT NULL,
    P_ARQ     IN VARCHAR2 DEFAULT NULL,
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [21/09/2026 - Alexandre Carvalho] O QUE A API CHAMA. RESULTADO NO LOG PELO TOKEN: C = CONCILIADO | S = SIMULADO OK | X = RECUSADO. */
    W_CON NUMBER; W_CTA NUMBER; W_VALOR NUMBER; W_DB DATE; W_DM DATE; W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    SAVEPOINT SP_GFIN_CONC;
    BEGIN
        MEGA.CCS_P_GFIN_CONCILIA_X(P_ORG, P_SEQ, P_LANCTO, P_CBA, P_USU, W_CON, W_CTA, W_VALOR, W_DB, W_DM);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            ROLLBACK TO SP_GFIN_CONC;
            W_ST := 'S'; W_MSG := 'Simulacao sem erro. Nada foi gravado.'; W_CON := NULL;
        ELSE
            W_ST := 'C'; W_MSG := NULL;
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_CONC;
            W_ST := 'X'; W_CON := NULL;
    END;
    INSERT INTO MEGA.CCS_TB_GFIN_CONC_LOG
    ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_STATUS, ORG_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO, CBA_IN_SEQUENCIA, CON_IN_SEQUENCIAL,
      CTA_AGN_IN_CODIGO, LOG_DT_BANCO, LOG_DT_MOVIMENTO, LOG_RE_VALOR, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO, EXT_ST_HISTORICO, EXT_ST_ARQUIVO, LOG_ST_MENSAGEM )
    VALUES
    ( MEGA.CCS_SEQ_GFIN_CONC_LOG.NEXTVAL, P_TOKEN, W_ST, P_ORG, P_SEQ, P_LANCTO, P_CBA, W_CON,
      W_CTA, W_DB, W_DM, W_VALOR, P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE, SUBSTR(P_HIST, 1, 120), SUBSTR(P_ARQ, 1, 120), W_MSG );
    COMMIT;
END CCS_P_GFIN_CONCILIA;
