    P_SEQ_BX     IN NUMBER,
    P_LANCTO_FIN IN NUMBER,
    P_LANCTO_BX  IN NUMBER,
    P_ACAOM      IN NUMBER,
    P_VALOR      IN NUMBER,
    P_SALDO_ANT  IN NUMBER,
    P_ZERADO_ANT IN VARCHAR2,
    P_USU        IN NUMBER
) IS
    /* [21/09/2026 - Alexandre Carvalho] NUCLEO DO ESTORNO DA BAIXA DO GESTOR. NAO COMITA. SO DESFAZ O QUE AINDA ESTA INTACTO:
       MOV DO BANCO NAO CONCILIADO, ACAO SEM LANCAMENTO CONTABIL, NENHUMA OUTRA REFERENCIA PENDURADA, TITULO AINDA ZERADO. */
    C_ORG_TAB CONSTANT NUMBER := 53; C_ORG_PAD CONSTANT NUMBER := 1; C_ORG_TAU CONSTANT VARCHAR2(3) := 'G'; C_MOV_TAB CONSTANT NUMBER := 352;
    F MEGA.FIN_MOVIMENTO%ROWTYPE;
    B MEGA.FIN_MOVIMENTO%ROWTYPE;
    T MEGA.FIN_MOVIMENTO%ROWTYPE;
    W_N NUMBER;
    E_OCUPADO EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
    PROCEDURE LE(P_S NUMBER, P_L NUMBER, R OUT MEGA.FIN_MOVIMENTO%ROWTYPE, P_QUE VARCHAR2) IS
    BEGIN
        SELECT M.* INTO R FROM MEGA.FIN_MOVIMENTO M
         WHERE M.ORG_TAB_IN_CODIGO = C_ORG_TAB AND M.ORG_PAD_IN_CODIGO = C_ORG_PAD AND M.ORG_IN_CODIGO = P_ORG AND M.ORG_TAU_ST_CODIGO = C_ORG_TAU
           AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = P_S AND M.MOV_IN_NUMLANCTO = P_L
           FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, P_QUE || ' nao existe mais no Mega (ja excluido por la?).');
        WHEN E_OCUPADO     THEN RAISE_APPLICATION_ERROR(-20100, P_QUE || ' em uso por outro usuario no Mega. Tente de novo em instantes.');
    END;
    PROCEDURE DESATUALIZA(R MEGA.FIN_MOVIMENTO%ROWTYPE) IS
    BEGIN
        FIN_PCK_MOVIMENTO.P_DESATUALIZAMOVIMENTO(
            PMOV_DT_DATADOCTO => R.MOV_DT_DATADOCTO, PMOV_DT_ENTRADA => R.MOV_DT_ENTRADA, PMOV_DT_VENCTO => R.MOV_DT_VENCTO,
            PMOV_DT_PRORROGADO => R.MOV_DT_PRORROGADO, PMOV_DT_ORCAMENTO => R.MOV_DT_ORCAMENTO,
            PMOV_TAB_IN_CODIGO => R.MOV_TAB_IN_CODIGO, PMOV_SEQ_IN_CODIGO => R.MOV_SEQ_IN_CODIGO, PMOV_IN_NUMLANCTO => R.MOV_IN_NUMLANCTO,
            PBAN_IN_NUMERO => 0, PIND_IN_CODIGOMOE => 0, PORG_IN_CODIGO => R.ORG_IN_CODIGO, PFIL_IN_CODIGO => R.FIL_IN_CODIGO,
            PAGN_TAB_IN_CODIGO => R.AGN_TAB_IN_CODIGO, PAGN_PAD_IN_CODIGO => R.AGN_PAD_IN_CODIGO, PAGN_IN_CODIGO => R.AGN_IN_CODIGO,
            PAGN_TAU_ST_CODIGO => R.AGN_TAU_ST_CODIGO, PMOV_BO_PREVISAO => 'N', PTREF_ST_CODIGO => R.TREF_ST_CODIGO,
            PMOV_CH_ORIGEM => R.MOV_CH_ORIGEM, PMOV_CH_NATUREZA => R.MOV_CH_NATUREZA,
            PMOV_RE_VALOR => R.MOV_RE_VALOR, PMOV_RE_VALORMOE => R.MOV_RE_VALORMOE,
            PUPDATEKIND => 'D', PMOV_CH_SITUACAO => R.MOV_CH_SITUACAO, PUSU_IN_ALTERACAO => P_USU,
            PACAOM_IN_SEQUENCIA => R.ACAOM_IN_SEQUENCIA, PMARCAPARACONTABILIZAR => 'N');
    END;
BEGIN
    LE(P_SEQ_TIT, P_LANCTO_TIT, T, 'Titulo');
    LE(P_SEQ_BX, P_LANCTO_FIN, F, 'Lancamento do banco');
    LE(P_SEQ_BX, P_LANCTO_BX, B, 'Lancamento da baixa');
    IF F.ACAOM_IN_SEQUENCIA <> P_ACAOM OR B.ACAOM_IN_SEQUENCIA <> P_ACAOM OR ABS(F.MOV_RE_VALOR - P_VALOR) >= 0.005 OR ABS(B.MOV_RE_VALOR - P_VALOR) >= 0.005 THEN
        RAISE_APPLICATION_ERROR(-20100, 'A baixa foi alterada no Mega depois de gravada. Estorne pelo Mega.');
    END IF;
    IF NVL(F.MOV_CH_CONCILIADO, 'N') = 'S' OR F.CON_IN_SEQUENCIAL IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20100, 'O lancamento do banco ja esta conciliado. Desfaca a conciliacao antes de estornar.');
    END IF;
    SELECT COUNT(*) INTO W_N FROM MEGA.CON_LANCAMENTO C WHERE C.ACAOM_ORG_IN_CODIGO = P_ORG AND C.ACAOM_IN_SEQUENCIA = P_ACAOM;
    IF W_N > 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'A baixa ja foi contabilizada. Estorne pelo Mega.');
    END IF;
    IF NVL(T.MOV_RE_SALDOCPACRE, 0) <> 0 OR NVL(T.MOV_BO_SALDOZERADO, 'N') <> 'S' THEN
        RAISE_APPLICATION_ERROR(-20100, 'O titulo foi movimentado depois da baixa. Estorne pelo Mega.');
    END IF;
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_REFERENCIAFIN R
     WHERE R.ORG_IN_CODIGO = P_ORG
       AND NOT (R.MOV_TAB_IN_CODIGO = C_MOV_TAB AND R.MOV_SEQ_IN_CODIGO = P_SEQ_BX AND R.MOV_IN_NUMLANCTO = P_LANCTO_BX)
       AND ( (R.REF_MOV_TAB_IN_CODIGO = C_MOV_TAB AND R.REF_MOV_SEQ_IN_CODIGO = P_SEQ_BX AND R.REF_MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX))
          OR (R.ORI_MOV_TAB_IN_CODIGO = C_MOV_TAB AND R.ORI_MOV_SEQ_IN_CODIGO = P_SEQ_BX AND R.ORI_MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX))
          OR (R.MOV_TAB_IN_CODIGO = C_MOV_TAB AND R.MOV_SEQ_IN_CODIGO = P_SEQ_BX AND R.MOV_IN_NUMLANCTO = P_LANCTO_FIN) );
    IF W_N > 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Ha outros lancamentos ligados a esta baixa (juros, desconto ou transferencia). Estorne pelo Mega.');
    END IF;

    FIN_PCK_MOVIMENTO.COMP_ST_NOME  := 'MEGA';
    FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    FIN_PCK_MOVIMENTO.REFAZENDOFIN  := 'S';
    FIN_PCK_MOVIMENTO.REFAZENDOORC  := 'N';
    FIN_PCK_MOVIMENTO.ORCREFAZ      := 0;
    DESATUALIZA(B);
    DESATUALIZA(F);

    DELETE FROM MEGA.FIN_REFERENCIAFIN
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO = P_LANCTO_BX;
    IF SQL%ROWCOUNT <> 2 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Referencias da baixa diferentes do esperado (' || SQL%ROWCOUNT || '). Estorne pelo Mega.');
    END IF;
    DELETE FROM MEGA.FIN_LANCPROJ
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX);
    DELETE FROM MEGA.FIN_LANCCCUSTO
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX);
    DELETE FROM MEGA.FIN_LANCCLASSE
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX);
    DELETE FROM MEGA.FIN_MOVFIN
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX);
    DELETE FROM MEGA.FIN_MOVIMENTO
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_BX AND MOV_IN_NUMLANCTO IN (P_LANCTO_FIN, P_LANCTO_BX);
    IF SQL%ROWCOUNT <> 2 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Movimentos da baixa diferentes do esperado (' || SQL%ROWCOUNT || ').');
    END IF;
    DELETE FROM MEGA.GLO_ACAOMOVIMENTO
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND ACAOM_IN_SEQUENCIA = P_ACAOM;
    UPDATE MEGA.FIN_MOVIMENTO
       SET MOV_RE_SALDOCPACRE = P_SALDO_ANT,
           MOV_BO_SALDOZERADO = NVL(P_ZERADO_ANT, 'N')
     WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = P_ORG AND ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = P_SEQ_TIT AND MOV_IN_NUMLANCTO = P_LANCTO_TIT;
END CCS_P_GFIN_ESTORNO_BAIXA_X;
