/

-- [23/07/2026 - ALEXANDRE CARVALHO] 2d. Extensao manual do "grupo" ------------
-- Agentes que sao empresas do grupo mas nao tem TAU 'G' no cadastro (cadastros-
-- CLIENTE das proprias empresas). O filtro "Mostrar empresas do grupo" da tela
-- de Liberacao considera TAU 'G' OU presenca nesta tabela.
CREATE TABLE MEGA.CCS_TB_GFIN_LIB_GRUPO_AGN (
  AGN_IN_CODIGO     NUMBER NOT NULL,
  GRU_ST_OBSERVACAO VARCHAR2(100),
  GRU_DT_INCLUSAO   DATE DEFAULT SYSDATE,
  CONSTRAINT PK_CCS_GFIN_LIB_GRUPO_AGN PRIMARY KEY (AGN_IN_CODIGO)
);

BEGIN
  MERGE INTO MEGA.CCS_TB_GFIN_LIB_GRUPO_AGN D
  USING (SELECT 10707 AGN, 'NORMA LUCIA SOARES VIEGAS' OBS FROM DUAL
   UNION SELECT 23979, 'QUALITY IND DE ESQUADRIAS E MANGUEIRAS' FROM DUAL
   UNION SELECT 21703, 'FREEDOM IND ESQ MANG NORDESTE' FROM DUAL
   UNION SELECT 21704, 'FREEDOM IND ESQ MANG NORDESTE' FROM DUAL
   UNION SELECT 21574, 'FREEDOM IND ESQ MANG NORDESTE' FROM DUAL) S
  ON (D.AGN_IN_CODIGO = S.AGN)
  WHEN NOT MATCHED THEN INSERT (AGN_IN_CODIGO, GRU_ST_OBSERVACAO) VALUES (S.AGN, S.OBS);
  COMMIT;
END;
/
