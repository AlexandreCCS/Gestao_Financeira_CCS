    E_OCUPADO EXCEPTION; PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
BEGIN
    SELECT NVL(MAX(PARAM_RE_VALOR), 5) INTO W_JANELA FROM MEGA.CCS_TB_GFIN_PARAM WHERE PARAM_ST_CHAVE = 'BXC_JANELA_DIAS';
    BEGIN
