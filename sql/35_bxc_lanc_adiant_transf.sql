    PROCEDURE CONCILIA(P_CTA NUMBER, P_PAD NUMBER, P_FIL NUMBER, P_DT DATE, P_MOV NUMBER, P_LINHA NUMBER, O_CON OUT NUMBER) IS
    BEGIN
        BEGIN
            MEGA.FIN_PCK_CONCILIACAOBANC.P_VALIDACONCILIACAO(P_ORG, P_FIL, P_DT);
        EXCEPTION WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20100, 'Periodo de conciliacao encerrado no Mega para a empresa ' || P_FIL || '.');
        END;
        SELECT MEGA.FIN_SEQ_CONCILIACAO.NEXTVAL INTO O_CON FROM DUAL;
        INSERT INTO MEGA.FIN_CONCILIAMOVIMENTO ( CON_IN_SEQUENCIAL, ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO, CON_CH_TIPO, CON_DT_CONCILIACAO, CON_DT_MAIORDATA, USU_IN_CODIGO, CON_RE_VALOR )
        VALUES ( O_CON, C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_ORG_TAB, P_PAD, P_CTA, 'N', 'A', SYSDATE, GREATEST(P_DT, W_DATA), P_USU, W_VAL );
        UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'S', CON_IN_SEQUENCIAL = O_CON WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = W_SEQ AND MOV_IN_NUMLANCTO = P_MOV;
        UPDATE MEGA.FIN_CONCILIACAO SET CBA_CH_STATUS = 'S', CON_IN_SEQUENCIAL = O_CON WHERE CBA_IN_SEQUENCIA = P_LINHA;
    END;
    FUNCTION RAIZ(P_FIL NUMBER) RETURN VARCHAR2 IS W VARCHAR2(40);
    BEGIN
        SELECT SUBSTR(REGEXP_REPLACE(MAX(A.AGN_ST_CGC), '[^0-9]', ''), 1, 8) INTO W FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_IN_CODIGO = P_FIL;
        RETURN W;
    END;
BEGIN
    SELECT * INTO L FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = P_LOG;
    BEGIN
        SELECT X.* INTO B FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = P_CBA FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato nao existe no Mega.');
        WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato em uso por outro usuario no Mega.');
    END;
    IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato ja esta conciliada.'); END IF;
    IF B.ORG_IN_CODIGO <> P_ORG THEN RAISE_APPLICATION_ERROR(-20100, 'Linha do extrato de outra organizacao.'); END IF;
    BEGIN
        SELECT * INTO K FROM MEGA.CCS_TB_GFIN_BXC_CONTA WHERE AGN_IN_CODIGO = B.AGN_IN_CODIGO AND CTA_CH_ATIVA = 'S';
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ' || B.AGN_IN_CODIGO || ' fora do escopo do Baixar e Conciliar.');
    END;
    IF P_AGN IS NULL THEN RAISE_APPLICATION_ERROR(-20100, CASE P_TIPO WHEN 'TRANSF' THEN 'Informe a outra conta da transferencia.' ELSE 'Informe o agente do adiantamento.' END); END IF;
    W_ACAO := CASE P_TIPO WHEN 'ADCLI' THEN 704 WHEN 'ADFOR' THEN 702 WHEN 'TRANSF' THEN 712 END;
    IF W_ACAO IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Tipo de lancamento invalido: ' || P_TIPO || '.'); END IF;
    IF P_TIPO = 'ADCLI' AND B.CBA_CH_NATUREZA <> 'C' THEN RAISE_APPLICATION_ERROR(-20100, 'Adiantamento de cliente so em entrada (credito) do extrato.'); END IF;
    IF P_TIPO = 'ADFOR' AND B.CBA_CH_NATUREZA <> 'D' THEN RAISE_APPLICATION_ERROR(-20100, 'Adiantamento a fornecedor so em saida (debito) do extrato.'); END IF;
    W_VAL := ROUND(NVL(B.CBA_RE_VALOR, 0), 2);
    IF W_VAL <= 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Linha do extrato sem valor.'); END IF;
    W_DATA := TRUNC(B.CBA_DT_DATA);
    IF W_DATA > TRUNC(SYSDATE) OR W_DATA < TRUNC(SYSDATE) - 90 THEN RAISE_APPLICATION_ERROR(-20100, 'Data da linha fora da janela (90 dias).'); END IF;
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO INTO W_CTA_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = B.AGN_IN_CODIGO AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira ' || B.AGN_IN_CODIGO || ' nao encontrada.');
    END;

    IF P_TIPO = 'TRANSF' THEN
        IF P_AGN = B.AGN_IN_CODIGO THEN RAISE_APPLICATION_ERROR(-20100, 'A outra conta da transferencia e a propria conta.'); END IF;
        BEGIN
            SELECT C.AGN_PAD_IN_CODIGO INTO W_OUT_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = P_AGN AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
        EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira ' || P_AGN || ' nao encontrada.');
        END;
        W_OUT_TAU := 'N';
        IF P_CBA2 IS NOT NULL THEN
            BEGIN
                SELECT X.* INTO B2 FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = P_CBA2 FOR UPDATE NOWAIT;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA2 || ' da outra conta nao existe no Mega.');
                WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA2 || ' da outra conta em uso por outro usuario no Mega.');
            END;
            IF NVL(B2.CBA_CH_STATUS, 'N') = 'S' OR B2.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'A linha ' || P_CBA2 || ' da outra conta ja esta conciliada.'); END IF;
            IF B2.AGN_IN_CODIGO <> P_AGN OR B2.ORG_IN_CODIGO <> P_ORG OR B2.CBA_CH_NATUREZA = B.CBA_CH_NATUREZA OR ABS(ROUND(B2.CBA_RE_VALOR, 2) - W_VAL) >= 0.005
               OR ABS(TRUNC(B2.CBA_DT_DATA) - W_DATA) > 3 THEN
                RAISE_APPLICATION_ERROR(-20100, 'A linha ' || P_CBA2 || ' nao e a outra ponta desta transferencia (conta, organizacao, natureza, valor ou data).');
            END IF;
            W_TEM_B2 := TRUE; W_OUT_FIL := B2.FIL_IN_CODIGO;
        ELSE
            SELECT MAX(FIL_IN_CODIGO) INTO W_OUT_FIL FROM MEGA.CCS_TB_GFIN_BXC_CONTA WHERE AGN_IN_CODIGO = P_AGN;
            IF W_OUT_FIL IS NULL THEN
                SELECT MAX(X.FIL_IN_CODIGO) KEEP (DENSE_RANK LAST ORDER BY X.CBA_DT_DATA) INTO W_OUT_FIL FROM MEGA.FIN_CONCILIACAO X WHERE X.AGN_IN_CODIGO = P_AGN AND X.ORG_IN_CODIGO = P_ORG;
            END IF;
            IF W_OUT_FIL IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Nao achei a empresa da conta ' || P_AGN || ' (nem extrato dela nesta organizacao).'); END IF;
        END IF;
        W_RAIZ1 := RAIZ(B.FIL_IN_CODIGO); W_RAIZ2 := RAIZ(W_OUT_FIL);
        IF W_RAIZ1 IS NULL OR W_RAIZ2 IS NULL OR W_RAIZ1 <> W_RAIZ2 THEN
            RAISE_APPLICATION_ERROR(-20100, 'Transferencia so entre contas da mesma raiz de CNPJ (empresa ' || B.FIL_IN_CODIGO || ' x ' || W_OUT_FIL || ').');
        END IF;
        W_ORIGEM_AQUI := (B.CBA_CH_NATUREZA = 'D'); W_ORI := CASE WHEN B.CBA_CH_NATUREZA = 'D' THEN 'S' ELSE 'N' END;
        SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_IN_CODIGO = CASE WHEN W_ORI = 'S' THEN P_AGN ELSE B.AGN_IN_CODIGO END;
        /* ja lancada (pelo financeiro ou pela outra conta) e ainda nao conciliada aqui? entao e conciliar, nao lancar */
        SELECT COUNT(*) INTO W_N FROM MEGA.FIN_MOVIMENTO M
         WHERE M.ORG_IN_CODIGO = P_ORG AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.AGN_IN_CODIGO = B.AGN_IN_CODIGO AND M.AGN_TAU_ST_CODIGO = 'N' AND M.ACAO_IN_CODIGO = 712
           AND M.MOV_CH_NATUREZA = CASE WHEN W_ORI = 'S' THEN 'C' ELSE 'D' END AND ABS(M.MOV_RE_VALOR - W_VAL) < 0.005 AND ABS(TRUNC(M.MOV_DT_DATADOCTO) - W_DATA) <= 5
           AND NVL(M.MOV_CH_CONCILIADO, 'N') = 'N' AND NVL(M.MOV_CH_SITUACAO, 'A') <> 'C';
        IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Ja existe transferencia deste valor nesta conta, nao conciliada, a ate 5 dias. Concilie com ela em vez de lancar outra.'); END IF;
    ELSE
        W_OUT_TAU := CASE P_TIPO WHEN 'ADCLI' THEN 'C' ELSE 'F' END;
        BEGIN
            SELECT I.AGN_PAD_IN_CODIGO INTO W_OUT_PAD FROM MEGA.GLO_AGENTES_ID I WHERE I.AGN_TAB_IN_CODIGO = C_ORG_TAB AND I.AGN_IN_CODIGO = P_AGN AND I.AGN_TAU_ST_CODIGO = W_OUT_TAU AND ROWNUM = 1;
        EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Agente ' || P_AGN || ' nao esta cadastrado como ' || CASE W_OUT_TAU WHEN 'C' THEN 'cliente' ELSE 'fornecedor' END || '.');
        END;
        SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_PAD_IN_CODIGO = W_OUT_PAD AND A.AGN_IN_CODIGO = P_AGN;
        W_OUT_FIL := K.FIL_IN_CODIGO;
        SELECT COUNT(*) INTO W_N FROM MEGA.FIN_MOVIMENTO M
         WHERE M.ORG_IN_CODIGO = P_ORG AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.AGN_IN_CODIGO = B.AGN_IN_CODIGO AND M.AGN_TAU_ST_CODIGO = 'N' AND M.ACAO_IN_CODIGO = W_ACAO
           AND ABS(M.MOV_RE_VALOR - W_VAL) < 0.005 AND ABS(TRUNC(M.MOV_DT_DATADOCTO) - W_DATA) <= 5 AND NVL(M.MOV_CH_CONCILIADO, 'N') = 'N' AND NVL(M.MOV_CH_SITUACAO, 'A') <> 'C';
        IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Ja existe adiantamento deste valor nesta conta, nao conciliado, a ate 5 dias. Concilie com ele em vez de lancar outro.'); END IF;
    END IF;

    FOR E IN (SELECT X.SIS_DT_ENCERRAMENTO, X.FIL_IN_CODIGO FROM MEGA.GLO_ENCERRASISTEMA X
               WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
                 AND X.FIL_IN_CODIGO IN (B.FIL_IN_CODIGO, W_OUT_FIL) AND X.SIS_IN_CODIGO IN (11, 4) AND W_DATA <= X.SIS_DT_ENCERRAMENTO) LOOP
        RAISE_APPLICATION_ERROR(-20100, 'Periodo encerrado no Mega para a empresa ' || E.FIL_IN_CODIGO || ' ate ' || TO_CHAR(E.SIS_DT_ENCERRAMENTO, 'DD/MM/YYYY') || '.');
    END LOOP;
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
    IF W_HUS IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mov. Financeiro do Mega.'); END IF;

    W_DOC := 'EXT' || P_CBA;
    W_HIST := SUBSTR(NVL(P_HIST, CASE P_TIPO WHEN 'ADCLI' THEN 'ADIANTAMENTO DE CLIENTE' WHEN 'ADFOR' THEN 'ADIANTAMENTO A FORNECEDOR' ELSE 'TRANSFERENCIA ENTRE CONTAS' END
                 || ' - ' || NVL(B.CBA_ST_HISTORICO, '') || ' (GESTOR FINANCEIRO)'), 1, 500);
    FIN_PCK_MOVIMENTO.COMP_ST_NOME := 'MEGA'; FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    W_SEQ := PCK_MEGA.ACHASEQUENCIADATABELA(P_ORG, C_MOV_TAB, W_DATA);
    IF W_SEQ IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Sem sequencia de movimento para ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || '.'); END IF;
    W_ACAOM := PCK_MEGA.PROXIMASEQUENCIATAB(59);
    W_AQUI := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_LA := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    INSERT INTO MEGA.GLO_ACAOMOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, ACAOM_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO,
      ACAOM_ST_DOCUMENTO, ACAOM_DT_DATAEMISSAO, ACAOM_DT_DATAENTRADA, USU_IN_INCLUSAO, USU_IN_ALTERACAO, ACAOM_DT_INCLUSAO, ACAOM_DT_ALTERACAO,
      ACAOM_RE_VALORCONTABIL, ACAOM_RE_VALORCONTABILREAL, ACAOM_RE_VALORFISCAL, ACAOM_RE_VALORFISCALREAL, ACAOM_RE_VALORFINANC, ACAOM_RE_VALORFINANCREAL,
      ACAOM_RE_VALORIMOB, ACAOM_RE_VALORIMOBREAL, CONT_ORG_IN_CODIGO, FIL_IN_CODIGO, LAN_CH_TIPOCONTAB, FORM_IN_ID )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, W_ACAOM, 55, 1, W_ACAO, W_DOC, W_DATA, W_DATA, P_USU, P_USU, SYSDATE, SYSDATE,
      W_VAL, W_VAL, 0, 0, 0, 0, 0, 0, P_ORG, B.FIL_IN_CODIGO, 'S', 14001 );

    IF P_TIPO = 'ADCLI' THEN
        INS_MOV(W_AQUI, B.FIL_IN_CODIGO, 'ADCLI', 'D', NULL, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', 'S');
        INS_RATEIO(W_AQUI, '9', 2, '9', 2, 'C');
        ATUALIZA(W_AQUI, B.FIL_IN_CODIGO, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', NULL, 'D');
        INS_MOV(W_LA, B.FIL_IN_CODIGO, 'CREDITO', 'C', 'ADIANT', W_OUT_PAD, P_AGN, 'C', 'N');
        INS_REF(W_LA, W_AQUI, W_LA, 'ADIANT');
        INS_RATEIO(W_LA, '1', NVL(P_CLA, 505), '1', NVL(P_CC, 196), 'D');
        ATUALIZA(W_LA, B.FIL_IN_CODIGO, W_OUT_PAD, P_AGN, 'C', 'ADIANT', 'C');
    ELSIF P_TIPO = 'ADFOR' THEN
        INS_MOV(W_AQUI, B.FIL_IN_CODIGO, 'ADIFOR', 'C', NULL, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', 'S');
        INS_RATEIO(W_AQUI, '9', 2, '9', 2, 'D');
        ATUALIZA(W_AQUI, B.FIL_IN_CODIGO, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', NULL, 'C');
        INS_MOV(W_LA, B.FIL_IN_CODIGO, 'DEBITO', 'D', 'ADIANT', W_OUT_PAD, P_AGN, 'F', 'N');
        INS_REF(W_LA, W_AQUI, W_LA, 'ADIANT');
        INS_RATEIO(W_LA, '1', NVL(P_CLA, 500), '1', NVL(P_CC, 232), 'C');
        ATUALIZA(W_LA, B.FIL_IN_CODIGO, W_OUT_PAD, P_AGN, 'F', 'ADIANT', 'D');
    ELSIF W_ORIGEM_AQUI THEN
        /* saida aqui: TRANSFD nesta conta (W_AQUI), TRANSFC na outra (W_LA) */
        INS_MOV(W_AQUI, B.FIL_IN_CODIGO, 'TRANSFD', 'C', NULL, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', 'S');
        INS_RATEIO(W_AQUI, '1', 522, '1', NVL(P_CC, 215), 'D');
        ATUALIZA(W_AQUI, B.FIL_IN_CODIGO, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', NULL, 'C');
        INS_MOV(W_LA, W_OUT_FIL, 'TRANSFC', 'D', 'TRANSF', W_OUT_PAD, P_AGN, 'N', 'N');
        INS_REF(W_LA, W_AQUI, W_LA, 'TRANSF');
        INS_REF(W_AQUI, W_LA, W_LA, 'TRANSFDEST');
        INS_RATEIO(W_LA, '1', 523, '1', NVL(P_CC, 215), 'C');
        ATUALIZA(W_LA, W_OUT_FIL, W_OUT_PAD, P_AGN, 'N', 'TRANSF', 'D');
    ELSE
        /* entrada aqui: TRANSFD na outra conta (W_LA), TRANSFC nesta (W_AQUI) */
        INS_MOV(W_LA, W_OUT_FIL, 'TRANSFD', 'C', NULL, W_OUT_PAD, P_AGN, 'N', 'S');
        INS_RATEIO(W_LA, '1', 522, '1', NVL(P_CC, 215), 'D');
        ATUALIZA(W_LA, W_OUT_FIL, W_OUT_PAD, P_AGN, 'N', NULL, 'C');
        INS_MOV(W_AQUI, B.FIL_IN_CODIGO, 'TRANSFC', 'D', 'TRANSF', W_CTA_PAD, B.AGN_IN_CODIGO, 'N', 'N');
        INS_REF(W_AQUI, W_LA, W_AQUI, 'TRANSF');
        INS_REF(W_LA, W_AQUI, W_AQUI, 'TRANSFDEST');
        INS_RATEIO(W_AQUI, '1', 523, '1', NVL(P_CC, 215), 'C');
        ATUALIZA(W_AQUI, B.FIL_IN_CODIGO, W_CTA_PAD, B.AGN_IN_CODIGO, 'N', 'TRANSF', 'D');
    END IF;

    /* conciliacao desta conta; na transferencia, tambem a da outra conta (log companheiro tipo C, desfeito junto no estorno) */
    CONCILIA(B.AGN_IN_CODIGO, W_CTA_PAD, B.FIL_IN_CODIGO, W_DATA, W_AQUI, P_CBA, W_CON);
    IF W_TEM_B2 THEN
        CONCILIA(P_AGN, W_OUT_PAD, W_OUT_FIL, TRUNC(B2.CBA_DT_DATA), W_LA, P_CBA2, W_CON2);
        INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, CTA_AGN_IN_CODIGO, FIL_IN_CODIGO, LOG_DT_BANCO, LOG_RE_VALOR_BANCO,
            LOG_IN_QT_TITULOS, LOG_ST_CBAS, LOG_ST_MOVS, LOG_ST_DOC_FIN, ACAO_IN_CODIGO, ACAOM_IN_SEQUENCIA, MOV_SEQ_IN_CODIGO, LANCTO_FIN, CON_IN_SEQUENCIAL, USU_IN_CODIGO, USU_ST_LOGIN,
            LOG_DT_INCLUSAO, EXT_ST_HISTORICO, LOG_ST_MENSAGEM )
        VALUES ( MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL, SUBSTR(L.LOG_ST_TOKEN, 1, 37) || '-2', 'C', 'B', L.LOG_CH_ORIGEM, P_ORG, P_AGN, W_OUT_FIL, TRUNC(B2.CBA_DT_DATA), W_VAL,
            0, TO_CHAR(P_CBA2), TO_CHAR(W_LA), W_DOC, 712, W_ACAOM, W_SEQ, W_LA, W_CON2, P_USU, L.USU_ST_LOGIN,
            SYSDATE, SUBSTR(B2.CBA_ST_HISTORICO, 1, 120), 'Outra ponta da transferencia do log ' || P_LOG || ' (desfeita junto)' );
    END IF;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG
       SET CTA_AGN_IN_CODIGO = B.AGN_IN_CODIGO, FIL_IN_CODIGO = B.FIL_IN_CODIGO, LOG_DT_BANCO = W_DATA, LOG_RE_VALOR_BANCO = W_VAL, LOG_IN_QT_TITULOS = 0,
           ACAO_IN_CODIGO = W_ACAO, ACAOM_IN_SEQUENCIA = W_ACAOM, MOV_SEQ_IN_CODIGO = W_SEQ, LANCTO_FIN = W_AQUI, LANCTO_CONTRA = W_LA, CON_IN_SEQUENCIAL = W_CON,
           LOG_ST_MOVS = W_AQUI || ',' || W_LA, LOG_ST_DOC_FIN = W_DOC, TPD_FIN_ST_CODIGO = CASE P_TIPO WHEN 'ADCLI' THEN 'ADCLI' WHEN 'ADFOR' THEN 'ADIFOR' ELSE CASE WHEN W_ORI = 'S' THEN 'TRANSFD' ELSE 'TRANSFC' END END,
           EXT_ST_HISTORICO = SUBSTR(B.CBA_ST_HISTORICO, 1, 120)
     WHERE LOG_IN_CODIGO = P_LOG;
END CCS_P_GFIN_BXC_LANC_X;
