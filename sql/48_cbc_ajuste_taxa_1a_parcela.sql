    PROCEDURE INS_REF(P_MOV NUMBER, P_REF NUMBER, P_ORI NUMBER, P_TIPO_REF VARCHAR2) IS
    BEGIN
        INSERT INTO MEGA.FIN_REFERENCIAFIN
        ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO,
          REF_ORG_TAB_IN_CODIGO, REF_ORG_PAD_IN_CODIGO, REF_ORG_IN_CODIGO, REF_ORG_TAU_ST_CODIGO, REF_MOV_TAB_IN_CODIGO, REF_MOV_SEQ_IN_CODIGO, REF_MOV_IN_NUMLANCTO,
          ORI_ORG_TAB_IN_CODIGO, ORI_ORG_PAD_IN_CODIGO, ORI_ORG_IN_CODIGO, ORI_ORG_TAU_ST_CODIGO, ORI_MOV_TAB_IN_CODIGO, ORI_MOV_SEQ_IN_CODIGO, ORI_MOV_IN_NUMLANCTO, REF_ST_TIPO )
        VALUES
        ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_MOV,
          C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_REF,
          C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_ORI, P_TIPO_REF );
    END;
BEGIN
    W_VAL := ROUND(NVL(P_VALOR, 0), 2);
    IF W_VAL <= 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Ajuste da taxa sem valor.'); END IF;
    /* linha do extrato */
    BEGIN
        SELECT X.* INTO B FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = P_CBA FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato nao existe no Mega.');
        WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato em uso por outro usuario no Mega.');
    END;
    IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato ja esta conciliada.'); END IF;
    IF B.ORG_IN_CODIGO <> P_ORG THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' de outra organizacao.'); END IF;
    IF B.CBA_CH_NATUREZA <> 'C' OR NOT REGEXP_LIKE(UPPER(NVL(B.CBA_ST_HISTORICO, ' ')), '^REDE') THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' nao e deposito da Rede.'); END IF;
    W_CTA := B.AGN_IN_CODIGO; W_DATA := TRUNC(B.CBA_DT_DATA); W_MAIOR := W_DATA;
    IF W_VAL > ROUND(B.CBA_RE_VALOR * 0.10, 2) THEN RAISE_APPLICATION_ERROR(-20100, 'Ajuste da taxa (' || W_VAL || ') maior que 10% do deposito: confira.'); END IF;
    /* validade e lista */
    SELECT TO_DATE(TO_CHAR(MAX(PARAM_RE_VALOR)), 'YYYYMMDD') INTO W_ATE FROM MEGA.CCS_TB_GFIN_PARAM WHERE PARAM_ST_CHAVE = 'CBC_TX1_ATE';
    IF W_ATE IS NULL OR W_DATA > W_ATE THEN RAISE_APPLICATION_ERROR(-20100, 'Ajuste da taxa da 1a parcela vale so para depositos ate ' || NVL(TO_CHAR(W_ATE, 'DD/MM/YYYY'), '(sem data)') || '.'); END IF;
    SELECT MAX(PARAM_RE_VALOR) INTO W_PONTE FROM MEGA.CCS_TB_GFIN_PARAM WHERE PARAM_ST_CHAVE = 'CBC_TX1_PONTE';
    IF W_PONTE IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ponte do ajuste (CBC_TX1_PONTE) nao configurada.'); END IF;
    BEGIN
        SELECT * INTO K FROM MEGA.CCS_TB_GFIN_BXC_CONTA WHERE AGN_IN_CODIGO = W_CTA AND CTA_CH_ATIVA = 'S';
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta ' || W_CTA || ' fora do escopo do Baixar e Conciliar.');
    END;
    IF NVL(K.CTA_CH_LOJA, 'N') <> 'S' THEN RAISE_APPLICATION_ERROR(-20100, 'Ajuste da taxa so em conta de loja.'); END IF;
    W_FIL := K.FIL_IN_CODIGO;
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := TRIM(REGEXP_SUBSTR(P_DOCS, '[^,]+', 1, W_N)); EXIT WHEN W_ITEM IS NULL;
        SELECT COUNT(*) INTO W_CS FROM MEGA.CCS_TB_GFIN_CBC_TX1 T WHERE T.FIL_IN_CODIGO = W_FIL AND T.MOV_ST_DOCUMENTO = W_ITEM;
        IF W_CS = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'NF ' || W_ITEM || ' da filial ' || W_FIL || ' fora da lista da taxa antecipada.'); END IF;
        W_NDOC := W_NDOC + 1;
        IF W_NDOC = 1 THEN W_DOC := SUBSTR(W_ITEM, 1, 30); END IF;
    END LOOP;
    IF W_NDOC = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Informe as NFs do ajuste.'); END IF;
    IF W_NDOC > 1 THEN W_DOC := TO_CHAR(P_CBA); END IF;   /* varias NFs: documento = linha do extrato (as NFs vao no log) */
    /* movimentos existentes (706 da baixa) */
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := TRIM(REGEXP_SUBSTR(P_MOVS, '[^,]+', 1, W_N)); EXIT WHEN W_ITEM IS NULL;
        MSEQ(W_N) := TO_NUMBER(REGEXP_SUBSTR(W_ITEM, '^[0-9]+')); MLAN(W_N) := TO_NUMBER(REGEXP_SUBSTR(W_ITEM, '[0-9]+$'));
    END LOOP;
    IF MLAN.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Deposito sem movimentos do Mega para conciliar.'); END IF;
    FOR I IN 1 .. MLAN.COUNT LOOP
        DECLARE R MEGA.FIN_MOVIMENTO%ROWTYPE;
        BEGIN
            SELECT M.* INTO R FROM MEGA.FIN_MOVIMENTO M WHERE M.ORG_IN_CODIGO = P_ORG AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = MSEQ(I) AND M.MOV_IN_NUMLANCTO = MLAN(I) FOR UPDATE NOWAIT;
            IF R.AGN_IN_CODIGO <> W_CTA OR R.MOV_CH_NATUREZA <> 'D' OR NVL(R.MOV_CH_CONCILIADO, 'N') = 'S' OR R.CON_IN_SEQUENCIAL IS NOT NULL OR NVL(R.MOV_CH_SITUACAO, 'N') = 'C' THEN
                RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MLAN(I) || ' nao serve (outra conta, saida, cancelado ou ja conciliado).');
            END IF;
            W_SOMA := W_SOMA + ROUND(R.MOV_RE_VALOR, 2);
            IF TRUNC(R.MOV_DT_DATADOCTO) > W_MAIOR THEN W_MAIOR := TRUNC(R.MOV_DT_DATADOCTO); END IF;
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MLAN(I) || ' nao existe no Mega.');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MLAN(I) || ' em uso por outro usuario no Mega.');
        END;
    END LOOP;
    IF ABS(ROUND(W_SOMA - W_VAL, 2) - ROUND(B.CBA_RE_VALOR, 2)) >= 0.005 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Movimentos (' || TO_CHAR(W_SOMA, 'FM999G990D00') || ') - ajuste (' || TO_CHAR(W_VAL, 'FM990D00') || ') diferente da linha do extrato (' || TO_CHAR(B.CBA_RE_VALOR, 'FM999G990D00') || ').');
    END IF;
    FOR E IN (SELECT X.SIS_DT_ENCERRAMENTO, X.FIL_IN_CODIGO FROM MEGA.GLO_ENCERRASISTEMA X
               WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
                 AND X.FIL_IN_CODIGO = W_FIL AND X.SIS_IN_CODIGO IN (11, 4) AND W_DATA <= X.SIS_DT_ENCERRAMENTO) LOOP
        RAISE_APPLICATION_ERROR(-20100, 'Periodo encerrado no Mega para a empresa ' || E.FIL_IN_CODIGO || ' ate ' || TO_CHAR(E.SIS_DT_ENCERRAMENTO, 'DD/MM/YYYY') || '.');
    END LOOP;
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
    IF W_HUS IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mov. Financeiro do Mega.'); END IF;
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO INTO W_CTA_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = W_CTA AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
        SELECT C.AGN_PAD_IN_CODIGO INTO W_PONTE_PAD FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = W_PONTE AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira da loja ou da ponte nao encontrada.');
    END;
    SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A WHERE A.AGN_TAB_IN_CODIGO = C_ORG_TAB AND A.AGN_IN_CODIGO = W_PONTE;
    W_HIST := C_HIST;

    /* 977: saida da loja (TRANSFD, C) -> entrada na ponte (TRANSFC, D). Acao NAO contabil: valores contabeis 0. */
    FIN_PCK_MOVIMENTO.COMP_ST_NOME := 'MEGA'; FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    W_SEQ := PCK_MEGA.ACHASEQUENCIADATABELA(P_ORG, C_MOV_TAB, W_DATA);
    IF W_SEQ IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Sem sequencia de movimento para ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || '.'); END IF;
    W_ACAOM := PCK_MEGA.PROXIMASEQUENCIATAB(59);
    W_O := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_D := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    INSERT INTO MEGA.GLO_ACAOMOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, ACAOM_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO,
      ACAOM_ST_DOCUMENTO, ACAOM_DT_DATAEMISSAO, ACAOM_DT_DATAENTRADA, USU_IN_INCLUSAO, USU_IN_ALTERACAO, ACAOM_DT_INCLUSAO, ACAOM_DT_ALTERACAO,
      ACAOM_RE_VALORCONTABIL, ACAOM_RE_VALORCONTABILREAL, ACAOM_RE_VALORFISCAL, ACAOM_RE_VALORFISCALREAL, ACAOM_RE_VALORFINANC, ACAOM_RE_VALORFINANCREAL,
      ACAOM_RE_VALORIMOB, ACAOM_RE_VALORIMOBREAL, CONT_ORG_IN_CODIGO, FIL_IN_CODIGO, LAN_CH_TIPOCONTAB, FORM_IN_ID )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, W_ACAOM, 55, 1, W_ACAO, W_DOC, W_DATA, W_DATA, P_USU, P_USU, SYSDATE, SYSDATE,
      0, 0, 0, 0, 0, 0, 0, 0, P_ORG, W_FIL, 'S', 14001 );
    INS_MOV(W_O, 'TRANSFD', 'C', NULL, W_CTA_PAD, W_CTA, 'S');
    INS_RATEIO(W_O, 522, 'D');
    ATUALIZA(W_O, W_CTA_PAD, W_CTA, NULL, 'C');
    INS_MOV(W_D, 'TRANSFC', 'D', 'TRANSF', W_PONTE_PAD, W_PONTE, 'N');
    INS_REF(W_D, W_O, W_D, 'TRANSF');
    INS_REF(W_O, W_D, W_D, 'TRANSFDEST');
    INS_RATEIO(W_D, 523, 'C');
    ATUALIZA(W_D, W_PONTE_PAD, W_PONTE, 'TRANSF', 'D');

    /* conciliacao: entradas existentes - saida 977 = linha do extrato */
    BEGIN
        MEGA.FIN_PCK_CONCILIACAOBANC.P_VALIDACONCILIACAO(P_ORG, W_FIL, W_MAIOR);
    EXCEPTION WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20100, 'Periodo de conciliacao encerrado no Mega para a empresa ' || W_FIL || '.');
    END;
    SELECT MEGA.FIN_SEQ_CONCILIACAO.NEXTVAL INTO W_CON FROM DUAL;
    INSERT INTO MEGA.FIN_CONCILIAMOVIMENTO ( CON_IN_SEQUENCIAL, ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO,
      CON_CH_TIPO, CON_DT_CONCILIACAO, CON_DT_MAIORDATA, USU_IN_CODIGO, CON_RE_VALOR )
    VALUES ( W_CON, C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_ORG_TAB, W_CTA_PAD, W_CTA, 'N', 'A', SYSDATE, W_MAIOR, P_USU, B.CBA_RE_VALOR );
    W_N := 0;
    FOR I IN 1 .. MLAN.COUNT LOOP
        UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'S', CON_IN_SEQUENCIAL = W_CON
         WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = MSEQ(I) AND MOV_IN_NUMLANCTO = MLAN(I);
        W_N := W_N + SQL%ROWCOUNT;
    END LOOP;
    UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'S', CON_IN_SEQUENCIAL = W_CON WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = W_SEQ AND MOV_IN_NUMLANCTO = W_O;
    W_N := W_N + SQL%ROWCOUNT;
    IF W_N <> MLAN.COUNT + 1 THEN RAISE_APPLICATION_ERROR(-20100, 'Conciliou ' || W_N || ' movimentos (esperado ' || (MLAN.COUNT + 1) || ').'); END IF;
    UPDATE MEGA.FIN_CONCILIACAO SET CBA_CH_STATUS = 'S', CON_IN_SEQUENCIAL = W_CON WHERE CBA_IN_SEQUENCIA = P_CBA;

    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG
       SET CTA_AGN_IN_CODIGO = W_CTA, FIL_IN_CODIGO = W_FIL, LOG_DT_BANCO = W_DATA, LOG_RE_VALOR_BANCO = B.CBA_RE_VALOR, LOG_RE_VALOR_TITULOS = 0, LOG_IN_QT_TITULOS = 0,
           ACAO_IN_CODIGO = W_ACAO, ACAOM_IN_SEQUENCIA = W_ACAOM, MOV_SEQ_IN_CODIGO = W_SEQ, LANCTO_FIN = W_O, LANCTO_CONTRA = W_D, CON_IN_SEQUENCIAL = W_CON,
           LOG_ST_MOVS = W_O || ',' || W_D, LOG_ST_MOVS_CONC = SUBSTR(P_MOVS, 1, 2000), LOG_ST_DOC_FIN = W_DOC, TPD_FIN_ST_CODIGO = 'TRANSFD', EXT_ST_ARQUIVO = 'REDE',
           EXT_ST_HISTORICO = SUBSTR(B.CBA_ST_HISTORICO || ': ajuste taxa 1a parcela NF ' || P_DOCS || ' (977 ' || TO_CHAR(W_VAL, 'FM990D00') || ')', 1, 120)
     WHERE LOG_IN_CODIGO = P_LOG;
END CCS_P_GFIN_CBC_TX1_X;
