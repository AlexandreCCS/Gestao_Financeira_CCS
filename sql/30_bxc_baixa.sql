        SELECT C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_LANC,
               L.CLA_TAB_IN_CODIGO, L.CLA_PAD_IN_CODIGO, L.CLA_IDE_ST_CODIGO, L.CLA_IN_REDUZIDO, DECODE(L.LCL_CH_NATUREZA, 'C', 'D', 'C'), L.LCC_IN_NUMERO, L.LPR_IN_NUMERO,
