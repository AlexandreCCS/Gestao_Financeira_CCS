CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BAIXA_CPA_X (
    P_ORG        IN  NUMBER,
    P_SEQ        IN  NUMBER,
    P_LANCTO     IN  NUMBER,
    P_CTA        IN  NUMBER,
    P_DATA       IN  DATE,
    P_VALOR      IN  NUMBER,
    P_USU        IN  NUMBER,
    P_HIST       IN  VARCHAR2,
    O_SEQ_BX     OUT NUMBER,
    O_LANCTO_FIN OUT NUMBER,
    O_LANCTO_BX  OUT NUMBER,
    O_ACAOM      OUT NUMBER,
    O_ACAO_BX    OUT NUMBER,
    O_SALDO_ANT  OUT NUMBER,
    O_ZERADO_ANT OUT VARCHAR2,
    O_AGN        OUT NUMBER,
    O_DOC        OUT VARCHAR2,
    O_PARC       OUT VARCHAR2,
    O_FIL        OUT NUMBER
) IS
    /* [21/09/2026 - Alexandre Carvalho] NUCLEO DA BAIXA CPA PELO EXTRATO. NAO COMITA. VER CABECALHO DO 19_baixa_cpa_extrato.sql */
    C_ORG_TAB   CONSTANT NUMBER := 53;
    C_ORG_PAD   CONSTANT NUMBER := 1;
    C_ORG_TAU   CONSTANT VARCHAR2(3) := 'G';
    C_MOV_TAB   CONSTANT NUMBER := 352;
    C_ACAO_TAB  CONSTANT NUMBER := 55;
    C_ACAO_PAD  CONSTANT NUMBER := 1;
    C_ACAO_FIN  CONSTANT NUMBER := 705;
    C_TPD_FIN   CONSTANT VARCHAR2(10) := 'PGTOM';
    C_TPD_BX    CONSTANT VARCHAR2(10) := 'DEBITO';
    C_TREF      CONSTANT VARCHAR2(10) := 'BXCPA';
    T           MEGA.FIN_MOVIMENTO%ROWTYPE;
    W_DATA      DATE := TRUNC(P_DATA);
    W_VALOR     NUMBER := ROUND(P_VALOR, 2);
    W_CTA_PAD   NUMBER;
    W_ACAO_BX   NUMBER;
    W_CONT_SEQ  NUMBER;
    W_HUS_FIN   NUMBER;
    W_HUS_CPA   NUMBER;
    W_NOME      VARCHAR2(100);
    W_N         NUMBER;
    W_NCLA      NUMBER;
    W_NCCF      NUMBER;
    W_NPRO      NUMBER;
    W_SALDO_VW  NUMBER;
    W_SEQ       NUMBER;
    W_ACAOM     NUMBER;
    W_FIN       NUMBER;
    W_BX        NUMBER;
    W_HIST      VARCHAR2(500);
    E_OCUPADO   EXCEPTION;
    PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
BEGIN
    IF W_VALOR IS NULL OR W_VALOR <= 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Valor do banco invalido.');
    END IF;
    IF W_DATA IS NULL OR W_DATA > TRUNC(SYSDATE) OR W_DATA < TRUNC(SYSDATE) - 60 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Data do banco fora da janela permitida (de 60 dias atras ate hoje).');
    END IF;
    /* (o periodo encerrado e conferido depois de ler o titulo - depende da empresa/filial dele) */
    /* TITULO: TRAVA A LINHA - SE ALGUEM ESTIVER COM ELE ABERTO NO MEGA, NAO ESPERA */
    BEGIN
        SELECT M.* INTO T
          FROM MEGA.FIN_MOVIMENTO M
         WHERE M.ORG_TAB_IN_CODIGO = C_ORG_TAB AND M.ORG_PAD_IN_CODIGO = C_ORG_PAD AND M.ORG_IN_CODIGO = P_ORG
           AND M.ORG_TAU_ST_CODIGO = C_ORG_TAU AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = P_SEQ
           AND M.MOV_IN_NUMLANCTO  = P_LANCTO
           FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo nao encontrado no Mega.');
        WHEN E_OCUPADO     THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo em uso por outro usuario no Mega. Tente de novo em instantes.');
    END;
    O_SALDO_ANT := NVL(T.MOV_RE_SALDOCPACRE, 0); O_ZERADO_ANT := NVL(T.MOV_BO_SALDOZERADO, 'N');
    O_AGN := T.AGN_IN_CODIGO; O_DOC := T.MOV_ST_DOCUMENTO; O_PARC := T.MOV_ST_PARCELA; O_FIL := T.FIL_IN_CODIGO;
    /* PERIODO ENCERRADO NO MEGA (GLO_ENCERRASISTEMA): 11 = FINANCEIRO, 4 = CONTABILIDADE - NAO GRAVA BAIXA EM MES FECHADO */
    FOR E IN (SELECT X.SIS_IN_CODIGO, X.SIS_DT_ENCERRAMENTO FROM MEGA.GLO_ENCERRASISTEMA X
               WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
                 AND X.FIL_IN_CODIGO = T.FIL_IN_CODIGO AND X.SIS_IN_CODIGO IN (11, 4) AND W_DATA <= X.SIS_DT_ENCERRAMENTO) LOOP
        RAISE_APPLICATION_ERROR(-20100, 'Periodo encerrado no Mega para a empresa ' || T.FIL_IN_CODIGO || ' ate ' || TO_CHAR(E.SIS_DT_ENCERRAMENTO, 'DD/MM/YYYY') ||
            CASE WHEN E.SIS_IN_CODIGO = 4 THEN ' (Contabilidade).' ELSE ' (Financeiro).' END);
    END LOOP;
    IF T.MOV_CH_ORIGEM <> 'P' OR T.TREF_ST_CODIGO IS NOT NULL OR T.MOV_CH_NATUREZA <> 'C' THEN
        RAISE_APPLICATION_ERROR(-20100, 'O lancamento informado nao e um titulo a pagar.');
    END IF;
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_CONTASPAGAR C
     WHERE C.ORG_TAB_IN_CODIGO = C_ORG_TAB AND C.ORG_PAD_IN_CODIGO = C_ORG_PAD AND C.ORG_IN_CODIGO = P_ORG AND C.ORG_TAU_ST_CODIGO = C_ORG_TAU
       AND C.MOV_TAB_IN_CODIGO = C_MOV_TAB AND C.MOV_SEQ_IN_CODIGO = P_SEQ AND C.MOV_IN_NUMLANCTO = P_LANCTO;
    IF W_N = 0 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo sem registro no Contas a Pagar.');
    END IF;
    IF NVL(T.MOV_BO_PREVISAO, 'N') <> 'N' THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo de previsao nao pode ser baixado.');
    END IF;
    IF NVL(T.MOV_CH_STATUSMOV, 'A') <> 'A' OR NVL(T.MOV_CH_SITUACAO, 'N') = 'C' THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo cancelado ou inativo.');
    END IF;
    IF NVL(T.MOV_BO_APROVADOADM, 'N') <> 'S' THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo ainda nao aprovado para pagamento no Mega.');
    END IF;
    IF NVL(T.MOV_ST_HBKSTATUS, 'NO') <> 'NO' THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo esta em remessa de pagamento eletronico (' || T.MOV_ST_HBKSTATUS || '). A baixa vem pelo retorno do banco.');
    END IF;
    IF O_SALDO_ANT <= 0 OR O_ZERADO_ANT = 'S' THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo ja esta baixado.');
    END IF;
    IF ABS(O_SALDO_ANT - W_VALOR) >= 0.005 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Valor do banco (' || TO_CHAR(W_VALOR, 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') ||
            ') diferente do saldo do titulo (' || TO_CHAR(O_SALDO_ANT, 'FM999G999G990D00', 'NLS_NUMERIC_CHARACTERS='',.''') || '). Baixa parcial ou com juros/desconto e feita no Mega.');
    END IF;
    /* CONFERE O SALDO PELA VISAO OFICIAL DO MEGA (A MESMA QUE A TELA DO GESTOR USA PARA SUGERIR) */
    BEGIN
        SELECT V.SALDO_EM_ABERTO INTO W_SALDO_VW FROM MEGA.FIN_VW_CONTASPAGAR V
         WHERE V.ORG_IN_CODIGO = P_ORG AND V.MOV_TAB_IN_CODIGO = C_MOV_TAB AND V.MOV_SEQ_IN_CODIGO = P_SEQ AND V.MOV_IN_NUMLANCTO = P_LANCTO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN W_SALDO_VW := NULL;
        WHEN TOO_MANY_ROWS THEN W_SALDO_VW := NULL;
    END;
    IF W_SALDO_VW IS NULL OR ABS(W_SALDO_VW - W_VALOR) >= 0.005 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Saldo em aberto do titulo nao confere com o valor do banco (visao do Contas a Pagar).');
    END IF;
    /* RATEIO: ESTA VERSAO SO BAIXA TITULO COM 1 CLASSE / 1 CENTRO DE CUSTO / ATE 1 PROJETO (96% DOS TITULOS) */
    SELECT COUNT(*) INTO W_NCLA FROM MEGA.FIN_LANCCLASSE L WHERE L.ORG_TAB_IN_CODIGO = C_ORG_TAB AND L.ORG_PAD_IN_CODIGO = C_ORG_PAD AND L.ORG_IN_CODIGO = P_ORG
       AND L.ORG_TAU_ST_CODIGO = C_ORG_TAU AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = P_SEQ AND L.MOV_IN_NUMLANCTO = P_LANCTO;
    SELECT COUNT(*) INTO W_NCCF FROM MEGA.FIN_LANCCCUSTO L WHERE L.ORG_TAB_IN_CODIGO = C_ORG_TAB AND L.ORG_PAD_IN_CODIGO = C_ORG_PAD AND L.ORG_IN_CODIGO = P_ORG
       AND L.ORG_TAU_ST_CODIGO = C_ORG_TAU AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = P_SEQ AND L.MOV_IN_NUMLANCTO = P_LANCTO;
    SELECT COUNT(*) INTO W_NPRO FROM MEGA.FIN_LANCPROJ L WHERE L.ORG_TAB_IN_CODIGO = C_ORG_TAB AND L.ORG_PAD_IN_CODIGO = C_ORG_PAD AND L.ORG_IN_CODIGO = P_ORG
       AND L.ORG_TAU_ST_CODIGO = C_ORG_TAU AND L.MOV_TAB_IN_CODIGO = C_MOV_TAB AND L.MOV_SEQ_IN_CODIGO = P_SEQ AND L.MOV_IN_NUMLANCTO = P_LANCTO;
    IF W_NCLA <> 1 OR W_NCCF <> 1 OR W_NPRO > 1 THEN
        RAISE_APPLICATION_ERROR(-20100, 'Titulo com rateio de classe/centro de custo (' || W_NCLA || '/' || W_NCCF || '/' || W_NPRO || '). Baixe pelo Mega.');
    END IF;
    /* CONTA FINANCEIRA */
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO INTO W_CTA_PAD FROM MEGA.GLO_CONTASFIN C
         WHERE C.AGN_TAB_IN_CODIGO = C_ORG_TAB AND C.AGN_IN_CODIGO = P_CTA AND C.AGN_TAU_ST_CODIGO = 'N' AND ROWNUM = 1;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira ' || P_CTA || ' nao encontrada no Mega.');
    END;
    /* ACAO DA BAIXA = A CONFIGURADA NA ACAO DO TITULO (GLO_ACAO.ACAO_BAIXA_IN_CODIGO) */
    BEGIN
        SELECT A.ACAO_BAIXA_IN_CODIGO INTO W_ACAO_BX FROM MEGA.GLO_ACAO A
         WHERE A.ACAO_TAB_IN_CODIGO = T.ACAO_TAB_IN_CODIGO AND A.ACAO_PAD_IN_CODIGO = T.ACAO_PAD_IN_CODIGO AND A.ACAO_IN_CODIGO = T.ACAO_IN_CODIGO;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN W_ACAO_BX := NULL;
    END;
    IF W_ACAO_BX = 510 THEN W_CONT_SEQ := 1;
    ELSIF W_ACAO_BX = 530 THEN W_CONT_SEQ := 14;
    ELSE
        RAISE_APPLICATION_ERROR(-20100, 'Acao do titulo (' || T.ACAO_IN_CODIGO || ') sem acao de baixa conhecida (' || NVL(TO_CHAR(W_ACAO_BX), 'vazia') || '). Baixe pelo Mega.');
    END IF;
    O_ACAO_BX := W_ACAO_BX;
    /* USUARIO: PRECISA PODER BAIXAR NO MEGA (HIERARQUIA NO CONTAS A PAGAR E NO MOV. FINANCEIRO) */
    BEGIN
        SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS_FIN FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
        SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS_CPA FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 12 AND H.GRU_IN_CODIGO = P_USU;
    END;
    IF W_HUS_FIN IS NULL OR W_HUS_CPA IS NULL THEN
        RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mega para baixar (Contas a Pagar / Mov. Financeiro).');
    END IF;
    SELECT SUBSTR(MAX(A.AGN_ST_NOME), 1, 100) INTO W_NOME FROM MEGA.GLO_AGENTES A
     WHERE A.AGN_TAB_IN_CODIGO = T.AGN_TAB_IN_CODIGO AND A.AGN_PAD_IN_CODIGO = T.AGN_PAD_IN_CODIGO AND A.AGN_IN_CODIGO = T.AGN_IN_CODIGO;
    W_HIST := SUBSTR('BAIXA AUTOMATICA PELO EXTRATO (GESTOR FINANCEIRO)' || CASE WHEN P_HIST IS NOT NULL THEN ' - ' || P_HIST END, 1, 500);

    FIN_PCK_MOVIMENTO.COMP_ST_NOME  := 'MEGA';
    FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    W_SEQ   := PCK_MEGA.ACHASEQUENCIADATABELA(P_ORG, C_MOV_TAB, W_DATA);
    W_ACAOM := PCK_MEGA.PROXIMASEQUENCIATAB(59);
    W_FIN   := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    W_BX    := PCK_MEGA.PROXIMASEQUENCIATAB(C_MOV_TAB);
    IF W_SEQ IS NULL THEN
        RAISE_APPLICATION_ERROR(-20100, 'Sem sequencia de movimento para a data ' || TO_CHAR(W_DATA, 'DD/MM/YYYY') || ' (periodo fechado?).');
    END IF;
    O_SEQ_BX := W_SEQ; O_ACAOM := W_ACAOM; O_LANCTO_FIN := W_FIN; O_LANCTO_BX := W_BX;

    INSERT INTO GLO_ACAOMOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO,
      ACAOM_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO,
      ACAOM_ST_DOCUMENTO, ACAOM_DT_DATAEMISSAO, ACAOM_DT_DATAENTRADA, USU_IN_INCLUSAO,
      USU_IN_ALTERACAO, ACAOM_DT_INCLUSAO, ACAOM_DT_ALTERACAO, ACAOM_RE_VALORCONTABIL,
      ACAOM_RE_VALORCONTABILREAL, ACAOM_RE_VALORFISCAL, ACAOM_RE_VALORFISCALREAL,
      ACAOM_RE_VALORFINANC, ACAOM_RE_VALORFINANCREAL, ACAOM_RE_VALORIMOB,
      ACAOM_RE_VALORIMOBREAL, CONT_ORG_IN_CODIGO, FIL_IN_CODIGO, LAN_CH_TIPOCONTAB, FORM_IN_ID )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU,
      W_ACAOM, C_ACAO_TAB, C_ACAO_PAD, C_ACAO_FIN,
      TO_CHAR(W_FIN), W_DATA, W_DATA, P_USU,
      P_USU, SYSDATE, SYSDATE, W_VALOR,
      0, 0, 0,
      W_VALOR, 0, 0,
      0, P_ORG, T.FIL_IN_CODIGO, 'S', 14001 );

    /* MOV FIN - SAIDA DA CONTA */
    INSERT INTO FIN_MOVIMENTO
    ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO,
      MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO,
      CONT_TAB_IN_CODIGO, CONT_PAD_IN_CODIGO, CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA,
      ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO, ACAOM_IN_SEQUENCIA,
      IND_IN_CODIGOMOE,
      AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO,
      TPD_ST_CODIGO, MOV_ST_DOCUMENTO, MOV_CH_SONUMEROS,
      MOV_DT_DATADOCTO, MOV_DT_ENTRADA, MOV_DT_VENCTO, MOV_DT_PRORROGADO, MOV_DT_ORCAMENTO,
      MOV_RE_VALOR, MOV_RE_VALORCRE, MOV_RE_VALORDEB, MOV_CH_NATUREZA,
      MOV_CH_STATUSSALDO, MOV_CH_SITUACAO, MOV_CH_STATUSMOV, MOV_BO_PREVISAO,
      MOV_DT_DATAINC, MOV_DT_DATAALT, MOV_CH_STATUSBXREF,
      USU_IN_INCLUSAO, USU_IN_ALTERACAO,
      MOV_RE_VALORMOE, MOV_RE_VALORCREMOE, MOV_RE_VALORDEBMOE,
      IND_IN_CODIGOIND, MOV_RE_COTACAOMOE,
      MOV_CH_ORIGEM, MOV_BO_APROVADOADM, MOV_BO_TITRECONHECIDO, MOV_BO_PAGLIBTESOUR,
      HIS_TAB_IN_CODIGO, HIS_PAD_IN_CODIGO, HIS_IN_REDUZIDO,
      MOV_CH_CONCILIADO, FIL_IN_CODIGO,
      MOV_ST_HBKSTATUS, HUS_IN_SEQUENCIA, MOV_BO_BXCHDEVOL, MOV_RE_VALORMOEDA,
      MOV_ST_COMPLHIST, MOV_BO_SALDOZERADO, MOV_CH_SITDESCDUPL, MOV_RE_SALDOCPACRE )
    VALUES
    ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU,
      C_MOV_TAB, W_SEQ, W_FIN,
      40, 1, 'MVFIN', 2,
      C_ACAO_TAB, C_ACAO_PAD, C_ACAO_FIN, W_ACAOM,
      0,
      C_ORG_TAB, W_CTA_PAD, P_CTA, 'N',
      C_TPD_FIN, TO_CHAR(W_FIN), 'S',
      W_DATA, W_DATA, W_DATA, W_DATA, W_DATA,
      W_VALOR, W_VALOR, 0, 'C',
      'N', 'N', 'A', 'N',
      SYSDATE, SYSDATE, 'N',
