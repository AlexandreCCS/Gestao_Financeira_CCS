CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_CB_IMPORTA (
    P_ARQ     IN NUMBER,
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [26/10/2026 - Alexandre Carvalho] WRAPPER: tudo ou nada. Simular = roda inteiro e desfaz tudo; o arquivo continua P (pendente)
       com a mensagem da validacao, para a mesma importacao poder ser gravada em seguida. Situacao: P | I importado | X recusado. */
    W_ST CHAR(1); W_MSG VARCHAR2(1500); W_NOVAS NUMBER; W_JA NUMBER; W_FORA NUMBER; W_ERRO NUMBER;
BEGIN
    SAVEPOINT SP_GFIN_CB_IMP;
    BEGIN
        MEGA.CCS_P_GFIN_CB_IMPORTA_X(P_ARQ);
        SELECT ARQ_IN_QT_NOVAS, ARQ_IN_QT_JA, ARQ_IN_QT_FORA, ARQ_IN_QT_ERRO INTO W_NOVAS, W_JA, W_FORA, W_ERRO FROM MEGA.CCS_TB_GFIN_CB_ARQUIVO WHERE ARQ_IN_CODIGO = P_ARQ;
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            ROLLBACK TO SP_GFIN_CB_IMP; W_ST := 'P';
            W_MSG := 'Validacao sem erro: ' || W_NOVAS || ' linha(s) seriam importadas, ' || W_JA || ' ja estavam no Mega. Nada foi gravado.';
        ELSE
            W_ST := 'I';
            W_MSG := W_NOVAS || ' linha(s) importada(s) no Mega; ' || W_JA || ' ja estavam la' || CASE WHEN W_FORA > 0 THEN '; ' || W_FORA || ' fora (tipo que o Mega nao importa)' END || '.';
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20110: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_CB_IMP; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_CB_ARQUIVO SET ARQ_CH_STATUS = W_ST, ARQ_ST_MENSAGEM = W_MSG, ARQ_DT_PROCESSADO = SYSDATE WHERE ARQ_IN_CODIGO = P_ARQ;
    COMMIT;
END CCS_P_GFIN_CB_IMPORTA;
