-- [09/10/2026 - ALEXANDRE CARVALHO] Liberacao de troca de FORMA DE RECEBIMENTO do titulo (Quality, OCPDB493).
-- Pedido do financeiro: "Nao permitir recebimento diferente da forma original; para mudanca da forma de recebimento ser obrigatoria
-- autorizacao (para conseguir monitorar no BI)". A baixa nao grava a forma usada (FIN_MOVIMENTO.FORP_IN_CODIGO vazio): quem recebe de
-- outra forma troca antes a forma do titulo (FIN_CONTASRECEBER.HCOB_IN_SEQUENCIA). A trava e nessa troca.
-- Regras (decisao do Alexandre 09/10): todas as filiais; liberacao ANTECIPADA no Gestor Financeiro (uso unico, por titulo + forma nova);
-- titulo SEM forma que recebe forma = livre (so registra); boleto segue a regra do banco do dia.
--   LIVRE (registra no log):
--     S = titulo estava sem forma e destino nao e boleto
--     D = BOLETO (TCOB SIMP) na forma atual OU na nova: boleto e regido SO pelo banco do dia, fora desta trava
--         ([09/10/2026 V2] antes: so destino = HCOB vigente do banco do dia)
--     A = rotina automatica: sem usuario no contexto (jobs) ou chamada por unidade CCS_* / T_CCS_* na pilha
--   COM LIBERACAO: L = consome a liberacao ativa do titulo para a forma nova (A -> E)
--   BLOQUEADA: X = sem liberacao -> ORA-20003 (tentativa gravada no log por transacao autonoma, para o BI)
-- Kill-switch: ALTER TRIGGER MEGA.CCS_T_LIBERA_FORMA_REC DISABLE;

CREATE SEQUENCE MEGA.CCS_SEQ_LIBERA_FORMA_REC START WITH 1 NOCACHE;
CREATE SEQUENCE MEGA.CCS_SEQ_LOG_FORMA_REC START WITH 1 NOCACHE;

CREATE TABLE MEGA.CCS_TB_LIBERA_FORMA_REC (
  LIB_IN_CODIGO        NUMBER PRIMARY KEY,
  ORG_IN_CODIGO        NUMBER NOT NULL,
  MOV_IN_NUMLANCTO     NUMBER NOT NULL,
  FIL_IN_CODIGO        NUMBER,
  AGN_IN_CODIGO        NUMBER,
  LIB_ST_DOCUMENTO     VARCHAR2(20),
  LIB_ST_PARCELA       VARCHAR2(6),
  HCOB_IN_DE           NUMBER,
  HCOB_IN_PARA         NUMBER,
  LIB_ST_MOTIVO        VARCHAR2(200),
  LIB_CH_STATUS        CHAR(1) DEFAULT 'A' NOT NULL CONSTRAINT CK_LIBFORMAREC_ST CHECK (LIB_CH_STATUS IN ('A','E','C')),
  LIB_IN_USU_LIBEROU   NUMBER,
  LIB_ST_USU_LIBEROU   VARCHAR2(60),
  LIB_DT_LIBERACAO     DATE DEFAULT SYSDATE,
  LIB_IN_USU_CANCELOU  NUMBER,
  LIB_DT_CANCELAMENTO  DATE,
  LIB_IN_USU_EXECUTOU  NUMBER,
  LIB_DT_EXECUCAO      DATE
);
CREATE INDEX MEGA.IX_LIBFORMAREC_TIT ON MEGA.CCS_TB_LIBERA_FORMA_REC (ORG_IN_CODIGO, MOV_IN_NUMLANCTO, LIB_CH_STATUS);

CREATE TABLE MEGA.CCS_TB_LOG_FORMA_REC (
  LOG_IN_CODIGO     NUMBER PRIMARY KEY,
  LOG_DT            DATE DEFAULT SYSDATE,
  LOG_CH_TIPO       CHAR(1),
  ORG_IN_CODIGO     NUMBER,
  MOV_IN_NUMLANCTO  NUMBER,
  FIL_IN_CODIGO     NUMBER,
  AGN_IN_CODIGO     NUMBER,
  LOG_ST_DOCUMENTO  VARCHAR2(20),
  LOG_ST_PARCELA    VARCHAR2(6),
  TPD_ST_CODIGO     VARCHAR2(10),
  HCOB_IN_DE        NUMBER,
  HCOB_IN_PARA      NUMBER,
  LIB_IN_CODIGO     NUMBER,
  USU_IN_CODIGO     NUMBER,
  LOG_ST_MODULO     VARCHAR2(100),
  LOG_ST_PROGRAMA   VARCHAR2(200)
);
CREATE INDEX MEGA.IX_LOGFORMAREC_DT ON MEGA.CCS_TB_LOG_FORMA_REC (LOG_DT);

CREATE OR REPLACE PROCEDURE MEGA.CCS_P_LOG_FORMA_REC_AUT(
  P_TIPO CHAR, P_ORG NUMBER, P_LANC NUMBER, P_FIL NUMBER, P_AGN NUMBER, P_DOC VARCHAR2, P_PARC VARCHAR2, P_TPD VARCHAR2,
  P_DE NUMBER, P_PARA NUMBER, P_USU NUMBER, P_PROG VARCHAR2) IS
  -- [09/10/2026 - ALEXANDRE CARVALHO] GRAVA A TENTATIVA BLOQUEADA (TIPO X) MESMO COM O ROLLBACK DA OPERACAO (TRANSACAO AUTONOMA)
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO MEGA.CCS_TB_LOG_FORMA_REC (LOG_IN_CODIGO, LOG_DT, LOG_CH_TIPO, ORG_IN_CODIGO, MOV_IN_NUMLANCTO, FIL_IN_CODIGO, AGN_IN_CODIGO,
    LOG_ST_DOCUMENTO, LOG_ST_PARCELA, TPD_ST_CODIGO, HCOB_IN_DE, HCOB_IN_PARA, LIB_IN_CODIGO, USU_IN_CODIGO, LOG_ST_MODULO, LOG_ST_PROGRAMA)
  VALUES (MEGA.CCS_SEQ_LOG_FORMA_REC.NEXTVAL, SYSDATE, P_TIPO, P_ORG, P_LANC, P_FIL, P_AGN, P_DOC, P_PARC, P_TPD, P_DE, P_PARA, NULL, P_USU,
    SUBSTR(SYS_CONTEXT('USERENV','MODULE'), 1, 100), SUBSTR(P_PROG, 1, 200));
  COMMIT;
EXCEPTION WHEN OTHERS THEN ROLLBACK;
END CCS_P_LOG_FORMA_REC_AUT;
