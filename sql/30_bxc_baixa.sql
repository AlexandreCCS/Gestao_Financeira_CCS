               L.CCF_TAB_IN_CODIGO, L.CCF_PAD_IN_CODIGO, L.CCF_IDE_ST_CODIGO, L.CCF_IN_REDUZIDO, L.LCC_RE_PERCENTUAL,
               ROUND(L.LCC_RE_VALOR * W_FATOR, 2), CASE WHEN L.LCL_CH_NATUREZA = 'D' THEN ROUND(L.LCC_RE_VALOR * W_FATOR, 2) ELSE 0 END, CASE WHEN L.LCL_CH_NATUREZA = 'C' THEN ROUND(L.LCC_RE_VALOR * W_FATOR, 2) ELSE 0 END,
