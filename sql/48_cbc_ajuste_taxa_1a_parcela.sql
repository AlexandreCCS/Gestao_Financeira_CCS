CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_CBC_TX1 (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_CBA     IN NUMBER,
    P_VALOR   IN NUMBER,
    P_DOCS    IN VARCHAR2,
    P_MOVS    IN VARCHAR2,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_ORIGEM  IN VARCHAR2 DEFAULT 'T',
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [27/11/2026 - Alexandre Carvalho] O QUE A API CHAMA. Log tipo A com status B/S/X; P_SIMULAR = 'S' desfaz tudo. */
    W_LOG NUMBER; W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    SELECT MEGA.CCS_SEQ_GFIN_BXC_LOG.NEXTVAL INTO W_LOG FROM DUAL;
    INSERT INTO MEGA.CCS_TB_GFIN_BXC_LOG ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, LOG_CH_ORIGEM, ORG_IN_CODIGO, LOG_ST_CBAS, USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO, EXT_ST_ARQUIVO )
    VALUES ( W_LOG, P_TOKEN, 'A', 'X', NVL(P_ORIGEM, 'T'), P_ORG, TO_CHAR(P_CBA), P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE, 'REDE' );
    SAVEPOINT SP_GFIN_CBC_TX1;
    BEGIN
        MEGA.CCS_P_GFIN_CBC_TX1_X(W_LOG, P_ORG, P_CBA, P_VALOR, P_DOCS, P_MOVS, P_USU);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN ROLLBACK TO SP_GFIN_CBC_TX1; W_ST := 'S'; W_MSG := 'Simulacao sem erro. Nada foi gravado.';
        ELSE W_ST := 'B'; W_MSG := 'Conciliado com ajuste da taxa da 1a parcela (977 de ' || TO_CHAR(ROUND(P_VALOR, 2), 'FM990D00') || ', NF ' || SUBSTR(P_DOCS, 1, 200) || ').'; END IF;
    EXCEPTION
        WHEN OTHERS THEN W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500); ROLLBACK TO SP_GFIN_CBC_TX1; W_ST := 'X';
    END;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = W_ST, LOG_ST_MENSAGEM = W_MSG WHERE LOG_IN_CODIGO = W_LOG;
    COMMIT;
END CCS_P_GFIN_CBC_TX1;
