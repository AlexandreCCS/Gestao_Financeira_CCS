   ===================================================================================================================== */
CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_ESTORNO_X (
    P_LOG IN NUMBER,
    P_USU IN NUMBER
) IS
    /* [25/10/2026 - Alexandre Carvalho] DESFAZ UMA OPERACAO DO BXC AINDA INTACTA. NAO COMITA.
       Tipos P/R/A: desconcilia, desatualiza e apaga os movimentos criados (lista em LOG_ST_MOVS), referencias, rateios, FIN_MOVFIN e
       o GLO_ACAOMOVIMENTO; devolve saldo/zerado/juros-baixa dos titulos (CCS_TB_GFIN_BXC_LOG_TIT). Tipo C: so desconcilia. */
    C_ORG_TAB CONSTANT NUMBER := 53; C_ORG_PAD CONSTANT NUMBER := 1; C_ORG_TAU CONSTANT VARCHAR2(3) := 'G'; C_MOV_TAB CONSTANT NUMBER := 352;
    L MEGA.CCS_TB_GFIN_BXC_LOG%ROWTYPE;
    TYPE T_NUM IS TABLE OF NUMBER INDEX BY PLS_INTEGER;
    MOVS T_NUM; CBAS T_NUM;
    W_N NUMBER; W_ITEM VARCHAR2(60); W_LISTA VARCHAR2(2100);
    E_OCUPADO EXCEPTION; PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
    PROCEDURE DESATUALIZA(R MEGA.FIN_MOVIMENTO%ROWTYPE) IS
    BEGIN
        FIN_PCK_MOVIMENTO.REFAZENDOFIN := 'S'; FIN_PCK_MOVIMENTO.REFAZENDOORC := 'N'; FIN_PCK_MOVIMENTO.ORCREFAZ := 0;
        FIN_PCK_MOVIMENTO.P_DESATUALIZAMOVIMENTO(
            PMOV_DT_DATADOCTO => R.MOV_DT_DATADOCTO, PMOV_DT_ENTRADA => R.MOV_DT_ENTRADA, PMOV_DT_VENCTO => R.MOV_DT_VENCTO,
            PMOV_DT_PRORROGADO => R.MOV_DT_PRORROGADO, PMOV_DT_ORCAMENTO => R.MOV_DT_ORCAMENTO,
            PMOV_TAB_IN_CODIGO => R.MOV_TAB_IN_CODIGO, PMOV_SEQ_IN_CODIGO => R.MOV_SEQ_IN_CODIGO, PMOV_IN_NUMLANCTO => R.MOV_IN_NUMLANCTO,
            PBAN_IN_NUMERO => 0, PIND_IN_CODIGOMOE => 0, PORG_IN_CODIGO => R.ORG_IN_CODIGO, PFIL_IN_CODIGO => R.FIL_IN_CODIGO,
            PAGN_TAB_IN_CODIGO => R.AGN_TAB_IN_CODIGO, PAGN_PAD_IN_CODIGO => R.AGN_PAD_IN_CODIGO, PAGN_IN_CODIGO => R.AGN_IN_CODIGO,
            PAGN_TAU_ST_CODIGO => R.AGN_TAU_ST_CODIGO, PMOV_BO_PREVISAO => 'N', PTREF_ST_CODIGO => R.TREF_ST_CODIGO,
            PMOV_CH_ORIGEM => R.MOV_CH_ORIGEM, PMOV_CH_NATUREZA => R.MOV_CH_NATUREZA,
            PMOV_RE_VALOR => R.MOV_RE_VALOR, PMOV_RE_VALORMOE => R.MOV_RE_VALORMOE,
            PUPDATEKIND => 'D', PMOV_CH_SITUACAO => R.MOV_CH_SITUACAO, PUSU_IN_ALTERACAO => P_USU,
            PACAOM_IN_SEQUENCIA => R.ACAOM_IN_SEQUENCIA, PMARCAPARACONTABILIZAR => 'N');
    END;
BEGIN
    SELECT * INTO L FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = P_LOG;
    IF L.LOG_CH_STATUS <> 'B' THEN RAISE_APPLICATION_ERROR(-20100, 'Operacao nao esta gravada (status ' || L.LOG_CH_STATUS || ').'); END IF;
    /* linhas do extrato desta operacao */
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := REGEXP_SUBSTR(L.LOG_ST_CBAS, '[^,]+', 1, W_N); EXIT WHEN W_ITEM IS NULL;
        CBAS(W_N) := TO_NUMBER(TRIM(W_ITEM));
    END LOOP;
    /* movimentos desta operacao (tipo C: os movimentos do Mega que foram conciliados; P/R/A: os criados) */
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := REGEXP_SUBSTR(L.LOG_ST_MOVS, '[^,]+', 1, W_N); EXIT WHEN W_ITEM IS NULL;
        MOVS(W_N) := TO_NUMBER(TRIM(W_ITEM));
    END LOOP;
    IF L.CON_IN_SEQUENCIAL IS NULL OR MOVS.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Operacao sem conciliacao ou sem movimentos registrados.'); END IF;

    /* CONCILIACAO INTACTA? os mesmos movimentos e as mesmas linhas, nada a mais */
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_MOVIMENTO M WHERE M.CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL;
    IF W_N <> (CASE WHEN L.LOG_CH_TIPO = 'C' THEN MOVS.COUNT ELSE 1 END) THEN
        RAISE_APPLICATION_ERROR(-20100, 'A conciliacao foi alterada no Mega (' || W_N || ' lancamento(s) ligados). Desfaca pelo Mega.');
    END IF;
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_CONCILIACAO B WHERE B.CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL;
    IF W_N <> CBAS.COUNT THEN RAISE_APPLICATION_ERROR(-20100, 'As linhas do extrato desta conciliacao mudaram no Mega. Desfaca pelo Mega.'); END IF;
    SELECT COUNT(*) INTO W_N FROM MEGA.FIN_CONCILIAMOVIMENTO C WHERE C.CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL AND C.CON_CH_TIPO = 'A';
    IF W_N <> 1 THEN RAISE_APPLICATION_ERROR(-20100, 'Conciliacao nao encontrada no Mega (ja desfeita por la?).'); END IF;

    IF L.LOG_CH_TIPO IN ('P', 'R', 'A') THEN
        SELECT COUNT(*) INTO W_N FROM MEGA.CON_LANCAMENTO C WHERE C.ACAOM_ORG_IN_CODIGO = L.ORG_IN_CODIGO AND C.ACAOM_IN_SEQUENCIA = L.ACAOM_IN_SEQUENCIA;
        IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'A operacao ja foi contabilizada. Estorne pelo Mega.'); END IF;
        /* os movimentos ainda sao os nossos e nada de fora aponta para eles */
        W_LISTA := L.LOG_ST_MOVS;
        SELECT COUNT(*) INTO W_N FROM MEGA.FIN_MOVIMENTO M
         WHERE M.ORG_IN_CODIGO = L.ORG_IN_CODIGO AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO
           AND M.ACAOM_IN_SEQUENCIA = L.ACAOM_IN_SEQUENCIA;
        IF W_N <> MOVS.COUNT THEN RAISE_APPLICATION_ERROR(-20100, 'Os movimentos da operacao foram alterados no Mega (' || W_N || ' de ' || MOVS.COUNT || '). Estorne pelo Mega.'); END IF;
        SELECT COUNT(*) INTO W_N FROM MEGA.FIN_REFERENCIAFIN R
         WHERE R.ORG_IN_CODIGO = L.ORG_IN_CODIGO AND R.MOV_TAB_IN_CODIGO = C_MOV_TAB
           AND NOT (R.MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND INSTR(',' || W_LISTA || ',', ',' || R.MOV_IN_NUMLANCTO || ',') > 0)
           AND ( (R.REF_MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND INSTR(',' || W_LISTA || ',', ',' || R.REF_MOV_IN_NUMLANCTO || ',') > 0)
              OR (R.ORI_MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND INSTR(',' || W_LISTA || ',', ',' || R.ORI_MOV_IN_NUMLANCTO || ',') > 0) );
        IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Ha outros lancamentos ligados a esta operacao no Mega. Estorne pelo Mega.'); END IF;
        /* titulos ainda como deixamos */
        FOR T IN (SELECT * FROM MEGA.CCS_TB_GFIN_BXC_LOG_TIT WHERE LOG_IN_CODIGO = P_LOG) LOOP
            DECLARE W_SALDO NUMBER; W_ZER VARCHAR2(1);
            BEGIN
                SELECT NVL(M.MOV_RE_SALDOCPACRE, 0), NVL(M.MOV_BO_SALDOZERADO, 'N') INTO W_SALDO, W_ZER FROM MEGA.FIN_MOVIMENTO M
                 WHERE M.ORG_IN_CODIGO = T.ORG_IN_CODIGO AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND M.MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO
                   FOR UPDATE NOWAIT;
                IF ABS(W_SALDO - (T.LGT_RE_SALDO_ANT - T.LGT_RE_VALOR - NVL(T.LGT_RE_DESCONTO, 0))) >= 0.005 THEN
                    RAISE_APPLICATION_ERROR(-20100, 'O titulo ' || T.MOV_ST_DOCUMENTO || '/' || T.MOV_ST_PARCELA || ' foi movimentado depois da baixa. Estorne pelo Mega.');
                END IF;
            EXCEPTION
                WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || T.MOV_ST_DOCUMENTO || ' nao existe mais no Mega.');
                WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Titulo ' || T.MOV_ST_DOCUMENTO || ' em uso por outro usuario no Mega.');
            END;
        END LOOP;
    END IF;

    /* 1) DESCONCILIA */
    UPDATE MEGA.FIN_CONCILIACAO SET CBA_CH_STATUS = 'N', CON_IN_SEQUENCIAL = NULL WHERE CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL;
    UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'N', CON_IN_SEQUENCIAL = NULL WHERE CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL;
    DELETE FROM MEGA.FIN_CONCILIAMOVIMENTO WHERE CON_IN_SEQUENCIAL = L.CON_IN_SEQUENCIAL;
    IF L.LOG_CH_TIPO = 'C' THEN RETURN; END IF;

    /* 2) DESATUALIZA E APAGA OS MOVIMENTOS CRIADOS (ordem inversa da criacao) */
    FIN_PCK_MOVIMENTO.COMP_ST_NOME := 'MEGA'; FIN_PCK_MOVIMENTO.USU_IN_CODIGO := P_USU;
    FOR I IN REVERSE 1 .. MOVS.COUNT LOOP
        DECLARE R MEGA.FIN_MOVIMENTO%ROWTYPE;
        BEGIN
            SELECT M.* INTO R FROM MEGA.FIN_MOVIMENTO M
             WHERE M.ORG_TAB_IN_CODIGO = C_ORG_TAB AND M.ORG_PAD_IN_CODIGO = C_ORG_PAD AND M.ORG_IN_CODIGO = L.ORG_IN_CODIGO AND M.ORG_TAU_ST_CODIGO = C_ORG_TAU
               AND M.MOV_TAB_IN_CODIGO = C_MOV_TAB AND M.MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND M.MOV_IN_NUMLANCTO = MOVS(I)
               FOR UPDATE NOWAIT;
            DESATUALIZA(R);
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MOVS(I) || ' nao existe mais no Mega.');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MOVS(I) || ' em uso por outro usuario no Mega.');
        END;
    END LOOP;
    FOR I IN 1 .. MOVS.COUNT LOOP
        DELETE FROM MEGA.FIN_REFERENCIAFIN WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        DELETE FROM MEGA.FIN_LANCPROJ WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        DELETE FROM MEGA.FIN_LANCCCUSTO WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        DELETE FROM MEGA.FIN_LANCCLASSE WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        DELETE FROM MEGA.FIN_MOVFIN WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        DELETE FROM MEGA.FIN_MOVIMENTO WHERE ORG_IN_CODIGO = L.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = L.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = MOVS(I);
        IF SQL%ROWCOUNT <> 1 THEN RAISE_APPLICATION_ERROR(-20100, 'Movimento ' || MOVS(I) || ' nao pode ser apagado.'); END IF;
    END LOOP;
    DELETE FROM MEGA.GLO_ACAOMOVIMENTO WHERE ORG_TAB_IN_CODIGO = C_ORG_TAB AND ORG_PAD_IN_CODIGO = C_ORG_PAD AND ORG_IN_CODIGO = L.ORG_IN_CODIGO AND ORG_TAU_ST_CODIGO = C_ORG_TAU AND ACAOM_IN_SEQUENCIA = L.ACAOM_IN_SEQUENCIA;

    /* 3) DEVOLVE OS TITULOS */
    FOR T IN (SELECT * FROM MEGA.CCS_TB_GFIN_BXC_LOG_TIT WHERE LOG_IN_CODIGO = P_LOG) LOOP
        UPDATE MEGA.FIN_MOVIMENTO SET MOV_RE_SALDOCPACRE = T.LGT_RE_SALDO_ANT, MOV_BO_SALDOZERADO = NVL(T.LGT_CH_ZERADO_ANT, 'N')
         WHERE ORG_IN_CODIGO = T.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
        IF L.LOG_CH_TIPO = 'R' THEN
            UPDATE MEGA.FIN_CONTASRECEBER SET CRE_RE_VRJUROSBAIXA = T.LGT_RE_JURBX_ANT
             WHERE ORG_IN_CODIGO = T.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
        ELSIF L.LOG_CH_TIPO = 'P' THEN
            UPDATE MEGA.FIN_CONTASPAGAR SET CPA_RE_VRJUROSBAIXA = T.LGT_RE_JURBX_ANT
             WHERE ORG_IN_CODIGO = T.ORG_IN_CODIGO AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = T.MOV_SEQ_IN_CODIGO AND MOV_IN_NUMLANCTO = T.MOV_IN_NUMLANCTO;
        END IF;
    END LOOP;
END CCS_P_GFIN_BXC_ESTORNO_X;
