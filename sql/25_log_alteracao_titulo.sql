-- [09/10/2026 - ALEXANDRE CARVALHO] LOG DE ALTERACOES EM TITULOS (CR/CP) PARA O GESTOR FINANCEIRO.
-- PEDIDO DO FINANCEIRO (GESTOR FINANCEIRO - BI, LIBERACOES): "VISUALIZAR MOVIMENTACOES DE ALTERACAO NO TITULO
-- (ABONO DE JUROS, MUDANCA DE VENCIMENTO E/OU FORMA DE PAGAMENTO, EXCLUSAO, OU SEJA, O QUE FOI ALTERADO)".
-- O MEGA SO GUARDA HISTORICO DE DATAS (FIN_MOVIMENTO_LOG, DESDE 09/2024); VALOR, JUROS/MULTA E EXCLUSAO DE TITULO
-- EM ABERTO NAO FICAM EM LUGAR NENHUM. A TROCA DE FORMA DE RECEBIMENTO JA E LOGADA EM CCS_TB_LOG_FORMA_REC (SQL 24).
--
-- 3 TRIGGERS AFTER ROW, SO REGISTRAM (NUNCA BLOQUEIAM: TODO O CORPO EM EXCEPTION WHEN OTHERS THEN NULL):
--   CCS_T_GFIN_ALTTIT_MOV  FIN_MOVIMENTO     (SO TITULOS: MOV_CH_ORIGEM R/P) - VALOR, VENCIMENTO, PRORROGADO, AGENTE,
--                                             DOCUMENTO, SITUACAO (CANCELAMENTO) E EXCLUSAO (DELETE, COM OS DADOS DO TITULO)
--   CCS_T_GFIN_ALTTIT_CRE  FIN_CONTASRECEBER  % JUROS E % MULTA (ABONO = ZERAR)
--   CCS_T_GFIN_ALTTIT_CPA  FIN_CONTASPAGAR    % JUROS E % MULTA
-- O INSERT E NA MESMA TRANSACAO: SE A OPERACAO DO MEGA FOR DESFEITA, O LOG SOME JUNTO (CORRETO).
-- USUARIO = GLO_PCK_CONTEXTO 'vUSU_IN_CODIGO' (MESMO METODO DO SQL 24); SEM USUARIO = ROTINA AUTOMATICA.
-- CRIADAS DESATIVADAS; SO SAO ATIVADAS DEPOIS DE CONFERIR STATUS VALID (TRIGGER INVALIDA TRAVA A FIN_MOVIMENTO).

CREATE SEQUENCE MEGA.CCS_SEQ_GFIN_ALTTIT_LOG START WITH 1 NOCACHE;

CREATE TABLE MEGA.CCS_TB_GFIN_ALTTIT_LOG (
  LOG_IN_CODIGO     NUMBER(14)     NOT NULL,
  LOG_DT_DATA       DATE           DEFAULT SYSDATE NOT NULL,
  LOG_ST_TABELA     VARCHAR2(20)   NOT NULL,   -- FIN_MOVIMENTO / FIN_CONTASRECEBER / FIN_CONTASPAGAR
  LOG_CH_OPERACAO   VARCHAR2(1)    NOT NULL,   -- U = ALTERACAO, D = EXCLUSAO
  LOG_ST_CAMPO      VARCHAR2(30)   NOT NULL,   -- VALOR, VENCIMENTO, PRORROGADO, AGENTE, DOCUMENTO, SITUACAO, JUROS_PERC, MULTA_PERC, EXCLUSAO
  LOG_ST_DE         VARCHAR2(100),
  LOG_ST_PARA       VARCHAR2(100),
  ORG_TAB_IN_CODIGO NUMBER, ORG_PAD_IN_CODIGO NUMBER, ORG_IN_CODIGO NUMBER, ORG_TAU_ST_CODIGO VARCHAR2(3),
  MOV_TAB_IN_CODIGO NUMBER, MOV_SEQ_IN_CODIGO NUMBER, MOV_IN_NUMLANCTO NUMBER,
  FIL_IN_CODIGO     NUMBER,
  AGN_IN_CODIGO     NUMBER,
  MOV_ST_DOCUMENTO  VARCHAR2(40),
  MOV_ST_PARCELA    VARCHAR2(10),
  MOV_CH_ORIGEM     VARCHAR2(1),               -- R = RECEBER, P = PAGAR
  MOV_RE_VALOR      NUMBER,
  USU_IN_CODIGO     NUMBER,                    -- USUARIO MEGA (NULL = ROTINA AUTOMATICA)
  LOG_ST_MODULO     VARCHAR2(100),
  LOG_ST_PROGRAMA   VARCHAR2(200),
  CONSTRAINT CCS_PK_GFIN_ALTTIT_LOG PRIMARY KEY (LOG_IN_CODIGO)
);
CREATE INDEX MEGA.CCS_IX_GFIN_ALTTIT_DATA ON MEGA.CCS_TB_GFIN_ALTTIT_LOG (LOG_DT_DATA);
CREATE INDEX MEGA.CCS_IX_GFIN_ALTTIT_TIT  ON MEGA.CCS_TB_GFIN_ALTTIT_LOG (ORG_IN_CODIGO, MOV_IN_NUMLANCTO);

-- GRAVACAO (MESMA TRANSACAO). USUARIO/PROGRAMA RESOLVIDOS AQUI PARA AS 3 TRIGGERS.
CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_ALTTIT_LOG(
  P_TAB VARCHAR2, P_OPER VARCHAR2, P_CAMPO VARCHAR2, P_DE VARCHAR2, P_PARA VARCHAR2,
  P_OTAB NUMBER, P_OPAD NUMBER, P_ORG NUMBER, P_OTAU VARCHAR2, P_MTAB NUMBER, P_MSEQ NUMBER, P_LANC NUMBER,
  P_FIL NUMBER, P_AGN NUMBER, P_DOC VARCHAR2, P_PARC VARCHAR2, P_ORIG VARCHAR2, P_VALOR NUMBER) IS
  -- [09/10/2026 - ALEXANDRE CARVALHO] NUNCA PROPAGA ERRO: O LOG NAO PODE IMPEDIR A OPERACAO DO MEGA
  vUsu  NUMBER;
  vProg VARCHAR2(200);
BEGIN
  BEGIN
    vUsu := TO_NUMBER(MEGA.GLO_PCK_CONTEXTO.F_GETVARIAVEL('vUSU_IN_CODIGO'));
  EXCEPTION WHEN OTHERS THEN vUsu := NULL; END;
  BEGIN
    -- PRIMEIRA UNIDADE DA PILHA QUE NAO E ESTE LOG NEM TRIGGER (QUEM DISPAROU A ALTERACAO)
    FOR I IN 2 .. LEAST(UTL_CALL_STACK.DYNAMIC_DEPTH, 12) LOOP
      vProg := UTL_CALL_STACK.CONCATENATE_SUBPROGRAM(UTL_CALL_STACK.SUBPROGRAM(I));
      EXIT WHEN vProg NOT LIKE '%CCS_P_GFIN_ALTTIT_LOG%' AND vProg NOT LIKE '%CCS_T_GFIN_ALTTIT%' AND vProg NOT LIKE '__anonymous_block%';
      vProg := NULL;
    END LOOP;
  EXCEPTION WHEN OTHERS THEN vProg := NULL; END;
  INSERT INTO MEGA.CCS_TB_GFIN_ALTTIT_LOG
    (LOG_IN_CODIGO, LOG_DT_DATA, LOG_ST_TABELA, LOG_CH_OPERACAO, LOG_ST_CAMPO, LOG_ST_DE, LOG_ST_PARA,
     ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO,
     MOV_IN_NUMLANCTO, FIL_IN_CODIGO, AGN_IN_CODIGO, MOV_ST_DOCUMENTO, MOV_ST_PARCELA, MOV_CH_ORIGEM, MOV_RE_VALOR,
     USU_IN_CODIGO, LOG_ST_MODULO, LOG_ST_PROGRAMA)
  VALUES
    (MEGA.CCS_SEQ_GFIN_ALTTIT_LOG.NEXTVAL, SYSDATE, P_TAB, P_OPER, P_CAMPO, SUBSTR(P_DE, 1, 100), SUBSTR(P_PARA, 1, 100),
     P_OTAB, P_OPAD, P_ORG, P_OTAU, P_MTAB, P_MSEQ, P_LANC, P_FIL, P_AGN, SUBSTR(P_DOC, 1, 40), SUBSTR(P_PARC, 1, 10),
     P_ORIG, P_VALOR, vUsu, SUBSTR(SYS_CONTEXT('USERENV', 'MODULE'), 1, 100), SUBSTR(vProg, 1, 200));
EXCEPTION WHEN OTHERS THEN NULL;
END CCS_P_GFIN_ALTTIT_LOG;
/

CREATE OR REPLACE TRIGGER MEGA.CCS_T_GFIN_ALTTIT_MOV
  AFTER UPDATE OF MOV_RE_VALOR, MOV_DT_VENCTO, MOV_DT_PRORROGADO, AGN_IN_CODIGO, MOV_ST_DOCUMENTO, MOV_CH_SITUACAO
     OR DELETE ON MEGA.FIN_MOVIMENTO
  FOR EACH ROW
  WHEN (OLD.MOV_CH_ORIGEM IN ('R', 'P'))
  DISABLE
DECLARE
  -- [09/10/2026 - ALEXANDRE CARVALHO] LOG DE ALTERACAO/EXCLUSAO DE TITULO (GESTOR FINANCEIRO). SO REGISTRA.
  PROCEDURE L(P_CAMPO VARCHAR2, P_DE VARCHAR2, P_PARA VARCHAR2, P_OPER VARCHAR2 DEFAULT 'U') IS
  BEGIN
    MEGA.CCS_P_GFIN_ALTTIT_LOG('FIN_MOVIMENTO', P_OPER, P_CAMPO, P_DE, P_PARA,
      :OLD.ORG_TAB_IN_CODIGO, :OLD.ORG_PAD_IN_CODIGO, :OLD.ORG_IN_CODIGO, :OLD.ORG_TAU_ST_CODIGO,
      :OLD.MOV_TAB_IN_CODIGO, :OLD.MOV_SEQ_IN_CODIGO, :OLD.MOV_IN_NUMLANCTO, :OLD.FIL_IN_CODIGO,
      NVL(:NEW.AGN_IN_CODIGO, :OLD.AGN_IN_CODIGO), NVL(:NEW.MOV_ST_DOCUMENTO, :OLD.MOV_ST_DOCUMENTO),
      :OLD.MOV_ST_PARCELA, :OLD.MOV_CH_ORIGEM, NVL(:NEW.MOV_RE_VALOR, :OLD.MOV_RE_VALOR));
  END;
  FUNCTION D(P DATE) RETURN VARCHAR2 IS BEGIN RETURN TO_CHAR(P, 'DD/MM/YYYY'); END;
  FUNCTION N(P NUMBER) RETURN VARCHAR2 IS BEGIN RETURN TO_CHAR(P, 'FM9999999999990.00', 'NLS_NUMERIC_CHARACTERS=,.'); END;
BEGIN
  IF DELETING THEN
    L('EXCLUSAO', 'valor ' || N(:OLD.MOV_RE_VALOR) || ' venc ' || D(NVL(:OLD.MOV_DT_PRORROGADO, :OLD.MOV_DT_VENCTO)), NULL, 'D');
  ELSE
    IF NVL(:OLD.MOV_RE_VALOR, -1) <> NVL(:NEW.MOV_RE_VALOR, -1) THEN L('VALOR', N(:OLD.MOV_RE_VALOR), N(:NEW.MOV_RE_VALOR)); END IF;
    IF NVL(:OLD.MOV_DT_VENCTO, DATE '1900-01-01') <> NVL(:NEW.MOV_DT_VENCTO, DATE '1900-01-01') THEN
      L('VENCIMENTO', D(:OLD.MOV_DT_VENCTO), D(:NEW.MOV_DT_VENCTO)); END IF;
    IF NVL(:OLD.MOV_DT_PRORROGADO, DATE '1900-01-01') <> NVL(:NEW.MOV_DT_PRORROGADO, DATE '1900-01-01') THEN
      L('PRORROGADO', D(:OLD.MOV_DT_PRORROGADO), D(:NEW.MOV_DT_PRORROGADO)); END IF;
    IF NVL(:OLD.AGN_IN_CODIGO, -1) <> NVL(:NEW.AGN_IN_CODIGO, -1) THEN
      L('AGENTE', TO_CHAR(:OLD.AGN_IN_CODIGO), TO_CHAR(:NEW.AGN_IN_CODIGO)); END IF;
    IF NVL(:OLD.MOV_ST_DOCUMENTO, '#') <> NVL(:NEW.MOV_ST_DOCUMENTO, '#') THEN
      L('DOCUMENTO', :OLD.MOV_ST_DOCUMENTO, :NEW.MOV_ST_DOCUMENTO); END IF;
    IF NVL(:OLD.MOV_CH_SITUACAO, '#') <> NVL(:NEW.MOV_CH_SITUACAO, '#') THEN
      L('SITUACAO', :OLD.MOV_CH_SITUACAO, :NEW.MOV_CH_SITUACAO); END IF;
  END IF;
EXCEPTION WHEN OTHERS THEN NULL;
END CCS_T_GFIN_ALTTIT_MOV;
/

CREATE OR REPLACE TRIGGER MEGA.CCS_T_GFIN_ALTTIT_CRE
  AFTER UPDATE OF CRE_RE_PERCJUROSEFET, CRE_RE_PERCMULTAEFET ON MEGA.FIN_CONTASRECEBER
  FOR EACH ROW
  DISABLE
