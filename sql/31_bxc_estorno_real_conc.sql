CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_ESTORNO (
    P_LOG   IN NUMBER,
    P_USU   IN NUMBER,
    P_LOGIN IN VARCHAR2
) IS
    /* [25/10/2026 - Alexandre Carvalho] O QUE A API CHAMA. Status vira 'E' se desfez; se recusou, continua 'B' com o motivo na mensagem. */
    W_MSG VARCHAR2(1500); W_N NUMBER;
BEGIN
    SELECT COUNT(*) INTO W_N FROM MEGA.CCS_TB_GFIN_BXC_LOG WHERE LOG_IN_CODIGO = P_LOG AND LOG_CH_STATUS = 'B';
    IF W_N = 0 THEN RETURN; END IF;
    SAVEPOINT SP_GFIN_BXC_EST;
    BEGIN
        MEGA.CCS_P_GFIN_BXC_ESTORNO_X(P_LOG, P_USU);
        UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_CH_STATUS = 'E', EST_USU_IN_CODIGO = P_USU, EST_USU_ST_LOGIN = SUBSTR(P_LOGIN, 1, 60), EST_DT = SYSDATE, LOG_ST_MENSAGEM = NULL
         WHERE LOG_IN_CODIGO = P_LOG;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_BXC_EST;
            UPDATE MEGA.CCS_TB_GFIN_BXC_LOG SET LOG_ST_MENSAGEM = SUBSTR('ESTORNO RECUSADO: ' || W_MSG, 1, 1500) WHERE LOG_IN_CODIGO = P_LOG;
    END;
    COMMIT;
END CCS_P_GFIN_BXC_ESTORNO;
