/* =====================================================================================================================
   [26/10/2026 - CRIADO POR ALEXANDRE CARVALHO] CONCILIACAO BANCARIA - IMPORTACAO DO EXTRATO PELO GESTOR (Quality, OCPDB493)
   Desenho: Instrucoes/Gestor_Financeiro_Conciliacao_Bancaria_Importacao.md (diagnostico 26/10).
   O Gestor le o .RET (CNAB 240, segmento E) no navegador, a API grava as linhas aqui (CCS_TB_GFIN_CB_LINHA) e a procedure
   CCS_P_GFIN_CB_IMPORTA grava em MEGA.FIN_CONCILIACAO exatamente como a importacao nativa do Mega:
     CBA_IN_SEQUENCIA = PCK_MEGA.PROXIMASEQUENCIATAB(358) | CBA_CH_TIPO 'I' | CBA_CH_STATUS 'N' | TPD/TPDB do FIN_TIPODOCTOBANCO
     (banco + categoria do lancamento) | ORG = empresa-mae da filial | CBA_ST_NOMEARQUIVO / CBA_DT_DATAARQUIVO / CBA_DT_IMPORTACAO.
   Tudo ou nada por arquivo e conta; a duplicidade e conferida DE NOVO dentro da transacao (multiconjunto por conta: data + natureza +
   valor + historico), com a conta travada (CCS_TB_GFIN_CB_TRAVA, NOWAIT). Mesmo arquivo (SHA-256) na mesma conta = recusado.
   Deploy pelo gateway SOAP: blocos separados por linha "/", DDL sem ";" final. Somente ASCII.
   ===================================================================================================================== */
CREATE TABLE MEGA.CCS_TB_GFIN_CB_ARQUIVO (
  ARQ_IN_CODIGO      NUMBER        NOT NULL,
  ARQ_ST_TOKEN       VARCHAR2(40)  NOT NULL,
  ARQ_ST_HASH        VARCHAR2(64)  NOT NULL,
  ARQ_ST_NOME        VARCHAR2(228) NOT NULL,
  ARQ_DT_ARQUIVO     DATE,
  BAN_IN_NUMERO      NUMBER(3)     NOT NULL,
  ARQ_ST_AGENCIA     VARCHAR2(10),
  ARQ_ST_CONTA       VARCHAR2(20),
  CTA_AGN_IN_CODIGO  NUMBER(7)     NOT NULL,
  FIL_IN_CODIGO      NUMBER(7)     NOT NULL,
  ORG_IN_CODIGO      NUMBER(7),
  ARQ_DT_INI         DATE,
  ARQ_DT_FIM         DATE,
  ARQ_RE_SALDO_INI   NUMBER,
  ARQ_RE_SALDO_FIM   NUMBER,
  ARQ_RE_CREDITOS    NUMBER,
  ARQ_RE_DEBITOS     NUMBER,
  ARQ_IN_QT_LIDAS    NUMBER,
  ARQ_IN_QT_NOVAS    NUMBER,
  ARQ_IN_QT_JA       NUMBER,
  ARQ_IN_QT_FORA     NUMBER,
  ARQ_IN_QT_ERRO     NUMBER,
  ARQ_CH_STATUS      CHAR(1)       NOT NULL,
  ARQ_ST_MENSAGEM    VARCHAR2(1500),
  USU_IN_CODIGO      NUMBER,
  USU_ST_LOGIN       VARCHAR2(60),
  ARQ_DT_INCLUSAO    DATE          DEFAULT SYSDATE NOT NULL,
  ARQ_DT_PROCESSADO  DATE,
  CONSTRAINT PK_CCS_GFIN_CB_ARQUIVO PRIMARY KEY (ARQ_IN_CODIGO),
  CONSTRAINT CK_CCS_GFIN_CB_ARQ_ST CHECK (ARQ_CH_STATUS IN ('P', 'I', 'S', 'X'))
)
/
CREATE UNIQUE INDEX MEGA.UK_CCS_GFIN_CB_ARQ_TOKEN ON MEGA.CCS_TB_GFIN_CB_ARQUIVO (ARQ_ST_TOKEN)
/
CREATE INDEX MEGA.IX_CCS_GFIN_CB_ARQ_HASH ON MEGA.CCS_TB_GFIN_CB_ARQUIVO (CTA_AGN_IN_CODIGO, ARQ_ST_HASH)
/
CREATE SEQUENCE MEGA.CCS_SEQ_GFIN_CB_ARQUIVO START WITH 1 INCREMENT BY 1 NOCACHE
/
CREATE TABLE MEGA.CCS_TB_GFIN_CB_LINHA (
  ARQ_IN_CODIGO      NUMBER        NOT NULL,
  LIN_IN_ORDEM       NUMBER        NOT NULL,
  LIN_ST_SEQARQ      VARCHAR2(20),
  LIN_ST_LOTE_NAT    VARCHAR2(3),
  LIN_DT_DATA        DATE          NOT NULL,
  LIN_CH_NATUREZA    CHAR(1)       NOT NULL,
  LIN_RE_VALOR       NUMBER        NOT NULL,
  LIN_ST_CATEGORIA   VARCHAR2(3),
  LIN_ST_CODHIST     VARCHAR2(4),
  LIN_ST_HISTORICO   VARCHAR2(50),
  LIN_ST_DOCUMENTO   VARCHAR2(20),
  TPD_ST_CODIGO      VARCHAR2(10),
  TPDB_ST_CODIGO     VARCHAR2(20),
  LIN_CH_SITUACAO    CHAR(1)       NOT NULL,
  LIN_ST_MOTIVO      VARCHAR2(300),
  CBA_IN_SEQUENCIA   NUMBER,
  CONSTRAINT PK_CCS_GFIN_CB_LINHA PRIMARY KEY (ARQ_IN_CODIGO, LIN_IN_ORDEM),
  CONSTRAINT CK_CCS_GFIN_CB_LIN_SIT CHECK (LIN_CH_SITUACAO IN ('N', 'J', 'F', 'E', 'I')),
  CONSTRAINT CK_CCS_GFIN_CB_LIN_NAT CHECK (LIN_CH_NATUREZA IN ('D', 'C'))
)
/
CREATE TABLE MEGA.CCS_TB_GFIN_CB_TRAVA (
  CTA_AGN_IN_CODIGO  NUMBER(7)     NOT NULL,
  TRV_DT_ULTIMA      DATE,
  CONSTRAINT PK_CCS_GFIN_CB_TRAVA PRIMARY KEY (CTA_AGN_IN_CODIGO)
)
/
MERGE INTO MEGA.CCS_TB_GFIN_CB_TRAVA D
USING (SELECT DISTINCT C.AGN_IN_CODIGO AGN FROM MEGA.GLO_CONTASFIN C WHERE C.AGN_TAB_IN_CODIGO = 53 AND C.AGN_TAU_ST_CODIGO = 'N' AND C.BAN_IN_NUMERO IS NOT NULL) S
ON (D.CTA_AGN_IN_CODIGO = S.AGN)
WHEN NOT MATCHED THEN INSERT (CTA_AGN_IN_CODIGO) VALUES (S.AGN)
/
MERGE INTO MEGA.CCS_TB_GFIN_PARAM D
USING (SELECT 'CB_DIAS_FORTE' CH, 2 VL, 'CONCILIACAO BANCARIA: DIAS DE DIFERENCA ACEITOS NO NIVEL 2 (COM IDENTIDADE). MEDIDO: 96% DAS CONCILIACOES 1X1 NO MESMO DIA' DS FROM DUAL
       UNION ALL SELECT 'CB_JANELA', 5, 'CONCILIACAO BANCARIA: DIAS MAXIMOS ENTRE BANCO E MEGA PARA SUGERIR (NIVEL 3)' FROM DUAL) S
ON (D.PARAM_ST_CHAVE = S.CH)
WHEN MATCHED THEN UPDATE SET D.PARAM_ST_DESCRICAO = S.DS
WHEN NOT MATCHED THEN INSERT (PARAM_ST_CHAVE, PARAM_RE_VALOR, PARAM_ST_DESCRICAO) VALUES (S.CH, S.VL, S.DS)
/
CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_CB_IMPORTA_X (
    P_ARQ IN NUMBER
) IS
    /* [26/10/2026 - Alexandre Carvalho] NUCLEO DA IMPORTACAO (NAO COMITA). Le CCS_TB_GFIN_CB_ARQUIVO P_ARQ (status P) e as linhas
       N/J dele, refaz a duplicidade com a conta travada e grava em FIN_CONCILIACAO. Linhas: N nova | J ja existia no Mega |
       F tipo marcado para nao importar (FIN_TIPODOCTOBANCO.TPDB_BO_IMPORTAR = N) | E erro (nao entra) | I importada (CBA). */
    C_TAB CONSTANT NUMBER := 53; C_PAD CONSTANT NUMBER := 1;
    A MEGA.CCS_TB_GFIN_CB_ARQUIVO%ROWTYPE;
    W_PAD NUMBER; W_BAN NUMBER; W_ORG NUMBER; W_N NUMBER; W_CBA NUMBER; W_TPD VARCHAR2(10); W_IMP VARCHAR2(1); W_EXIST NUMBER;
    W_NOVAS NUMBER := 0; W_JA NUMBER := 0; W_FORA NUMBER := 0; W_DOC VARCHAR2(20);
    E_OCUPADO EXCEPTION; PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
BEGIN
    SELECT X.* INTO A FROM MEGA.CCS_TB_GFIN_CB_ARQUIVO X WHERE X.ARQ_IN_CODIGO = P_ARQ FOR UPDATE;
    IF A.ARQ_CH_STATUS <> 'P' THEN RAISE_APPLICATION_ERROR(-20110, 'Esta importacao ja foi processada (situacao ' || A.ARQ_CH_STATUS || ').'); END IF;

    -- conta financeira ativa do Mega e banco do arquivo
    BEGIN
        SELECT C.AGN_PAD_IN_CODIGO, C.BAN_IN_NUMERO INTO W_PAD, W_BAN
          FROM MEGA.GLO_CONTASFIN C, MEGA.GLO_AGENTES_ID I
         WHERE C.AGN_TAB_IN_CODIGO = C_TAB AND C.AGN_IN_CODIGO = A.CTA_AGN_IN_CODIGO AND C.AGN_TAU_ST_CODIGO = 'N'
           AND I.AGN_TAB_IN_CODIGO = C.AGN_TAB_IN_CODIGO AND I.AGN_PAD_IN_CODIGO = C.AGN_PAD_IN_CODIGO AND I.AGN_IN_CODIGO = C.AGN_IN_CODIGO
           AND I.AGN_TAU_ST_CODIGO = 'N' AND NVL(I.AGN_CH_STATUS, 'A') = 'A' AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20110, 'Conta financeira ' || A.CTA_AGN_IN_CODIGO || ' nao encontrada ou inativa no Mega.');
    END;
    IF NVL(W_BAN, -1) <> A.BAN_IN_NUMERO THEN
        RAISE_APPLICATION_ERROR(-20110, 'O arquivo e do banco ' || A.BAN_IN_NUMERO || ' e a conta ' || A.CTA_AGN_IN_CODIGO || ' e do banco ' || NVL(TO_CHAR(W_BAN), '(sem banco)') || '.');
    END IF;
    -- empresa = organizacao-mae da filial (200 -> 10, 400 -> 30, 800 -> 20)
    BEGIN
        SELECT O.PAI_ORG_IN_CODIGO INTO W_ORG FROM MEGA.GLO_VW_ORGANIZACAO O
         WHERE O.ORG_TAB_IN_CODIGO = C_TAB AND O.ORG_PAD_IN_CODIGO = C_PAD AND O.ORG_IN_CODIGO = A.FIL_IN_CODIGO AND ROWNUM = 1;
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20110, 'Filial ' || A.FIL_IN_CODIGO || ' nao encontrada no Mega.');
    END;
    IF W_ORG IS NULL THEN RAISE_APPLICATION_ERROR(-20110, 'Filial ' || A.FIL_IN_CODIGO || ' sem empresa no Mega.'); END IF;

    -- uma importacao por conta de cada vez
    BEGIN
        SELECT 1 INTO W_N FROM MEGA.CCS_TB_GFIN_CB_TRAVA T WHERE T.CTA_AGN_IN_CODIGO = A.CTA_AGN_IN_CODIGO FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN INSERT INTO MEGA.CCS_TB_GFIN_CB_TRAVA (CTA_AGN_IN_CODIGO) VALUES (A.CTA_AGN_IN_CODIGO);
        WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20110, 'Outra importacao desta conta esta em andamento. Tente de novo em alguns segundos.');
    END;
    UPDATE MEGA.CCS_TB_GFIN_CB_TRAVA SET TRV_DT_ULTIMA = SYSDATE WHERE CTA_AGN_IN_CODIGO = A.CTA_AGN_IN_CODIGO;

    -- mesmo arquivo ja importado nesta conta
    SELECT COUNT(*) INTO W_N FROM MEGA.CCS_TB_GFIN_CB_ARQUIVO X
     WHERE X.CTA_AGN_IN_CODIGO = A.CTA_AGN_IN_CODIGO AND X.ARQ_ST_HASH = A.ARQ_ST_HASH AND X.ARQ_CH_STATUS = 'I' AND X.ARQ_IN_CODIGO <> P_ARQ;
    IF W_N > 0 THEN RAISE_APPLICATION_ERROR(-20110, 'Este arquivo ja foi importado nesta conta pelo Gestor. Nada novo a gravar.'); END IF;

    FOR L IN (SELECT X.*, ROW_NUMBER() OVER (PARTITION BY X.LIN_DT_DATA, X.LIN_CH_NATUREZA, X.LIN_RE_VALOR, UPPER(TRIM(X.LIN_ST_HISTORICO)) ORDER BY X.LIN_IN_ORDEM) RN
                FROM MEGA.CCS_TB_GFIN_CB_LINHA X WHERE X.ARQ_IN_CODIGO = P_ARQ AND X.LIN_CH_SITUACAO IN ('N', 'J') ORDER BY X.LIN_IN_ORDEM) LOOP
        IF L.LIN_DT_DATA > TRUNC(SYSDATE) + 1 OR L.LIN_DT_DATA < DATE '2015-01-01' THEN
            RAISE_APPLICATION_ERROR(-20110, 'Linha ' || L.LIN_IN_ORDEM || ': data ' || TO_CHAR(L.LIN_DT_DATA, 'DD/MM/YYYY') || ' fora do esperado.');
        END IF;
        IF NVL(L.LIN_RE_VALOR, 0) <= 0 THEN RAISE_APPLICATION_ERROR(-20110, 'Linha ' || L.LIN_IN_ORDEM || ': valor invalido.'); END IF;
        -- quantas linhas iguais a conta ja tem no Mega (fora as que esta importacao acabou de criar)
        SELECT COUNT(*) INTO W_EXIST FROM MEGA.FIN_CONCILIACAO B
         WHERE B.AGN_TAB_IN_CODIGO = C_TAB AND B.AGN_IN_CODIGO = A.CTA_AGN_IN_CODIGO AND B.AGN_TAU_ST_CODIGO = 'N'
           AND B.CBA_DT_DATA = L.LIN_DT_DATA AND B.CBA_CH_NATUREZA = L.LIN_CH_NATUREZA AND B.CBA_RE_VALOR = L.LIN_RE_VALOR
           AND UPPER(TRIM(B.CBA_ST_HISTORICO)) = UPPER(TRIM(L.LIN_ST_HISTORICO))
           AND NOT EXISTS (SELECT 1 FROM MEGA.CCS_TB_GFIN_CB_LINHA Z WHERE Z.ARQ_IN_CODIGO = P_ARQ AND Z.LIN_CH_SITUACAO = 'I' AND Z.CBA_IN_SEQUENCIA = B.CBA_IN_SEQUENCIA);
        IF L.RN <= W_EXIST THEN
            UPDATE MEGA.CCS_TB_GFIN_CB_LINHA SET LIN_CH_SITUACAO = 'J', LIN_ST_MOTIVO = 'Ja estava no Mega (mesma data, natureza, valor e historico)'
             WHERE ARQ_IN_CODIGO = P_ARQ AND LIN_IN_ORDEM = L.LIN_IN_ORDEM;
            W_JA := W_JA + 1;
        ELSE
            BEGIN
                SELECT D.TPD_ST_CODIGO, NVL(D.TPDB_BO_IMPORTAR, 'S') INTO W_TPD, W_IMP FROM MEGA.FIN_TIPODOCTOBANCO D
                 WHERE D.BAN_IN_NUMERO = A.BAN_IN_NUMERO AND D.TPDB_ST_CODIGO = L.LIN_ST_CATEGORIA;
            EXCEPTION WHEN NO_DATA_FOUND THEN
                RAISE_APPLICATION_ERROR(-20110, 'Linha ' || L.LIN_IN_ORDEM || ': codigo ' || L.LIN_ST_CATEGORIA || ' do banco ' || A.BAN_IN_NUMERO || ' sem tipo de documento no Mega (Financeiro > Tipo de documento do banco).');
            END;
            IF W_IMP = 'N' THEN
                UPDATE MEGA.CCS_TB_GFIN_CB_LINHA SET LIN_CH_SITUACAO = 'F', TPD_ST_CODIGO = W_TPD, TPDB_ST_CODIGO = L.LIN_ST_CATEGORIA,
                       LIN_ST_MOTIVO = 'Tipo do banco marcado para nao importar no Mega' WHERE ARQ_IN_CODIGO = P_ARQ AND LIN_IN_ORDEM = L.LIN_IN_ORDEM;
                W_FORA := W_FORA + 1;
            ELSE
                W_CBA := MEGA.PCK_MEGA.PROXIMASEQUENCIATAB(358);
                IF NVL(W_CBA, 0) = 0 THEN RAISE_APPLICATION_ERROR(-20110, 'Falha na numeracao do extrato do Mega (tabela 358).'); END IF;
                W_DOC := SUBSTR(L.LIN_ST_DOCUMENTO, 1, 20);
                INSERT INTO MEGA.FIN_CONCILIACAO
                  (CBA_IN_SEQUENCIA, TPD_ST_CODIGO, TPDB_ST_CODIGO, BAN_IN_NUMERO,
                   ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, FIL_IN_CODIGO,
                   AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO,
                   CBA_DT_DATA, CBA_CH_NATUREZA, CBA_RE_VALOR, CBA_CH_TIPO, CBA_CH_STATUS,
                   CBA_ST_HISTORICO, CBA_ST_DOCUMENTO, CBA_CH_SONUMEROS, CBA_DT_IMPORTACAO, CBA_DT_DATAARQUIVO, CBA_ST_NOMEARQUIVO)
                VALUES
                  (W_CBA, W_TPD, L.LIN_ST_CATEGORIA, A.BAN_IN_NUMERO,
                   C_TAB, C_PAD, W_ORG, 'G', A.FIL_IN_CODIGO,
                   C_TAB, W_PAD, A.CTA_AGN_IN_CODIGO, 'N',
                   L.LIN_DT_DATA, L.LIN_CH_NATUREZA, L.LIN_RE_VALOR, 'I', 'N',
                   SUBSTR(L.LIN_ST_HISTORICO, 1, 50), W_DOC, CASE WHEN REGEXP_LIKE(TRIM(W_DOC), '^[0-9]*$') OR TRIM(W_DOC) IS NULL THEN 'S' ELSE 'N' END,
                   SYSDATE, NVL(A.ARQ_DT_ARQUIVO, SYSDATE), SUBSTR(A.ARQ_ST_NOME, 1, 228));
                UPDATE MEGA.CCS_TB_GFIN_CB_LINHA SET LIN_CH_SITUACAO = 'I', CBA_IN_SEQUENCIA = W_CBA, TPD_ST_CODIGO = W_TPD, TPDB_ST_CODIGO = L.LIN_ST_CATEGORIA, LIN_ST_MOTIVO = NULL
                 WHERE ARQ_IN_CODIGO = P_ARQ AND LIN_IN_ORDEM = L.LIN_IN_ORDEM;
                W_NOVAS := W_NOVAS + 1;
            END IF;
        END IF;
    END LOOP;
    SELECT COUNT(*) INTO W_N FROM MEGA.CCS_TB_GFIN_CB_LINHA X WHERE X.ARQ_IN_CODIGO = P_ARQ AND X.LIN_CH_SITUACAO = 'E';
    UPDATE MEGA.CCS_TB_GFIN_CB_ARQUIVO SET ORG_IN_CODIGO = W_ORG, ARQ_IN_QT_NOVAS = W_NOVAS, ARQ_IN_QT_JA = W_JA, ARQ_IN_QT_FORA = W_FORA, ARQ_IN_QT_ERRO = W_N
     WHERE ARQ_IN_CODIGO = P_ARQ;
END CCS_P_GFIN_CB_IMPORTA_X;
