MERGE INTO MEGA.CCS_TB_GFIN_PARAM P USING (
  SELECT 'BXC_TOLERANCIA' CHAVE, 1 VALOR, 'BXC: DIFERENCA RESIDUAL ABSORVIDA COMO JUROS/DESCONTO (R$)' DESCR FROM DUAL UNION ALL
  SELECT 'BXC_TETO_ROBO', 50000, 'BXC: VALOR MAXIMO POR BAIXA FEITA PELO ROBO SEM CLIQUE (R$)' FROM DUAL UNION ALL
  SELECT 'BXC_ROBO_ATIVO', 0, 'BXC: ROBO LIGADO (1) / DESLIGADO (0)' FROM DUAL UNION ALL
  SELECT 'BXC_USU_ROBO', 0, 'BXC: USUARIO DO MEGA EM NOME DE QUEM O ROBO BAIXA (0 = NAO DEFINIDO)' FROM DUAL UNION ALL
  SELECT 'BXC_JANELA_DIAS', 5, 'BXC: DISTANCIA MAXIMA EM DIAS ENTRE DATA DO BANCO E LANCAMENTO/VENCIMENTO' FROM DUAL UNION ALL
  SELECT 'BXC_TIT_DIAS_ANTES', 90, 'BXC: TITULOS CANDIDATOS - VENCIMENTO ATE N DIAS ANTES DA DATA DO BANCO' FROM DUAL UNION ALL
  SELECT 'BXC_TIT_DIAS_DEPOIS', 30, 'BXC: TITULOS CANDIDATOS - VENCIMENTO ATE N DIAS DEPOIS DA DATA DO BANCO' FROM DUAL UNION ALL
  SELECT 'BXC_MAX_TITULOS', 6, 'BXC: MAXIMO DE TITULOS NUM SO PAGAMENTO/RECEBIMENTO (SOMA)' FROM DUAL UNION ALL
  SELECT 'BXC_CLA_CP_JUROS', 627, 'BXC: CLASSE FINANCEIRA DOS JUROS PAGOS (CONTAS A PAGAR)' FROM DUAL UNION ALL
  SELECT 'BXC_CLA_CP_DESC', 566, 'BXC: CLASSE FINANCEIRA DOS DESCONTOS OBTIDOS (CONTAS A PAGAR)' FROM DUAL UNION ALL
  SELECT 'BXC_CLA_CR_JUROS', 68, 'BXC: CLASSE FINANCEIRA DOS JUROS RECEBIDOS (CONTAS A RECEBER)' FROM DUAL UNION ALL
  SELECT 'BXC_CLA_CR_MULTA', 68, 'BXC: CLASSE FINANCEIRA DAS MULTAS RECEBIDAS (CONTAS A RECEBER)' FROM DUAL UNION ALL
  SELECT 'BXC_CLA_CR_DESC', 468, 'BXC: CLASSE FINANCEIRA DOS DESCONTOS CONCEDIDOS (CONTAS A RECEBER)' FROM DUAL UNION ALL
  SELECT 'BXC_EXIGE_COMPROV', 0, 'BXC: EXIGIR COMPROVANTE EM PIX/TED ACIMA DO VALOR BXC_COMPROV_ACIMA (1/0)' FROM DUAL UNION ALL
  SELECT 'BXC_COMPROV_ACIMA', 0, 'BXC: VALOR A PARTIR DO QUAL O COMPROVANTE E EXIGIDO (R$)' FROM DUAL
) X ON (P.PARAM_ST_CHAVE = X.CHAVE)
WHEN NOT MATCHED THEN INSERT (PARAM_ST_CHAVE, PARAM_RE_VALOR, PARAM_ST_DESCRICAO, PARAM_DT_ALTERACAO, PARAM_IN_USU, PARAM_ST_USU)
VALUES (X.CHAVE, X.VALOR, X.DESCR, SYSDATE, 0, 'INSTALACAO 25/10/2026')
