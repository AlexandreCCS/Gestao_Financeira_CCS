CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BXC_REAL_X (
    P_LOG  IN NUMBER,
    P_ORG  IN NUMBER,
    P_CBA  IN NUMBER,
    P_DEP  IN NUMBER,
    P_USU  IN NUMBER,
    P_HIST IN VARCHAR2
) IS
    /* [25/10/2026 - Alexandre Carvalho] MOVIMENTO REAL: uma linha do extrato que nao tem titulo (tarifa, IOF, IR, rendimento) vira
       lancamento avulso do Mega (710 saida / 711 entrada: mov da conta + contraparte AVISTA) conciliado com a linha. NAO COMITA.
       Pegada: ORG 30 / ACAOM 6449670 (Gestor_Financeiro_Baixa_e_Conciliacao_Fase2.md secao 6). */
    C_ORG_TAB CONSTANT NUMBER := 53; C_ORG_PAD CONSTANT NUMBER := 1; C_ORG_TAU CONSTANT VARCHAR2(3) := 'G'; C_MOV_TAB CONSTANT NUMBER := 352;
    B MEGA.FIN_CONCILIACAO%ROWTYPE;
    D MEGA.CCS_TB_GFIN_BXC_DEPARA%ROWTYPE;
    K MEGA.CCS_TB_GFIN_BXC_CONTA%ROWTYPE;
    W_SAIDA BOOLEAN; W_NAT_FIN VARCHAR2(1); W_NAT_CT VARCHAR2(1); W_TPD_CT VARCHAR2(10); W_TPD_FIN VARCHAR2(10);
    W_CTA_PAD NUMBER; W_AGN NUMBER; W_AGN_PAD NUMBER; W_AGN_TAU VARCHAR2(3); W_TAU_PREF VARCHAR2(1); W_NOME VARCHAR2(100);
    W_HUS NUMBER; W_DATA DATE; W_SEQ NUMBER; W_ACAOM NUMBER; W_FIN NUMBER; W_CT NUMBER; W_CON NUMBER; W_DOC VARCHAR2(30); W_HIST VARCHAR2(500);
    W_TAC VARCHAR2(10); W_CS NUMBER; W_VAL NUMBER;
    E_OCUPADO EXCEPTION; PRAGMA EXCEPTION_INIT(E_OCUPADO, -54);
    PROCEDURE CONT(P_ACAO NUMBER, P_TREF VARCHAR2, O_TAC OUT VARCHAR2, O_SEQ OUT NUMBER) IS
    BEGIN
        SELECT CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA INTO O_TAC, O_SEQ FROM MEGA.CCS_TB_GFIN_BXC_CONT WHERE ACAO_IN_CODIGO = P_ACAO AND TREF_ST_CODIGO = NVL(P_TREF, '-');
    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Contabilizacao nao mapeada para a acao ' || P_ACAO || ' / ' || NVL(P_TREF, 'mov financeiro') || '.');
    END;
    PROCEDURE ATUALIZA(P_LANC NUMBER, P_ATAB NUMBER, P_APAD NUMBER, P_AGN NUMBER, P_ATAU VARCHAR2, P_TREF VARCHAR2, P_NAT VARCHAR2) IS
    BEGIN
        FIN_PCK_MOVIMENTO.REFAZENDOFIN := 'S'; FIN_PCK_MOVIMENTO.REFAZENDOORC := 'N'; FIN_PCK_MOVIMENTO.ORCREFAZ := 0;
        FIN_PCK_MOVIMENTO.P_ATUALIZAMOVIMENTO(
            PMOV_DT_DATADOCTO => W_DATA, PMOV_DT_ENTRADA => W_DATA, PMOV_DT_VENCTO => W_DATA, PMOV_DT_PRORROGADO => W_DATA, PMOV_DT_ORCAMENTO => W_DATA,
            PMOV_TAB_IN_CODIGO => C_MOV_TAB, PMOV_SEQ_IN_CODIGO => W_SEQ, PMOV_IN_NUMLANCTO => P_LANC,
            PBAN_IN_NUMERO => 0, PIND_IN_CODIGOMOE => 0, PORG_IN_CODIGO => P_ORG, PFIL_IN_CODIGO => K.FIL_IN_CODIGO,
            PAGN_TAB_IN_CODIGO => P_ATAB, PAGN_PAD_IN_CODIGO => P_APAD, PAGN_IN_CODIGO => P_AGN, PAGN_TAU_ST_CODIGO => P_ATAU,
            PMOV_BO_PREVISAO => 'N', PTREF_ST_CODIGO => P_TREF, PMOV_CH_ORIGEM => 'M', PMOV_CH_NATUREZA => P_NAT,
            PMOV_RE_VALOR => W_VAL, PMOV_RE_VALORMOE => W_VAL, PCRI_IN_CODIGO => -1, PFATOR => 1);
    END;
    PROCEDURE INS_MOV(P_LANC NUMBER, P_TPD VARCHAR2, P_NAT VARCHAR2, P_TREF VARCHAR2, P_ATAB NUMBER, P_APAD NUMBER, P_AGN NUMBER, P_ATAU VARCHAR2, P_FIN VARCHAR2) IS
    BEGIN
        CONT(D.ACAO_IN_CODIGO, P_TREF, W_TAC, W_CS);
        INSERT INTO MEGA.FIN_MOVIMENTO
        ( ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, MOV_TAB_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO,
          CONT_TAB_IN_CODIGO, CONT_PAD_IN_CODIGO, CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA, ACAO_TAB_IN_CODIGO, ACAO_PAD_IN_CODIGO, ACAO_IN_CODIGO, ACAOM_IN_SEQUENCIA, IND_IN_CODIGOMOE,
          AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO, TPD_ST_CODIGO, MOV_ST_DOCUMENTO, MOV_CH_SONUMEROS,
          MOV_DT_DATADOCTO, MOV_DT_ENTRADA, MOV_DT_VENCTO, MOV_DT_PRORROGADO, MOV_DT_ORCAMENTO, MOV_RE_VALOR, MOV_RE_VALORCRE, MOV_RE_VALORDEB, MOV_CH_NATUREZA,
          MOV_CH_STATUSSALDO, MOV_CH_SITUACAO, MOV_CH_STATUSMOV, MOV_BO_PREVISAO, MOV_DT_DATAINC, MOV_DT_DATAALT, MOV_CH_STATUSBXREF, USU_IN_INCLUSAO, USU_IN_ALTERACAO,
          MOV_RE_VALORMOE, MOV_RE_VALORCREMOE, MOV_RE_VALORDEBMOE, IND_IN_CODIGOIND, MOV_RE_COTACAOMOE, TREF_ST_CODIGO, MOV_CH_ORIGEM, MOV_BO_APROVADOADM, MOV_BO_TITRECONHECIDO, MOV_BO_PAGLIBTESOUR,
          HIS_TAB_IN_CODIGO, HIS_PAD_IN_CODIGO, HIS_IN_REDUZIDO, MOV_CH_CONCILIADO, FIL_IN_CODIGO, MOV_ST_HBKSTATUS, HUS_IN_SEQUENCIA, MOV_BO_BXCHDEVOL, MOV_RE_VALORMOEDA, MOV_ST_COMPLHIST, MOV_BO_SALDOZERADO, MOV_CH_SITDESCDUPL, MOV_RE_SALDOCPACRE )
        VALUES
        ( C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_MOV_TAB, W_SEQ, P_LANC,
          40, 1, W_TAC, W_CS, 55, 1, D.ACAO_IN_CODIGO, W_ACAOM, 0,
          P_ATAB, P_APAD, P_AGN, P_ATAU, P_TPD, W_DOC, 'S',
          W_DATA, W_DATA, W_DATA, W_DATA, W_DATA, W_VAL, CASE WHEN P_NAT = 'C' THEN W_VAL ELSE 0 END, CASE WHEN P_NAT = 'D' THEN W_VAL ELSE 0 END, P_NAT,
          'N', 'N', 'A', 'N', SYSDATE, SYSDATE, 'N', P_USU, P_USU,
          W_VAL, CASE WHEN P_NAT = 'C' THEN W_VAL ELSE 0 END, CASE WHEN P_NAT = 'D' THEN W_VAL ELSE 0 END, 0, 1, P_TREF, 'M', 'S', 'S', 'N',
          CASE WHEN P_FIN = 'S' THEN 0 END, CASE WHEN P_FIN = 'S' THEN 0 END, CASE WHEN P_FIN = 'S' THEN 0 END, 'N', K.FIL_IN_CODIGO, 'NO', W_HUS, 'N', 0, W_HIST, 'N', 'N', 0 );
    END;
