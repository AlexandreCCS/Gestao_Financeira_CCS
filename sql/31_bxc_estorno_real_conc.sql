    EXCEPTION WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Conta financeira ' || P_CTA || ' nao encontrada.');
    END;
    SELECT MIN(H.HUS_IN_SEQUENCIA) INTO W_HUS FROM MEGA.GLO_HIERARQUIAUSUARIO H WHERE H.SIS_IN_CODIGO = 14 AND H.GRU_IN_CODIGO = P_USU;
    IF W_HUS IS NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Usuario ' || P_USU || ' sem hierarquia no Mov. Financeiro do Mega para conciliar.'); END IF;
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := REGEXP_SUBSTR(P_MOVS, '[^;]+', 1, W_N); EXIT WHEN W_ITEM IS NULL;
        SEQS(W_N) := TO_NUMBER(REGEXP_SUBSTR(W_ITEM, '[^:]+', 1, 1)); LANCS(W_N) := TO_NUMBER(REGEXP_SUBSTR(W_ITEM, '[^:]+', 1, 2));
        DECLARE M MEGA.FIN_MOVIMENTO%ROWTYPE;
        BEGIN
            SELECT X.* INTO M FROM MEGA.FIN_MOVIMENTO X
             WHERE X.ORG_TAB_IN_CODIGO = C_ORG_TAB AND X.ORG_PAD_IN_CODIGO = C_ORG_PAD AND X.ORG_IN_CODIGO = P_ORG AND X.ORG_TAU_ST_CODIGO = C_ORG_TAU
               AND X.MOV_TAB_IN_CODIGO = C_MOV_TAB AND X.MOV_SEQ_IN_CODIGO = SEQS(W_N) AND X.MOV_IN_NUMLANCTO = LANCS(W_N) FOR UPDATE NOWAIT;
            IF M.AGN_IN_CODIGO <> P_CTA OR M.AGN_TAU_ST_CODIGO <> 'N' THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || LANCS(W_N) || ' nao e desta conta.'); END IF;
            IF NVL(M.MOV_CH_SITUACAO, 'N') = 'C' OR NVL(M.MOV_BO_PREVISAO, 'N') <> 'N' THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || LANCS(W_N) || ' cancelado ou de previsao.'); END IF;
            IF NVL(M.MOV_CH_CONCILIADO, 'N') = 'S' OR M.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || LANCS(W_N) || ' ja esta conciliado.'); END IF;
            IF W_NAT_M IS NULL THEN W_NAT_M := M.MOV_CH_NATUREZA; ELSIF W_NAT_M <> M.MOV_CH_NATUREZA THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamentos com naturezas diferentes no mesmo lote.'); END IF;
            W_SOMA_M := W_SOMA_M + NVL(M.MOV_RE_VALOR, 0); W_FIL := NVL(W_FIL, M.FIL_IN_CODIGO);
            W_MAIOR := GREATEST(NVL(W_MAIOR, TRUNC(M.MOV_DT_DATADOCTO)), TRUNC(M.MOV_DT_DATADOCTO)); W_MENOR := LEAST(NVL(W_MENOR, TRUNC(M.MOV_DT_DATADOCTO)), TRUNC(M.MOV_DT_DATADOCTO));
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || LANCS(W_N) || ' nao encontrado no Mega.');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Lancamento ' || LANCS(W_N) || ' em uso por outro usuario no Mega.');
        END;
        W_LISTA := W_LISTA || CASE WHEN W_LISTA IS NULL THEN '' ELSE ',' END || LANCS(W_N);
    END LOOP;
    W_N := 0;
    LOOP
        W_N := W_N + 1; W_ITEM := REGEXP_SUBSTR(P_CBAS, '[^,]+', 1, W_N); EXIT WHEN W_ITEM IS NULL;
        CBAS(W_N) := TO_NUMBER(TRIM(W_ITEM));
        DECLARE B MEGA.FIN_CONCILIACAO%ROWTYPE;
        BEGIN
            SELECT X.* INTO B FROM MEGA.FIN_CONCILIACAO X WHERE X.CBA_IN_SEQUENCIA = CBAS(W_N) FOR UPDATE NOWAIT;
            IF B.AGN_IN_CODIGO <> P_CTA THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato e de outra conta.'); END IF;
            IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato ja conciliada.'); END IF;
            IF W_NAT_B IS NULL THEN W_NAT_B := B.CBA_CH_NATUREZA; ELSIF W_NAT_B <> B.CBA_CH_NATUREZA THEN RAISE_APPLICATION_ERROR(-20100, 'Linhas do extrato com naturezas diferentes no mesmo lote.'); END IF;
            W_SOMA_B := W_SOMA_B + NVL(B.CBA_RE_VALOR, 0);
            W_MAIOR := GREATEST(W_MAIOR, TRUNC(B.CBA_DT_DATA)); W_MENOR := LEAST(W_MENOR, TRUNC(B.CBA_DT_DATA));
        EXCEPTION
            WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato nao existe no Mega.');
            WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || CBAS(W_N) || ' do extrato em uso por outro usuario no Mega.');
        END;
    END LOOP;
    IF LANCS.COUNT = 0 OR CBAS.COUNT = 0 THEN RAISE_APPLICATION_ERROR(-20100, 'Informe lancamentos e linhas do extrato.'); END IF;
    IF W_NAT_M = W_NAT_B THEN RAISE_APPLICATION_ERROR(-20100, 'Natureza nao confere: saida no banco pede lancamento de saida no Mega (e entrada, entrada).'); END IF;
    IF ABS(W_SOMA_M - W_SOMA_B) >= 0.005 THEN RAISE_APPLICATION_ERROR(-20100, 'Soma dos lancamentos (' || TO_CHAR(W_SOMA_M, 'FM999G999G990D00') || ') diferente da soma do banco (' || TO_CHAR(W_SOMA_B, 'FM999G999G990D00') || ').'); END IF;
    IF W_MAIOR - W_MENOR > W_JANELA THEN RAISE_APPLICATION_ERROR(-20100, 'Datas do lote com mais de ' || W_JANELA || ' dias de distancia.'); END IF;
    BEGIN
        MEGA.FIN_PCK_CONCILIACAOBANC.P_VALIDACONCILIACAO(P_ORG, W_FIL, W_MENOR);
    EXCEPTION WHEN OTHERS THEN RAISE_APPLICATION_ERROR(-20100, 'Periodo de conciliacao encerrado no Mega para a empresa ' || W_FIL || '.');
    END;
    SELECT MEGA.FIN_SEQ_CONCILIACAO.NEXTVAL INTO W_CON FROM DUAL;
    INSERT INTO MEGA.FIN_CONCILIAMOVIMENTO ( CON_IN_SEQUENCIAL, ORG_TAB_IN_CODIGO, ORG_PAD_IN_CODIGO, ORG_IN_CODIGO, ORG_TAU_ST_CODIGO, AGN_TAB_IN_CODIGO, AGN_PAD_IN_CODIGO, AGN_IN_CODIGO, AGN_TAU_ST_CODIGO, CON_CH_TIPO, CON_DT_CONCILIACAO, CON_DT_MAIORDATA, USU_IN_CODIGO, CON_RE_VALOR )
    VALUES ( W_CON, C_ORG_TAB, C_ORG_PAD, P_ORG, C_ORG_TAU, C_ORG_TAB, W_CTA_PAD, P_CTA, 'N', 'A', SYSDATE, W_MAIOR, P_USU, W_SOMA_M );
    FOR I IN 1 .. LANCS.COUNT LOOP
        UPDATE MEGA.FIN_MOVIMENTO SET MOV_CH_CONCILIADO = 'S', CON_IN_SEQUENCIAL = W_CON
         WHERE ORG_IN_CODIGO = P_ORG AND MOV_TAB_IN_CODIGO = C_MOV_TAB AND MOV_SEQ_IN_CODIGO = SEQS(I) AND MOV_IN_NUMLANCTO = LANCS(I);
    END LOOP;
    FOR I IN 1 .. CBAS.COUNT LOOP
        UPDATE MEGA.FIN_CONCILIACAO SET CBA_CH_STATUS = 'S', CON_IN_SEQUENCIAL = W_CON WHERE CBA_IN_SEQUENCIA = CBAS(I);
    END LOOP;
    W_N := LANCS.COUNT;
    UPDATE MEGA.CCS_TB_GFIN_BXC_LOG
       SET FIL_IN_CODIGO = W_FIL, LOG_DT_BANCO = W_MAIOR, LOG_RE_VALOR_BANCO = W_SOMA_B, LOG_RE_VALOR_TITULOS = W_SOMA_M, LOG_IN_QT_TITULOS = W_N,
           CON_IN_SEQUENCIAL = W_CON, LOG_ST_MOVS = SUBSTR(W_LISTA, 1, 2000)
     WHERE LOG_IN_CODIGO = P_LOG;
END CCS_P_GFIN_BXC_CONC_X;
