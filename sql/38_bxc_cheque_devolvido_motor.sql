/* =====================================================================================================================
   [03/11/2026 - Alexandre Carvalho] GESTOR FINANCEIRO - BAIXAR E CONCILIAR (QUALITY): CHEQUE RECEBIDO DEVOLVIDO - MOTOR.
   Processo (decisao do Alexandre, 03/11): linha CHRD do extrato ("DEV CH NAC|DEP <banco> <n. cheque> <alinea>") casada com UM cheque de
   MEGA.CUS_FIN_CHEQUESCRE (banco + numero + valor). Numa transacao:
     1) lanca a acao 971 "Estorno Devolucao de Cheque recebido" e concilia com a linha (CCS_P_GFIN_BXC_REAL_X, de-para CHRD deste arquivo);
     2) reabre as parcelas que o cheque baixou: exclui a baixa 706 dele (DOCTEDP na carteira + CREDITO BXCRE no cliente). O trigger
        CCS_T_MOV_CHQ registra o estorno no cheque e devolve o saldo dele; o saldo da parcela e recalculado pela rotina do Mega
        (FIN_PCK_UTILIDADE.F_ATUALIZASALDODOCUMENTO, a mesma do CCS_P_AJUSTA_ESTORNO_CHQ);
     3) marca o cheque D com a alinea (BXC_CHD_MARCA); 4) avisa a equipe por WhatsApp (BXC_CHD_WHATS, lista BXC_CHD_ZAP_LISTA, tarefa 9997).
   A nova baixa da parcela e do usuario, como hoje. "Desfazer" (CCS_P_GFIN_BXC_ESTORNO) desfaz so a 971 e o status do cheque.
   Pegada da 971 copiada do lancamento manual de teste (ORG 10 / ACAOM 96036553): CHRD na conta (MVFIN 27, rateio 9/2) + DEBITO AVISTA no
   agente 1000 tau O (MVFIN 27, classe/CC dos parametros BXC_CHD_CLASSE/CCUSTO, projeto 9/2).
   Pre-requisitos: sql/37 (parametros) e sql/31 de 03/11 (REAL_X aceita 971; ESTORNO devolve o cheque). SO ASCII. Blocos separados por "/".
   Diagnostico: agenda_02_11_a_08_11/mm45g41_01..27.
   ===================================================================================================================== */
MERGE INTO MEGA.CCS_TB_GFIN_BXC_CONT C USING (
  SELECT 971 ACAO, '-' TREF, 'MVFIN' TAC, 27 SEQ, 'cheque devolvido: mov da conta (CHRD) [03/11/2026]' OBS FROM DUAL UNION ALL
  SELECT 971, 'AVISTA', 'MVFIN', 27, 'cheque devolvido: contraparte a vista [03/11/2026]' FROM DUAL
) X ON (C.ACAO_IN_CODIGO = X.ACAO AND C.TREF_ST_CODIGO = X.TREF)
WHEN NOT MATCHED THEN INSERT (ACAO_IN_CODIGO, TREF_ST_CODIGO, CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA, CONT_ST_OBS) VALUES (X.ACAO, X.TREF, X.TAC, X.SEQ, X.OBS)
/
