          CLA_TAB_IN_CODIGO, CLA_PAD_IN_CODIGO, CLA_IDE_ST_CODIGO, CLA_IN_REDUZIDO, LCL_CH_NATUREZA, LCC_IN_NUMERO, LPR_IN_NUMERO,
