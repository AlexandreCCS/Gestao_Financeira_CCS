CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_BAIXA_CPA (
    P_TOKEN   IN VARCHAR2,
    P_ORG     IN NUMBER,
    P_SEQ     IN NUMBER,
    P_LANCTO  IN NUMBER,
    P_CTA     IN NUMBER,
    P_DATA    IN DATE,
    P_VALOR   IN NUMBER,
    P_USU     IN NUMBER,
    P_LOGIN   IN VARCHAR2,
    P_HIST    IN VARCHAR2 DEFAULT NULL,
    P_DOCBCO  IN VARCHAR2 DEFAULT NULL,
    P_ARQ     IN VARCHAR2 DEFAULT NULL,
    P_SIMULAR IN VARCHAR2 DEFAULT 'N'
) IS
    /* [21/09/2026 - Alexandre Carvalho] O QUE A API DO GESTOR CHAMA. NUNCA PROPAGA ERRO DE REGRA: GRAVA O RESULTADO NO LOG
       (B = BAIXADO | S = SIMULADO OK, NADA GRAVADO | X = RECUSADO/ERRO) E A API LE O LOG PELO TOKEN. */
    W_SEQ_BX NUMBER; W_FIN NUMBER; W_BX NUMBER; W_ACAOM NUMBER; W_ACAO_BX NUMBER; W_SALDO NUMBER; W_ZER VARCHAR2(1);
    W_AGN NUMBER; W_DOC VARCHAR2(30); W_PARC VARCHAR2(10); W_FIL NUMBER;
    W_ST CHAR(1); W_MSG VARCHAR2(1500);
BEGIN
    SAVEPOINT SP_GFIN_BAIXA;
    BEGIN
        MEGA.CCS_P_GFIN_BAIXA_CPA_X(P_ORG, P_SEQ, P_LANCTO, P_CTA, P_DATA, P_VALOR, P_USU, P_HIST,
            W_SEQ_BX, W_FIN, W_BX, W_ACAOM, W_ACAO_BX, W_SALDO, W_ZER, W_AGN, W_DOC, W_PARC, W_FIL);
        IF NVL(P_SIMULAR, 'N') = 'S' THEN
            ROLLBACK TO SP_GFIN_BAIXA;
            W_ST := 'S'; W_MSG := 'Simulacao sem erro. Nada foi gravado.';
        ELSE
            W_ST := 'B'; W_MSG := NULL;
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_BAIXA;
            W_ST := 'X';
    END;
    INSERT INTO MEGA.CCS_TB_GFIN_BAIXA_LOG
    ( LOG_IN_CODIGO, LOG_ST_TOKEN, LOG_CH_TIPO, LOG_CH_STATUS, ORG_IN_CODIGO, MOV_SEQ_IN_CODIGO, MOV_IN_NUMLANCTO,
      AGN_IN_CODIGO, MOV_ST_DOCUMENTO, MOV_ST_PARCELA, FIL_IN_CODIGO, CTA_AGN_IN_CODIGO, LOG_DT_BAIXA, LOG_RE_VALOR,
      LOG_RE_SALDO_ANT, LOG_CH_ZERADO_ANT, BX_MOV_SEQ_IN_CODIGO, LANCTO_FIN, LANCTO_BX, ACAOM_IN_SEQUENCIA, ACAO_BX_IN_CODIGO,
      USU_IN_CODIGO, USU_ST_LOGIN, LOG_DT_INCLUSAO, EXT_ST_HISTORICO, EXT_ST_DOCUMENTO, EXT_ST_ARQUIVO, LOG_ST_MENSAGEM )
    VALUES
    ( MEGA.CCS_SEQ_GFIN_BAIXA_LOG.NEXTVAL, P_TOKEN, 'P', W_ST, P_ORG, P_SEQ, P_LANCTO,
      W_AGN, W_DOC, W_PARC, W_FIL, P_CTA, TRUNC(P_DATA), ROUND(P_VALOR, 2),
      W_SALDO, W_ZER, CASE WHEN W_ST = 'B' THEN W_SEQ_BX END, CASE WHEN W_ST = 'B' THEN W_FIN END, CASE WHEN W_ST = 'B' THEN W_BX END,
      CASE WHEN W_ST = 'B' THEN W_ACAOM END, W_ACAO_BX,
      P_USU, SUBSTR(P_LOGIN, 1, 60), SYSDATE, SUBSTR(P_HIST, 1, 120), SUBSTR(P_DOCBCO, 1, 60), SUBSTR(P_ARQ, 1, 120), W_MSG );
    COMMIT;
END CCS_P_GFIN_BAIXA_CPA;
