CREATE OR REPLACE PROCEDURE MEGA.CCS_P_GFIN_DESCONCILIA (
    P_LOG   IN NUMBER,
    P_USU   IN NUMBER,
    P_LOGIN IN VARCHAR2
) IS
    /* [21/09/2026 - Alexandre Carvalho] O QUE A API CHAMA PARA DESFAZER. STATUS VIRA 'D'; SE RECUSAR, CONTINUA 'C' COM O MOTIVO NA MENSAGEM. */
    R MEGA.CCS_TB_GFIN_CONC_LOG%ROWTYPE;
    W_MSG VARCHAR2(1500);
BEGIN
    BEGIN
        SELECT * INTO R FROM MEGA.CCS_TB_GFIN_CONC_LOG WHERE LOG_IN_CODIGO = P_LOG AND LOG_CH_STATUS = 'C' FOR UPDATE NOWAIT;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RETURN;
    END;
    SAVEPOINT SP_GFIN_DESCONC;
    BEGIN
        MEGA.CCS_P_GFIN_DESCONCILIA_X(R.ORG_IN_CODIGO, R.MOV_SEQ_IN_CODIGO, R.MOV_IN_NUMLANCTO, R.CBA_IN_SEQUENCIA, R.CON_IN_SEQUENCIAL);
        UPDATE MEGA.CCS_TB_GFIN_CONC_LOG
           SET LOG_CH_STATUS = 'D', DES_USU_IN_CODIGO = P_USU, DES_USU_ST_LOGIN = SUBSTR(P_LOGIN, 1, 60), DES_DT = SYSDATE, LOG_ST_MENSAGEM = NULL
         WHERE LOG_IN_CODIGO = P_LOG;
    EXCEPTION
        WHEN OTHERS THEN
            W_MSG := SUBSTR(REGEXP_REPLACE(SQLERRM, '^ORA-20100: ', ''), 1, 1500);
            ROLLBACK TO SP_GFIN_DESCONC;
            UPDATE MEGA.CCS_TB_GFIN_CONC_LOG SET LOG_ST_MENSAGEM = SUBSTR('NAO DESFEZ: ' || W_MSG, 1, 1500) WHERE LOG_IN_CODIGO = P_LOG;
    END;
    COMMIT;
END CCS_P_GFIN_DESCONCILIA;
