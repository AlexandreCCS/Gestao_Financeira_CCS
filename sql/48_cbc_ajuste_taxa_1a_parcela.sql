/* =====================================================================================================================
   [27/11/2026 - Alexandre Carvalho] GESTOR FINANCEIRO - CONCILIACAO DE CARTAO (QUALITY): AJUSTE DA TAXA ANTECIPADA NA 1a PARCELA ("Tx 1o parc.")
   No inicio das lojas (vendas de 09/07 a 08/09/2026) a baixa automatica lancou a taxa (956) de TODAS as parcelas na 1a parcela. As parcelas
   2+ dessas vendas foram baixadas pelo BRUTO no Itau da loja, mas a Rede deposita o LIQUIDO (bruto - MDR da parcela): o deposito nao fecha.
   Decisoes do Alexandre (27/11): ajuste AUTOMATICO (sem flag na tela por enquanto), acao 977 NAO contabil (ACAO_BO_CONTAB = 'N'), saida da
   conta da loja para a ponte 27619 (REDE), complemento "Ajuste feito para correcao das taxas de cartao na primeira parcela"; vale so para as
   vendas da lista (CCS_TB_GFIN_CBC_TX1: criterio taxa1/valor1 = n. parcelas x 2,19% + 401/32962 + 401/30353) e ate 05/03/2027
   (ultima parcela 401/32550-006 vence 27/02/2027, sabado). Exemplo aprovado: log 4085 (NF 32370 3/3, 3,02, linha 78928).
   - UMA 977 por deposito (soma das parcelas elegiveis), conciliada junto com os movimentos 706 existentes contra a linha do extrato:
     entradas (706) - saida 977 = linha. Log tipo A com LOG_ST_MOVS_CONC: o Desfazer padrao (CCS_P_GFIN_BXC_ESTORNO_X) desfaz tudo.
   - Pegada da 712 do Gestor (sql/43): TRANSFD na loja (nat C, classe 522 D) + TRANSFC na ponte (TREF TRANSF, nat D, classe 523 C), CC 215.
   SO ASCII. Blocos separados por "/".
   ===================================================================================================================== */
CREATE TABLE MEGA.CCS_TB_GFIN_CBC_TX1 (
    FIL_IN_CODIGO     NUMBER        NOT NULL,
    AGN_IN_CODIGO     NUMBER        NOT NULL,
    MOV_ST_DOCUMENTO  VARCHAR2(30)  NOT NULL,
    TX1_IN_PARCELAS   NUMBER,
    TX1_RE_TAXA       NUMBER,
    TX1_RE_VALOR1     NUMBER,
    TX1_DT_EMISSAO    DATE,
    TX1_DT_ULT_VENC   DATE,
    TX1_ST_OBS        VARCHAR2(200),
    TX1_DT_INCLUSAO   DATE DEFAULT SYSDATE,
    CONSTRAINT PK_CCS_TB_GFIN_CBC_TX1 PRIMARY KEY (FIL_IN_CODIGO, AGN_IN_CODIGO, MOV_ST_DOCUMENTO)
)
/
MERGE INTO MEGA.CCS_TB_GFIN_PARAM P USING (
  SELECT 'CBC_TX1_ATE' K, 20270305 V, 'Ajuste da taxa antecipada na 1a parcela (977): vale para depositos ate esta data (AAAAMMDD)' D FROM DUAL UNION ALL
  SELECT 'CBC_TX1_PONTE', 27619, 'Ajuste da taxa antecipada na 1a parcela (977): conta ponte de destino (REDE)' FROM DUAL
) X ON (P.PARAM_ST_CHAVE = X.K)
WHEN NOT MATCHED THEN INSERT (PARAM_ST_CHAVE, PARAM_RE_VALOR, PARAM_ST_DESCRICAO, PARAM_DT_ALTERACAO, PARAM_ST_USU) VALUES (X.K, X.V, X.D, SYSDATE, 'CCS 27/11/2026')
/
MERGE INTO MEGA.CCS_TB_GFIN_BXC_CONT C USING (
  SELECT 977 ACAO, '-' TREF, 'MVFIN' TAC, 11 SEQ, 'ajuste taxa 1a parcela: TRANSFD na conta da loja [27/11/2026]' OBS FROM DUAL UNION ALL
  SELECT 977, 'TRANSF', 'MVFIN', 12, 'ajuste taxa 1a parcela: TRANSFC na ponte [27/11/2026]' FROM DUAL
) X ON (C.ACAO_IN_CODIGO = X.ACAO AND C.TREF_ST_CODIGO = X.TREF)
WHEN NOT MATCHED THEN INSERT (ACAO_IN_CODIGO, TREF_ST_CODIGO, CONT_TAC_ST_CODIGO, CONT_CON_IN_SEQUENCIA, CONT_ST_OBS) VALUES (X.ACAO, X.TREF, X.TAC, X.SEQ, X.OBS)
/
