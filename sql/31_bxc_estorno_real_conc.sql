        WHEN E_OCUPADO THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato em uso por outro usuario no Mega.');
    END;
    IF NVL(B.CBA_CH_STATUS, 'N') = 'S' OR B.CON_IN_SEQUENCIAL IS NOT NULL THEN RAISE_APPLICATION_ERROR(-20100, 'Linha ' || P_CBA || ' do extrato ja esta conciliada.'); END IF;
